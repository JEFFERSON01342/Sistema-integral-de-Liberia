SELECT DISTINCT ON (e.id_empresa, lower(trim(e.departamento)))
       e.id_empresa, trim(e.departamento)
FROM public.empleados AS e
WHERE nullif(trim(e.departamento), '') IS NOT NULL
ORDER BY e.id_empresa, lower(trim(e.departamento)), trim(e.departamento);

INSERT INTO public.puestos_empresa (id_empresa, id_departamento, nombre)
SELECT DISTINCT ON (e.id_empresa, COALESCE(d.id_departamento, 0), lower(trim(e.puesto)))
       e.id_empresa, d.id_departamento, trim(e.puesto)
FROM public.empleados AS e
LEFT JOIN public.departamentos_empresa AS d
  ON d.id_empresa = e.id_empresa
 AND lower(trim(d.nombre)) = lower(trim(e.departamento))
WHERE nullif(trim(e.puesto), '') IS NOT NULL
ORDER BY e.id_empresa, COALESCE(d.id_departamento, 0), lower(trim(e.puesto)), trim(e.puesto);

UPDATE public.empleados AS e
SET id_departamento = d.id_departamento
FROM public.departamentos_empresa AS d
WHERE d.id_empresa = e.id_empresa
  AND lower(trim(d.nombre)) = lower(trim(e.departamento));

UPDATE public.empleados AS e
SET id_puesto = p.id_puesto
FROM public.puestos_empresa AS p
WHERE p.id_empresa = e.id_empresa
  AND lower(trim(p.nombre)) = lower(trim(e.puesto))
  AND p.id_departamento IS NOT DISTINCT FROM e.id_departamento;

