CREATE OR REPLACE FUNCTION public.sincronizar_texto_empleado_catalogo()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_puesto public.puestos_empresa%ROWTYPE;
  v_departamento public.departamentos_empresa%ROWTYPE;
BEGIN
  IF NEW.id_puesto IS NOT NULL THEN
    SELECT * INTO v_puesto
    FROM public.puestos_empresa
    WHERE id_empresa = NEW.id_empresa AND id_puesto = NEW.id_puesto;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'El puesto seleccionado no pertenece a esta empresa.';
    END IF;
    IF NEW.id_departamento IS NOT NULL
       AND NEW.id_departamento IS DISTINCT FROM v_puesto.id_departamento THEN
      RAISE EXCEPTION 'El puesto seleccionado pertenece a otro departamento.';
    END IF;
    NEW.id_departamento := v_puesto.id_departamento;
    NEW.puesto := v_puesto.nombre;
  ELSE
    NEW.puesto := NULL;
  END IF;

  IF NEW.id_departamento IS NOT NULL THEN
    SELECT * INTO v_departamento
    FROM public.departamentos_empresa
    WHERE id_empresa = NEW.id_empresa
      AND id_departamento = NEW.id_departamento;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'El departamento seleccionado no pertenece a esta empresa.';
    END IF;
    NEW.departamento := v_departamento.nombre;
  ELSE
    NEW.departamento := NULL;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.sincronizar_texto_empleado_catalogo()
  FROM PUBLIC, anon, authenticated, service_role;

CREATE TRIGGER empleados_sincronizar_catalogo
BEFORE INSERT OR UPDATE OF id_departamento, id_puesto ON public.empleados
FOR EACH ROW EXECUTE FUNCTION public.sincronizar_texto_empleado_catalogo();

CREATE OR REPLACE FUNCTION public.aplicar_rol_puesto_empleado(
  p_id_empleado bigint,
  p_id_perfil uuid,
  p_rol_nuevo text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor uuid := (SELECT auth.uid());
  v_actor_rol text;
  v_empleado record;
  v_perfil record;
BEGIN
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para cambiar el rol de acceso.';
  END IF;

  SELECT e.id_empresa, e.id_sucursal
  INTO v_empleado
  FROM public.empleados AS e
  WHERE e.id_empleado = p_id_empleado
    AND e.id_perfil = p_id_perfil;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'El empleado no tiene vinculada esa cuenta.';
  END IF;
  IF NOT (SELECT public.puede_gestionar_rrhh(v_empleado.id_empresa, v_empleado.id_sucursal)) THEN
    RAISE EXCEPTION 'No tienes permiso para cambiar el rol de este empleado.';
  END IF;

  SELECT p.rol INTO v_actor_rol
  FROM public.perfiles AS p
  WHERE p.id = v_actor AND p.activo;
  IF v_actor_rol NOT IN ('admin', 'superadmin') THEN
    RAISE EXCEPTION 'Solo un administrador puede asignar el rol del puesto.';
  END IF;
  IF p_rol_nuevo IS NULL THEN
    RAISE EXCEPTION 'Este puesto no tiene acceso al sistema. Desvincula la cuenta antes de asignarlo.';
  END IF;
  IF p_rol_nuevo NOT IN ('admin', 'gerente', 'contador', 'cajero', 'despacho', 'bodega') THEN
    RAISE EXCEPTION 'El rol configurado en el puesto no es válido.';
  END IF;
  IF p_rol_nuevo = 'admin' AND v_actor_rol <> 'superadmin' THEN
    RAISE EXCEPTION 'Solo un superadministrador puede asignar el rol administrador.';
  END IF;
  IF p_id_perfil = v_actor THEN
    RAISE EXCEPTION 'No puedes cambiar tu propio rol desde el puesto de empleado.';
  END IF;

  SELECT p.rol, p.id_empresa, p.id_sucursal, p.activo
  INTO v_perfil
  FROM public.perfiles AS p
  WHERE p.id = p_id_perfil
  FOR UPDATE;
  IF NOT FOUND OR NOT v_perfil.activo
     OR v_perfil.id_empresa IS DISTINCT FROM v_empleado.id_empresa
     OR v_perfil.id_sucursal IS DISTINCT FROM v_empleado.id_sucursal THEN
    RAISE EXCEPTION 'La cuenta debe estar activa y pertenecer a la misma empresa y sucursal.';
  END IF;
  IF v_perfil.rol = 'superadmin' THEN
    RAISE EXCEPTION 'No se puede cambiar el rol de un superadministrador.';
  END IF;
  IF v_perfil.rol = 'admin' AND v_actor_rol <> 'superadmin' THEN
    RAISE EXCEPTION 'Solo un superadministrador puede cambiar una cuenta administradora.';
  END IF;

  IF v_perfil.rol IS DISTINCT FROM p_rol_nuevo THEN
    UPDATE public.perfiles SET rol = p_rol_nuevo WHERE id = p_id_perfil;
    INSERT INTO public.auditoria_roles_puesto (
      id_empresa, id_sucursal, id_empleado, id_perfil,
      rol_anterior, rol_nuevo, cambiado_por
    )
    VALUES (
      v_empleado.id_empresa, v_empleado.id_sucursal,
      p_id_empleado, p_id_perfil,
      v_perfil.rol, p_rol_nuevo, v_actor
    );
    IF v_empleado.id_sucursal IS NOT NULL THEN
      INSERT INTO public.auditoria_asignaciones_sucursal (
        id_empresa, id_sucursal, id_usuario, realizado_por, rol_anterior, rol_nuevo
      )
      VALUES (
        v_empleado.id_empresa, v_empleado.id_sucursal, p_id_perfil,
        v_actor, v_perfil.rol, p_rol_nuevo
      );
    END IF;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.aplicar_rol_puesto_empleado(bigint, uuid, text)
  FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.actualizar_rol_al_cambiar_puesto()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_rol text;
BEGIN
  IF NEW.id_puesto IS NOT DISTINCT FROM OLD.id_puesto
     OR NEW.id_perfil IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT rol_acceso INTO v_rol
  FROM public.puestos_empresa
  WHERE id_empresa = NEW.id_empresa AND id_puesto = NEW.id_puesto;
  PERFORM public.aplicar_rol_puesto_empleado(
    NEW.id_empleado, NEW.id_perfil, v_rol
  );
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.actualizar_rol_al_cambiar_puesto()
  FROM PUBLIC, anon, authenticated, service_role;

CREATE TRIGGER empleados_actualizar_rol_al_cambiar_puesto
AFTER UPDATE OF id_puesto ON public.empleados
FOR EACH ROW EXECUTE FUNCTION public.actualizar_rol_al_cambiar_puesto();

CREATE OR REPLACE FUNCTION public.sincronizar_empleados_tras_cambio_catalogo()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF TG_TABLE_NAME = 'departamentos_empresa' THEN
    UPDATE public.empleados
    SET id_departamento = id_departamento
    WHERE id_empresa = NEW.id_empresa
      AND id_departamento = NEW.id_departamento;
  ELSE
    UPDATE public.empleados
    SET id_departamento = NEW.id_departamento,
        id_puesto = id_puesto
    WHERE id_empresa = NEW.id_empresa
      AND id_puesto = NEW.id_puesto;
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.sincronizar_empleados_tras_cambio_catalogo()
  FROM PUBLIC, anon, authenticated, service_role;

