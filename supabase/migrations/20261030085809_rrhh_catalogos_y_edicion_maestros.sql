CREATE OR REPLACE FUNCTION public.actualizar_roles_empleados_puesto_catalogo()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_empleado record;
BEGIN
  IF OLD.rol_acceso IS NOT DISTINCT FROM NEW.rol_acceso THEN
    RETURN NEW;
  END IF;
  FOR v_empleado IN
    SELECT e.id_empleado, e.id_perfil
    FROM public.empleados AS e
    WHERE e.id_empresa = NEW.id_empresa
      AND e.id_puesto = NEW.id_puesto
      AND e.id_perfil IS NOT NULL
  LOOP
    PERFORM public.aplicar_rol_puesto_empleado(
      v_empleado.id_empleado, v_empleado.id_perfil, NEW.rol_acceso
    );
  END LOOP;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.actualizar_roles_empleados_puesto_catalogo()
  FROM PUBLIC, anon, authenticated, service_role;

CREATE TRIGGER puestos_empresa_aplicar_rol
AFTER UPDATE OF rol_acceso ON public.puestos_empresa
FOR EACH ROW EXECUTE FUNCTION public.actualizar_roles_empleados_puesto_catalogo();

CREATE OR REPLACE FUNCTION public.actualizar_rol_al_vincular_perfil(
  p_id_empleado bigint,
  p_id_perfil uuid
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_rol text;
BEGIN
  IF p_id_perfil IS NULL THEN
    UPDATE public.empleados
    SET id_perfil = NULL
    WHERE id_empleado = p_id_empleado;
    IF NOT FOUND THEN RAISE EXCEPTION 'El empleado no existe.'; END IF;
    RETURN;
  END IF;

  SELECT p.rol_acceso INTO v_rol
  FROM public.empleados AS e
  JOIN public.puestos_empresa AS p
    ON p.id_empresa = e.id_empresa AND p.id_puesto = e.id_puesto
  WHERE e.id_empleado = p_id_empleado;
  IF NOT FOUND OR v_rol IS NULL THEN
    RAISE EXCEPTION 'Asigna primero un puesto con rol de acceso. Los puestos de apoyo no requieren cuenta.';
  END IF;

  UPDATE public.empleados
  SET id_perfil = p_id_perfil
  WHERE id_empleado = p_id_empleado;
  IF NOT FOUND THEN RAISE EXCEPTION 'El empleado no existe.'; END IF;

  PERFORM public.aplicar_rol_puesto_empleado(
    p_id_empleado, p_id_perfil, v_rol
  );
END;
$$;

REVOKE ALL ON FUNCTION public.actualizar_rol_al_vincular_perfil(bigint, uuid)
  FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.vincular_perfil_empleado(
  p_id_empleado bigint,
  p_id_perfil uuid
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_empresa integer;
  v_sucursal integer;
  v_perfil record;
BEGIN
  SELECT e.id_empresa, e.id_sucursal
  INTO v_empresa, v_sucursal
  FROM public.empleados AS e
  WHERE e.id_empleado = p_id_empleado;
  IF v_empresa IS NULL THEN RAISE EXCEPTION 'El empleado no existe.'; END IF;
  IF NOT (SELECT public.puede_gestionar_rrhh(v_empresa, v_sucursal)) THEN
    RAISE EXCEPTION 'No tienes permiso para vincular perfiles en esta empresa/sucursal.';
  END IF;

  IF p_id_perfil IS NOT NULL THEN
    SELECT p.id_empresa, p.id_sucursal, p.rol, p.activo
    INTO v_perfil
    FROM public.perfiles AS p
    WHERE p.id = p_id_perfil;
    IF NOT FOUND OR NOT v_perfil.activo
       OR v_perfil.id_empresa IS DISTINCT FROM v_empresa
       OR v_perfil.id_sucursal IS DISTINCT FROM v_sucursal
       OR v_perfil.rol NOT IN ('superadmin', 'admin', 'gerente', 'contador', 'cajero', 'despacho', 'bodega') THEN
      RAISE EXCEPTION 'El perfil debe ser una cuenta activa de personal de la misma empresa y sucursal.';
    END IF;
  END IF;

  PERFORM public.actualizar_rol_al_vincular_perfil(p_id_empleado, p_id_perfil);
END;
$$;

REVOKE ALL ON FUNCTION public.vincular_perfil_empleado(bigint, uuid)
