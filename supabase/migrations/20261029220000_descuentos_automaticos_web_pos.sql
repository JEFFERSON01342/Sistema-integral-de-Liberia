  FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.listar_promociones_web(p_id_empresa integer)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_resultado jsonb;
BEGIN
  SELECT COALESCE(jsonb_agg(to_jsonb(x) ORDER BY x.fecha_inicio NULLS FIRST, x.id), '[]'::jsonb)
  INTO v_resultado
  FROM (
    SELECT d.id, d.nombre, d.descripcion, d.tipo, d.valor, d.fecha_inicio,
      d.fecha_fin, d.aplica_a, d.temporada, d.banner_texto,
      COALESCE((
        SELECT jsonb_agg(dp.id_producto ORDER BY dp.id_producto)
        FROM public.descuento_productos dp
        WHERE dp.id_empresa = d.id_empresa AND dp.id_descuento = d.id
      ), '[]'::jsonb) AS productos,
      COALESCE((
        SELECT jsonb_agg(jsonb_build_object(
          'id_categoria', dc.id_categoria, 'categoria_nombre', c.nombre
        ) ORDER BY c.nombre)
        FROM public.descuento_categorias dc
        JOIN public.categorias_producto c
          ON c.id_empresa = dc.id_empresa AND c.id_categoria = dc.id_categoria
        WHERE dc.id_empresa = d.id_empresa AND dc.id_descuento = d.id
      ), '[]'::jsonb) AS categorias
    FROM public.descuentos d
    WHERE d.id_empresa = p_id_empresa
      AND d.activo
      AND d.codigo_descuento IS NULL
      AND (d.fecha_inicio IS NULL OR d.fecha_inicio <= (now() AT TIME ZONE 'America/Managua')::date)
      AND (d.fecha_fin IS NULL OR d.fecha_fin >= (now() AT TIME ZONE 'America/Managua')::date)
      AND (d.usos_maximos IS NULL OR (
        SELECT count(*) FROM public.aplicaciones_descuento a
        WHERE a.id_empresa = d.id_empresa AND a.id_descuento = d.id
      ) < d.usos_maximos)
  ) x;
  RETURN v_resultado;
END;
$$;

REVOKE ALL ON FUNCTION public.listar_promociones_web(integer)
  FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.listar_promociones_web(integer) TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.crear_descuento_automatico(
  p_datos jsonb,
  p_ids_productos bigint[] DEFAULT ARRAY[]::bigint[],
  p_ids_categorias bigint[] DEFAULT ARRAY[]::bigint[]
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_empresa integer;
  v_id_descuento bigint;
  v_aplica text;
  v_tipo text;
  v_valor numeric(14,2);
BEGIN
  v_empresa := NULLIF(p_datos ->> 'id_empresa', '')::integer;
  IF v_empresa IS NULL
     OR (SELECT auth.uid()) IS NULL
     OR NOT (SELECT public.puede_administrar_empresa(v_empresa)) THEN
    RAISE EXCEPTION 'No tienes permiso para crear promociones en esta empresa.';
  END IF;
  IF p_datos IS NULL OR jsonb_typeof(p_datos) <> 'object' THEN
    RAISE EXCEPTION 'Los datos de la promoción no son válidos.';
  END IF;
  v_aplica := COALESCE(p_datos ->> 'aplica_a', 'todos');
  v_tipo := p_datos ->> 'tipo';
  v_valor := (p_datos ->> 'valor')::numeric(14,2);
  IF v_tipo NOT IN ('porcentaje', 'monto')
     OR v_valor IS NULL
     OR (v_tipo = 'porcentaje' AND (v_valor <= 0 OR v_valor >= 100))
     OR (v_tipo = 'monto' AND v_valor <= 0) THEN
    RAISE EXCEPTION 'El tipo o valor del descuento no es válido.';
  END IF;
  IF v_aplica NOT IN ('todos', 'categorias', 'productos') THEN
    RAISE EXCEPTION 'El alcance de la promoción no es válido.';
  END IF;
  IF (v_aplica = 'productos' AND COALESCE(cardinality(p_ids_productos), 0) = 0)
     OR (v_aplica = 'categorias' AND COALESCE(cardinality(p_ids_categorias), 0) = 0)
     OR (v_aplica <> 'productos' AND COALESCE(cardinality(p_ids_productos), 0) > 0)
     OR (v_aplica <> 'categorias' AND COALESCE(cardinality(p_ids_categorias), 0) > 0) THEN
    RAISE EXCEPTION 'Selecciona productos o categorías que coincidan con el alcance.';
  END IF;
  IF p_datos ->> 'fecha_inicio' IS NOT NULL AND p_datos ->> 'fecha_fin' IS NOT NULL
     AND (p_datos ->> 'fecha_fin')::date < (p_datos ->> 'fecha_inicio')::date THEN
    RAISE EXCEPTION 'La fecha de fin no puede ser anterior a la de inicio.';
  END IF;
  IF p_datos ->> 'usos_maximos' IS NOT NULL
     AND ((p_datos ->> 'usos_maximos')::integer <= 0) THEN
    RAISE EXCEPTION 'El límite de usos debe ser mayor que cero.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM unnest(COALESCE(p_ids_productos, ARRAY[]::bigint[])) x(id)
    LEFT JOIN public.productos p
      ON p.id_empresa = v_empresa AND p.id_producto = x.id AND p.activo
    WHERE p.id_producto IS NULL
  ) OR EXISTS (
    SELECT 1 FROM unnest(COALESCE(p_ids_categorias, ARRAY[]::bigint[])) x(id)
    LEFT JOIN public.categorias_producto c
      ON c.id_empresa = v_empresa AND c.id_categoria = x.id AND c.activa
    WHERE c.id_categoria IS NULL
  ) THEN
    RAISE EXCEPTION 'Hay productos o categorías que no existen o están inactivos.';
  END IF;

  INSERT INTO public.descuentos (
    id_empresa, nombre, descripcion, tipo, valor, fecha_inicio, fecha_fin,
    aplica_a, temporada, banner_texto, usos_maximos, activo
  )
  VALUES (
    v_empresa,
    trim(COALESCE(p_datos ->> 'nombre', '')),
    NULLIF(trim(COALESCE(p_datos ->> 'descripcion', '')), ''),
    v_tipo, v_valor,
    NULLIF(p_datos ->> 'fecha_inicio', '')::date,
    NULLIF(p_datos ->> 'fecha_fin', '')::date,
    v_aplica,
    NULLIF(trim(COALESCE(p_datos ->> 'temporada', '')), ''),
    NULLIF(trim(COALESCE(p_datos ->> 'banner_texto', '')), ''),
    NULLIF(p_datos ->> 'usos_maximos', '')::integer,
    true
  )
  RETURNING id INTO v_id_descuento;

  IF v_aplica = 'productos' THEN
    INSERT INTO public.descuento_productos (id_empresa, id_descuento, id_producto)
    SELECT v_empresa, v_id_descuento, x.id
    FROM unnest(p_ids_productos) x(id)
    ON CONFLICT DO NOTHING;
  ELSIF v_aplica = 'categorias' THEN
    INSERT INTO public.descuento_categorias (id_empresa, id_descuento, id_categoria)
    SELECT v_empresa, v_id_descuento, x.id
    FROM unnest(p_ids_categorias) x(id)
    ON CONFLICT DO NOTHING;
  END IF;
  RETURN v_id_descuento;
END;
$$;

REVOKE ALL ON FUNCTION public.crear_descuento_automatico(jsonb, bigint[], bigint[])
  FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.crear_descuento_automatico(jsonb, bigint[], bigint[])
  TO authenticated;


CREATE OR REPLACE FUNCTION public.registrar_venta_pos(
  p_id_sesion bigint,
  p_items jsonb,
  p_pagos jsonb,
  p_idempotencia_key text,
  p_id_cliente bigint DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_caja bigint;
  v_estado_sesion text;
  v_zona text;
  v_fecha date;
  v_ahora timestamptz := clock_timestamp();
  v_periodo bigint;
  v_items jsonb;
  v_pagos jsonb;
  v_huella text;
  v_venta_existente bigint;
  v_huella_existente text;
  v_id_bodega bigint;
  v_id_ubicacion bigint;
  v_id_venta bigint;
  v_id_detalle bigint;
  v_id_comprobante bigint;
  v_id_cuenta_ingreso bigint;
  v_id_cuenta_costo bigint;
  v_id_cuenta_inventario bigint;
  v_id_cuenta_pago bigint;
  v_id_cuenta_descuento bigint;
  v_id_producto bigint;
  v_id_descuento bigint;
  v_cantidad numeric(14,3);
  v_precio numeric(14,2);
  v_precio_lista numeric(14,2);
  v_descuento_linea numeric(14,2);
  v_descuento_total numeric(14,2) := 0;
  v_promocion record;
  v_subtotal_linea numeric(14,2);
  v_costo_linea numeric(14,2);
  v_cantidad_pendiente numeric(14,3);
  v_consumo numeric(14,3);
  v_costo_unitario numeric(14,4);
  v_costo_consumo numeric(14,2);
  v_subtotal numeric(14,2) := 0;
  v_costo_total numeric(14,2) := 0;
  v_total_pagos numeric(14,2) := 0;
  v_total_efectivo numeric(14,2) := 0;
  v_efectivo_recibido numeric(14,2);
  v_cambio numeric(14,2);
  v_metodos integer;
  v_metodo_venta text;
  v_linea integer := 0;
  v_linea_asiento integer := 0;
  v_clave text := trim(COALESCE(p_idempotencia_key, ''));
  v_producto record;
  v_capa record;
  v_pago record;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para registrar una venta.';
  END IF;

  IF char_length(v_clave) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'La clave de idempotencia es obligatoria y debe tener entre 1 y 128 caracteres.';
  END IF;

  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 50 THEN
    RAISE EXCEPTION 'La venta debe incluir entre 1 y 50 productos.';
  END IF;

  IF jsonb_typeof(p_pagos) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_pagos) NOT BETWEEN 1 AND 3 THEN
    RAISE EXCEPTION 'La venta debe incluir entre uno y tres medios de pago.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(p_items) AS e(value)
    WHERE jsonb_typeof(e.value) <> 'object'
       OR NOT (e.value ? 'id_producto')
       OR NOT (e.value ? 'cantidad')
       OR jsonb_typeof(e.value -> 'id_producto') <> 'number'
       OR jsonb_typeof(e.value -> 'cantidad') <> 'number'
  ) THEN
    RAISE EXCEPTION 'Cada producto debe incluir id_producto y cantidad numéricos.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric)
    WHERE i.id_producto IS NULL OR i.cantidad IS NULL
       OR i.cantidad <= 0 OR i.cantidad <> round(i.cantidad, 3)
  ) THEN
    RAISE EXCEPTION 'Cada producto debe tener cantidad positiva con máximo tres decimales.';
  END IF;

  IF EXISTS (
    SELECT i.id_producto
    FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric)
    GROUP BY i.id_producto
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Combina las cantidades repetidas de un mismo producto.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(p_pagos) AS e(value)
    WHERE jsonb_typeof(e.value) <> 'object'
       OR NOT (e.value ? 'metodo_pago')
       OR NOT (e.value ? 'monto')
       OR jsonb_typeof(e.value -> 'metodo_pago') <> 'string'
       OR jsonb_typeof(e.value -> 'monto') <> 'number'
       OR (
         e.value ? 'efectivo_recibido'
         AND jsonb_typeof(e.value -> 'efectivo_recibido') NOT IN ('number', 'null')
       )
  ) THEN
    RAISE EXCEPTION 'Cada pago debe incluir metodo_pago y monto; el efectivo puede incluir efectivo_recibido.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_pagos) AS p(
      metodo_pago text, monto numeric, efectivo_recibido numeric
    )
    WHERE p.metodo_pago NOT IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA')
       OR p.monto IS NULL OR p.monto <= 0 OR p.monto <> round(p.monto, 2)
       OR (
         p.metodo_pago = 'EFECTIVO'
         AND (
           p.efectivo_recibido IS NULL
           OR p.efectivo_recibido < p.monto
           OR p.efectivo_recibido <> round(p.efectivo_recibido, 2)
         )
       )
       OR (p.metodo_pago <> 'EFECTIVO' AND p.efectivo_recibido IS NOT NULL)
  ) THEN
    RAISE EXCEPTION 'Verifica los montos de pago y el efectivo recibido.';
  END IF;

  IF EXISTS (
    SELECT p.metodo_pago
    FROM jsonb_to_recordset(p_pagos) AS p(
      metodo_pago text, monto numeric, efectivo_recibido numeric
    )
    GROUP BY p.metodo_pago
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Combina los montos cuando uses el mismo medio de pago más de una vez.';
  END IF;

  SELECT jsonb_agg(
    jsonb_build_object('id_producto', i.id_producto, 'cantidad', i.cantidad)
    ORDER BY i.id_producto
  )
  INTO v_items
  FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric);

  SELECT jsonb_agg(
    jsonb_build_object(
      'metodo_pago', p.metodo_pago,
      'monto', p.monto,
      'efectivo_recibido', p.efectivo_recibido
    )
    ORDER BY p.metodo_pago
  ), COALESCE(sum(p.monto), 0)::numeric(14,2),
     count(*)::integer,
     COALESCE(sum(p.monto) FILTER (WHERE p.metodo_pago = 'EFECTIVO'), 0)::numeric(14,2),
     COALESCE(sum(p.efectivo_recibido) FILTER (WHERE p.metodo_pago = 'EFECTIVO'), 0)::numeric(14,2)
  INTO v_pagos, v_total_pagos, v_metodos, v_total_efectivo, v_efectivo_recibido
  FROM jsonb_to_recordset(p_pagos) AS p(
    metodo_pago text, monto numeric, efectivo_recibido numeric
  );

  v_huella := md5(
    v_items::text || '|' || v_pagos::text || '|' ||
    p_id_sesion::text || '|' || COALESCE(p_id_cliente::text, 'NULL')
  );

  SELECT sc.id_empresa, sc.id_sucursal, sc.id_caja, sc.estado, sc.zona_horaria
  INTO v_empresa, v_sucursal, v_caja, v_estado_sesion, v_zona
  FROM public.sesiones_caja AS sc
  WHERE sc.id_sesion = p_id_sesion
  FOR UPDATE;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'La sesión de caja no existe.';
  END IF;

  IF NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, false)) THEN
    RAISE EXCEPTION 'No tienes permiso para registrar ventas en esta sucursal.';
  END IF;

  SELECT v.id_venta, v.huella_solicitud
  INTO v_venta_existente, v_huella_existente
  FROM public.ventas AS v
  WHERE v.id_empresa = v_empresa
    AND v.idempotencia_key = v_clave;

  IF v_venta_existente IS NOT NULL THEN
    IF v_huella_existente <> v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó con datos diferentes.';
    END IF;
    RETURN v_venta_existente;
  END IF;

  IF v_estado_sesion <> 'ABIERTA' THEN
    RAISE EXCEPTION 'No se puede vender con una sesión de caja cerrada.';
  END IF;

  v_fecha := (v_ahora AT TIME ZONE v_zona)::date;

  PERFORM d.id
  FROM public.descuentos d
  WHERE d.id_empresa = v_empresa AND d.activo AND d.codigo_descuento IS NULL
  ORDER BY d.id
  FOR UPDATE;

  SELECT pc.id_periodo INTO v_periodo
  FROM public.periodos_contables AS pc
  WHERE pc.id_empresa = v_empresa
    AND v_fecha BETWEEN pc.fecha_inicio AND pc.fecha_fin
    AND pc.estado = 'ABIERTO'
  FOR SHARE;

  IF v_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha real de la venta.';
  END IF;

  IF p_id_cliente IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.clientes AS c
    WHERE c.id_empresa = v_empresa AND c.id_cliente = p_id_cliente AND c.activo
  ) THEN
    RAISE EXCEPTION 'El cliente no existe, está inactivo o pertenece a otra empresa.';
  END IF;

  SELECT b.id_bodega INTO v_id_bodega
  FROM public.bodegas AS b
  WHERE b.id_empresa = v_empresa AND b.id_sucursal = v_sucursal AND b.activa
  ORDER BY b.id_bodega LIMIT 1;

  SELECT u.id_ubicacion INTO v_id_ubicacion
  FROM public.ubicaciones_bodega AS u
  WHERE u.id_empresa = v_empresa AND u.id_sucursal = v_sucursal
    AND u.id_bodega = v_id_bodega AND u.tipo_area = 'PICKING' AND u.activa
  ORDER BY u.id_ubicacion LIMIT 1;

  IF v_id_bodega IS NULL OR v_id_ubicacion IS NULL THEN
    RAISE EXCEPTION 'No existe una ubicación activa de ventas/exhibición.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
    LEFT JOIN public.productos AS p
      ON p.id_empresa = v_empresa AND p.id_producto = i.id_producto
    WHERE p.id_producto IS NULL OR NOT p.activo
  ) THEN
    RAISE EXCEPTION 'Uno o más productos no existen, están inactivos o pertenecen a otra empresa.';
  END IF;

  PERFORM p.id_producto
  FROM public.productos AS p
  JOIN jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
    ON i.id_producto = p.id_producto
  WHERE p.id_empresa = v_empresa
  ORDER BY p.id_producto
  FOR UPDATE OF p;

  FOR v_producto IN
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta, i.cantidad
    FROM jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
    JOIN public.productos AS p
      ON p.id_empresa = v_empresa AND p.id_producto = i.id_producto
    ORDER BY p.id_producto
  LOOP
    SELECT COALESCE(sum(cf.cantidad_disponible), 0)
    INTO v_cantidad_pendiente
    FROM public.capas_inventario_fifo AS cf
    WHERE cf.id_empresa = v_empresa AND cf.id_sucursal = v_sucursal
      AND cf.id_ubicacion = v_id_ubicacion AND cf.id_producto = v_producto.id_producto;

    IF v_cantidad_pendiente < v_producto.cantidad THEN
      RAISE EXCEPTION 'Existencias insuficientes para % (disponible %, solicitado %).',
        v_producto.sku, v_cantidad_pendiente, v_producto.cantidad;
    END IF;

    v_precio_lista := v_producto.precio_venta;
    v_precio := v_precio_lista;
    SELECT promo.* INTO v_promocion
    FROM public._mejor_descuento_producto(v_empresa, v_producto.id_producto, v_fecha) promo;
    IF FOUND THEN
      v_precio := v_promocion.precio_final;
        v_descuento_linea :=
          round(v_producto.cantidad * v_precio_lista, 2)
          - round(v_producto.cantidad * v_precio, 2);
        v_descuento_total := v_descuento_total + v_descuento_linea;
    END IF;
    v_subtotal := v_subtotal + round(v_producto.cantidad * v_precio, 2);
  END LOOP;

  IF v_subtotal <= 0 OR v_total_pagos <> v_subtotal THEN
    RAISE EXCEPTION 'Los pagos (%) deben cubrir exactamente el total de la venta (%).',
      v_total_pagos, v_subtotal;
  END IF;

  v_efectivo_recibido := CASE
    WHEN v_total_efectivo = 0 THEN NULL
    ELSE v_efectivo_recibido
  END;
  v_cambio := CASE
    WHEN v_total_efectivo = 0 THEN NULL
    ELSE v_efectivo_recibido - v_total_efectivo
  END;

  SELECT CASE WHEN count(*) = 1 THEN min(p.metodo_pago) ELSE 'MIXTO' END
  INTO v_metodo_venta
  FROM jsonb_to_recordset(v_pagos) AS p(
    metodo_pago text, monto numeric, efectivo_recibido numeric
  );

  INSERT INTO public.ventas (
    id_empresa, id_sucursal, id_caja, id_sesion, id_cliente,
    fecha_operativa, registrada_en, metodo_pago, subtotal, impuesto, total, total_descuento,
    efectivo_recibido, cambio, costo_total_fifo, idempotencia_key,
    huella_solicitud, registrada_por
  )
  VALUES (
    v_empresa, v_sucursal, v_caja, p_id_sesion, p_id_cliente,
    v_fecha, v_ahora, v_metodo_venta, v_subtotal, 0, v_subtotal, v_descuento_total,
    v_efectivo_recibido, v_cambio, 0, v_clave, v_huella, v_usuario
  )
  RETURNING id_venta INTO v_id_venta;

  v_subtotal := 0;

  FOR v_producto IN
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta, i.cantidad
    FROM jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
    JOIN public.productos AS p
      ON p.id_empresa = v_empresa AND p.id_producto = i.id_producto
    ORDER BY p.id_producto
  LOOP
    v_linea := v_linea + 1;
    v_id_producto := v_producto.id_producto;
    v_cantidad := v_producto.cantidad;
    v_precio_lista := v_producto.precio_venta;
    v_precio := v_precio_lista;
    v_id_descuento := NULL;
    SELECT promo.* INTO v_promocion
    FROM public._mejor_descuento_producto(v_empresa, v_id_producto, v_fecha) promo;
    IF FOUND THEN
      v_precio := v_promocion.precio_final;
      v_id_descuento := v_promocion.id_descuento;
    ELSE
      v_descuento_linea := 0;
    END IF;
    v_subtotal_linea := round(v_cantidad * v_precio, 2);
    IF v_id_descuento IS NOT NULL THEN
      v_descuento_linea :=
        round(v_cantidad * v_precio_lista, 2) - v_subtotal_linea;
      IF v_descuento_linea <= 0 THEN
        v_id_descuento := NULL;
        v_descuento_linea := 0;
      END IF;
    END IF;
    v_costo_linea := 0;

    INSERT INTO public.detalle_ventas (
      id_empresa, id_venta, id_producto, numero_linea, sku_snapshot,
      nombre_snapshot, cantidad, precio_unitario, subtotal_linea, costo_fifo,
      precio_lista_unitario, descuento_unitario, descuento_linea,
      id_descuento, nombre_descuento_snapshot
    )
    VALUES (
      v_empresa, v_id_venta, v_id_producto, v_linea, v_producto.sku,
      v_producto.nombre, v_cantidad, v_precio, v_subtotal_linea, 0,
      v_precio_lista,
      v_precio_lista - v_precio,
      v_descuento_linea,
      v_id_descuento,
      CASE WHEN v_id_descuento IS NOT NULL THEN v_promocion.nombre END
    )
    RETURNING id_detalle INTO v_id_detalle;

    v_cantidad_pendiente := v_cantidad;

    FOR v_capa IN
      SELECT cf.id_capa, cf.cantidad_disponible, cf.costo_unitario
      FROM public.capas_inventario_fifo AS cf
      WHERE cf.id_empresa = v_empresa AND cf.id_sucursal = v_sucursal
        AND cf.id_ubicacion = v_id_ubicacion AND cf.id_producto = v_id_producto
        AND cf.cantidad_disponible > 0
      ORDER BY cf.recibido_en, cf.id_capa
      FOR UPDATE OF cf
    LOOP
      EXIT WHEN v_cantidad_pendiente = 0;
      v_consumo := LEAST(v_cantidad_pendiente, v_capa.cantidad_disponible);
      v_costo_unitario := v_capa.costo_unitario;
      v_costo_consumo := round(v_consumo * v_costo_unitario, 2);
      v_cantidad_pendiente := v_cantidad_pendiente - v_consumo;
      v_costo_linea := v_costo_linea + v_costo_consumo;

      UPDATE public.capas_inventario_fifo
      SET cantidad_disponible = cantidad_disponible - v_consumo
      WHERE id_capa = v_capa.id_capa;

      INSERT INTO public.consumos_fifo_venta (
        id_empresa, id_venta, id_detalle, id_capa, cantidad,
        costo_unitario, costo_total
      )
      VALUES (
        v_empresa, v_id_venta, v_id_detalle, v_capa.id_capa, v_consumo,
        v_costo_unitario, v_costo_consumo
      );
    END LOOP;

    IF v_cantidad_pendiente <> 0 THEN
      RAISE EXCEPTION 'No fue posible asignar toda la cantidad FIFO de %.', v_producto.sku;
    END IF;

    v_costo_linea := round(v_costo_linea, 2);
    IF v_costo_linea <= 0 THEN
      RAISE EXCEPTION 'El costo FIFO de % debe ser al menos 0.01.', v_producto.sku;
    END IF;

    UPDATE public.detalle_ventas
    SET costo_fifo = v_costo_linea
    WHERE id_detalle = v_id_detalle;

    INSERT INTO public.movimientos_inventario (
      id_empresa, id_sucursal, id_bodega, id_ubicacion, id_producto,
      tipo, cantidad_delta, costo_total, descripcion, fecha_operativa,
      registrado_en, registrado_por, origen_tipo, origen_id
    )
    VALUES (
      v_empresa, v_sucursal, v_id_bodega, v_id_ubicacion, v_id_producto,
      'VENTA', -v_cantidad, v_costo_linea, 'Salida por venta POS',
      v_fecha, v_ahora, v_usuario, 'VENTA', v_id_venta::text
    );

    v_subtotal := v_subtotal + v_subtotal_linea;
    v_costo_total := v_costo_total + v_costo_linea;
  END LOOP;

  INSERT INTO public.aplicaciones_descuento (
    id_empresa, id_venta, id_descuento, nombre_descuento_snapshot,
    monto_descuento, monto_neto_atribuido
  )
  SELECT v_empresa, v_id_venta, d.id_descuento,
    max(d.nombre_descuento_snapshot), sum(d.descuento_linea), sum(d.subtotal_linea)
  FROM public.detalle_ventas d
  WHERE d.id_empresa = v_empresa AND d.id_venta = v_id_venta
    AND d.id_descuento IS NOT NULL
  GROUP BY d.id_descuento;

  FOR v_pago IN
    SELECT p.metodo_pago, p.monto, p.efectivo_recibido
    FROM jsonb_to_recordset(v_pagos) AS p(
      metodo_pago text, monto numeric, efectivo_recibido numeric
    )
    ORDER BY p.metodo_pago
  LOOP
    v_linea := v_linea + 1;

    INSERT INTO public.pagos_venta (
      id_empresa, id_venta, numero_linea, metodo_pago, monto,
      efectivo_recibido, cambio
    )
    VALUES (
      v_empresa, v_id_venta, v_linea, v_pago.metodo_pago, v_pago.monto,
      CASE WHEN v_pago.metodo_pago = 'EFECTIVO' THEN v_pago.efectivo_recibido END,
      CASE WHEN v_pago.metodo_pago = 'EFECTIVO'
        THEN v_pago.efectivo_recibido - v_pago.monto END
    );

    IF v_pago.metodo_pago = 'EFECTIVO' THEN
      INSERT INTO public.movimientos_caja (
        id_empresa, id_sucursal, id_caja, id_sesion, tipo, monto,
        descripcion, fecha_operativa, registrado_en, registrado_por,
        origen_tipo, origen_id, idempotencia_key
      )
      VALUES (
        v_empresa, v_sucursal, v_caja, p_id_sesion, 'VENTA_EFECTIVO',
        v_pago.monto, 'Venta V-' || v_id_venta::text,
        v_fecha, v_ahora, v_usuario, 'VENTA', v_id_venta::text,
        'VENTA:' || v_id_venta::text
      );
    END IF;
  END LOOP;

  SELECT c.id_cuenta INTO v_id_cuenta_ingreso
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa AND c.codigo = '4.1.01'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
  SELECT c.id_cuenta INTO v_id_cuenta_costo
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa AND c.codigo = '5.1.01'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
  SELECT c.id_cuenta INTO v_id_cuenta_inventario
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa AND c.codigo = '1.1.06'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
  IF v_descuento_total > 0 THEN
    SELECT c.id_cuenta INTO v_id_cuenta_descuento
    FROM public.cuentas_contables AS c
    WHERE c.id_empresa = v_empresa AND c.codigo = '4.2.02'
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
  END IF;

  IF v_id_cuenta_ingreso IS NULL OR v_id_cuenta_costo IS NULL
     OR v_id_cuenta_inventario IS NULL
     OR (v_descuento_total > 0 AND v_id_cuenta_descuento IS NULL) THEN
    RAISE EXCEPTION 'Falta una cuenta de ventas, costo o inventario activa.';
  END IF;

  INSERT INTO public.comprobantes_contables (
    id_empresa, id_sucursal, id_periodo, tipo, fecha, descripcion,
    origen_tipo, origen_id, idempotencia_key, creado_por
  )
  VALUES (
    v_empresa, v_sucursal, v_periodo, 'VENTA', v_fecha,
    'Venta POS V-' || v_id_venta::text || ' (' || v_metodo_venta || ')',
    'VENTA_POS', v_id_venta::text, 'VENTA_POS:' || v_id_venta::text, v_usuario
  )
  RETURNING id_comprobante INTO v_id_comprobante;

  FOR v_pago IN
    SELECT p.metodo_pago, sum(p.monto)::numeric(14,2) AS monto
    FROM jsonb_to_recordset(v_pagos) AS p(
      metodo_pago text, monto numeric, efectivo_recibido numeric
    )
    GROUP BY p.metodo_pago
    ORDER BY p.metodo_pago
  LOOP
    v_id_cuenta_pago := NULL;
    SELECT c.id_cuenta INTO v_id_cuenta_pago
    FROM public.cuentas_contables AS c
    WHERE c.id_empresa = v_empresa
      AND c.codigo = CASE v_pago.metodo_pago
        WHEN 'EFECTIVO' THEN '1.1.02'
        WHEN 'TARJETA' THEN '1.1.08'
        WHEN 'TRANSFERENCIA' THEN '1.1.04'
      END
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;

    IF v_id_cuenta_pago IS NULL THEN
      RAISE EXCEPTION 'Falta configurar la cuenta contable para el medio de pago %.',
        v_pago.metodo_pago;
    END IF;

    v_linea_asiento := v_linea_asiento + 1;
    INSERT INTO public.lineas_comprobante_contable (
      id_empresa, id_comprobante, id_cuenta, numero_linea,
      descripcion, debe, haber
    )
    VALUES (
      v_empresa, v_id_comprobante, v_id_cuenta_pago, v_linea_asiento,
      'Cobro ' || v_pago.metodo_pago || ' de venta V-' || v_id_venta::text,
      v_pago.monto, 0
    );
  END LOOP;

  v_linea_asiento := v_linea_asiento + 1;
  INSERT INTO public.lineas_comprobante_contable (
    id_empresa, id_comprobante, id_cuenta, numero_linea, descripcion, debe, haber
  )
  VALUES
    (v_empresa, v_id_comprobante, v_id_cuenta_ingreso, v_linea_asiento,
      'Ingreso bruto de venta V-' || v_id_venta::text, 0, v_subtotal + v_descuento_total),
    (v_empresa, v_id_comprobante, v_id_cuenta_costo, v_linea_asiento + 1,
      'Costo FIFO de venta V-' || v_id_venta::text, v_costo_total, 0),
    (v_empresa, v_id_comprobante, v_id_cuenta_inventario, v_linea_asiento + 2,
      'Salida de inventario V-' || v_id_venta::text, 0, v_costo_total);
  IF v_descuento_total > 0 THEN
    INSERT INTO public.lineas_comprobante_contable (
      id_empresa, id_comprobante, id_cuenta, numero_linea, descripcion, debe, haber
    )
    VALUES (
      v_empresa, v_id_comprobante, v_id_cuenta_descuento, v_linea_asiento + 3,
      'Descuentos sobre venta V-' || v_id_venta::text, v_descuento_total, 0
    );
  END IF;

  UPDATE public.comprobantes_contables
  SET estado = 'CONTABILIZADO',
      contabilizado_por = v_usuario,
      contabilizado_en = v_ahora
  WHERE id_empresa = v_empresa AND id_comprobante = v_id_comprobante;

  UPDATE public.ventas
  SET id_comprobante = v_id_comprobante,
      costo_total_fifo = v_costo_total
  WHERE id_empresa = v_empresa AND id_venta = v_id_venta;

  RETURN v_id_venta;
END;
$$;

CREATE OR REPLACE FUNCTION public._registrar_pedido_web(
  p_id_empresa integer,
  p_user_id uuid,
  p_datos jsonb,
  p_items jsonb,
  p_clave_idempotencia text,
  p_pago_simulado boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_id_sucursal integer;
  v_tipo_entrega text;
  v_metodo_pago text;
  v_nombre text;
  v_telefono text;
  v_email text;
  v_direccion text;
  v_notas text;
  v_estado_pago text;
  v_id_pedido bigint;
  v_numero_orden text;
  v_token uuid;
  v_huella text;
  v_item record;
  v_producto record;
  v_existencia numeric(14,3);
  v_total numeric(14,2) := 0;
  v_subtotal numeric(14,2);
  v_precio_lista numeric(14,2);
  v_precio_final numeric(14,2);
  v_descuento_linea numeric(14,2);
  v_descuento_total numeric(14,2) := 0;
  v_id_descuento bigint;
  v_promocion record;
  v_linea integer := 0;
  v_resumen jsonb := '[]'::jsonb;
  v_pedido_existente public.pedidos_web%ROWTYPE;
BEGIN
  IF p_id_empresa IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.empresa e WHERE e.id_empresa = p_id_empresa AND e.activa
  ) THEN
    RAISE EXCEPTION 'No hay una empresa activa para registrar el pedido.';
  END IF;
  IF p_user_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.perfiles p
    WHERE p.id = p_user_id AND p.activo AND p.rol = 'cliente'
  ) THEN
    RAISE EXCEPTION 'La cuenta no está habilitada como cliente de la tienda.';
  END IF;
  IF p_datos IS NULL OR jsonb_typeof(p_datos) <> 'object' THEN
    RAISE EXCEPTION 'Los datos de contacto y entrega son obligatorios.';
  END IF;
  IF p_clave_idempotencia IS NULL
     OR trim(p_clave_idempotencia) !~*
       '^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$' THEN
    RAISE EXCEPTION 'La clave de solicitud debe ser un UUID generado aleatoriamente.';
  END IF;

  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'El pedido debe contener entre 1 y 100 productos.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    WHERE x.id_producto IS NULL OR x.cantidad IS NULL OR x.cantidad <= 0
  ) OR EXISTS (
    SELECT x.id_producto
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    GROUP BY x.id_producto
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'El carrito contiene productos o cantidades inválidas o duplicadas.';
  END IF;
  SELECT md5(jsonb_build_object(
    'user_id', p_user_id,
    'datos', p_datos,
    'pago_simulado', COALESCE(p_pago_simulado, false),
    'items', COALESCE(jsonb_agg(jsonb_build_object(
      'id_producto', x.id_producto, 'cantidad', x.cantidad
    ) ORDER BY x.id_producto), '[]'::jsonb)
  )::text)
  INTO v_huella
  FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric);

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_id_empresa::text || ':' || trim(p_clave_idempotencia), 0)
  );
  SELECT p.* INTO v_pedido_existente
  FROM public.pedidos_web p
  WHERE p.id_empresa = p_id_empresa
    AND p.clave_idempotencia = trim(p_clave_idempotencia);
  IF FOUND THEN
    IF v_pedido_existente.user_id IS DISTINCT FROM p_user_id THEN
      RAISE EXCEPTION 'La clave de solicitud ya fue utilizada.';
    END IF;
    IF v_pedido_existente.huella_solicitud <> v_huella THEN
      RAISE EXCEPTION 'La clave de solicitud ya fue utilizada con otros datos.';
    END IF;
    SELECT a.token_acceso INTO v_token
    FROM public.accesos_pedido_web a
    WHERE a.id_pedido = v_pedido_existente.id_pedido;
    RETURN jsonb_build_object(
      'id_pedido', v_pedido_existente.id_pedido,
      'numero_orden', v_pedido_existente.numero_orden,
      'estado', v_pedido_existente.estado,
      'estado_pago', v_pedido_existente.estado_pago,
      'total', v_pedido_existente.total,
      'descuento_total', v_pedido_existente.total_descuento,
      'items', COALESCE((
        SELECT jsonb_agg(jsonb_build_object(
          'id_producto', d.id_producto, 'name', d.nombre_snapshot,
          'sku', d.sku_snapshot, 'image', d.imagen_snapshot,
          'quantity', d.cantidad, 'precio_lista_unitario', d.precio_lista_unitario,
          'precio_unitario', d.precio_unitario, 'descuento_linea', d.descuento_linea,
          'nombre_descuento', d.nombre_descuento_snapshot,
          'subtotal_linea', d.subtotal_linea
        ) ORDER BY d.numero_linea)
        FROM public.detalles_pedido_web d
        WHERE d.id_empresa = v_pedido_existente.id_empresa
          AND d.id_pedido = v_pedido_existente.id_pedido
      ), '[]'::jsonb)
    ) || CASE WHEN p_user_id IS NULL
      THEN jsonb_build_object('token_acceso', v_token)
      ELSE '{}'::jsonb
    END;
  END IF;

  v_tipo_entrega := upper(trim(COALESCE(p_datos ->> 'tipo_entrega', '')));
  IF v_tipo_entrega IN ('RECOGER EN TIENDA', 'RETIRO EN TIENDA', 'RECOGER', 'RETIRO') THEN
    v_tipo_entrega := 'RETIRO';
  ELSIF v_tipo_entrega = 'DOMICILIO' THEN
    v_tipo_entrega := 'DOMICILIO';
  ELSE
    RAISE EXCEPTION 'El tipo de entrega debe ser retiro o domicilio.';
  END IF;

  v_metodo_pago := upper(trim(COALESCE(p_datos ->> 'metodo_pago', '')));
  IF v_metodo_pago IN ('EFECTIVO EN LOCAL', 'PAGO EN LOCAL', 'EFECTIVO') THEN
    v_metodo_pago := 'EFECTIVO';
  ELSIF v_metodo_pago IN ('TARJETA', 'TARJETA_SIMULADA') THEN
    v_metodo_pago := 'TARJETA_SIMULADA';
  ELSIF v_metodo_pago = 'TRANSFERENCIA' THEN
    v_metodo_pago := 'TRANSFERENCIA';
  ELSE
    RAISE EXCEPTION 'El método de pago del pedido no es válido.';
  END IF;
  IF (v_metodo_pago = 'TARJETA_SIMULADA') IS DISTINCT FROM COALESCE(p_pago_simulado, false) THEN
    RAISE EXCEPTION 'La tarjeta solo puede registrarse como simulada después de completar la simulación.';
  END IF;

  v_nombre := trim(COALESCE(NULLIF(p_datos ->> 'nombre_cliente', ''), ''));
  v_telefono := trim(COALESCE(NULLIF(p_datos ->> 'telefono', ''), ''));
  v_email := NULLIF(trim(COALESCE(p_datos ->> 'email', '')), '');
  v_direccion := NULLIF(trim(COALESCE(p_datos ->> 'direccion_entrega', '')), '');
  v_notas := NULLIF(trim(COALESCE(p_datos ->> 'notas', '')), '');
  IF p_user_id IS NOT NULL THEN
    SELECT
      COALESCE(NULLIF(v_nombre, ''), p.nombre_completo, p.email),
      COALESCE(NULLIF(v_telefono, ''), p.telefono),
      COALESCE(v_email, p.email)
    INTO v_nombre, v_telefono, v_email
    FROM public.perfiles p
    WHERE p.id = p_user_id AND p.activo AND p.rol = 'cliente';
  END IF;
  IF char_length(v_nombre) NOT BETWEEN 2 AND 160
     OR char_length(v_telefono) NOT BETWEEN 6 AND 32 THEN
    RAISE EXCEPTION 'Ingresa un nombre y teléfono de contacto válidos.';
  END IF;
  IF v_tipo_entrega = 'DOMICILIO'
     AND char_length(COALESCE(v_direccion, '')) < 5 THEN
    RAISE EXCEPTION 'La dirección es obligatoria para entrega a domicilio.';
  END IF;
  IF v_tipo_entrega = 'RETIRO' AND v_direccion IS NOT NULL THEN
    RAISE EXCEPTION 'No se debe enviar dirección para un pedido de retiro.';
  END IF;

  v_id_sucursal := NULLIF(p_datos ->> 'id_sucursal', '')::integer;
  IF v_id_sucursal IS NULL AND v_tipo_entrega = 'DOMICILIO' THEN
    SELECT s.id_sucursal INTO v_id_sucursal
    FROM public.sucursales s
    WHERE s.id_empresa = p_id_empresa AND s.es_principal AND s.activa
    ORDER BY s.id_sucursal
    LIMIT 1;
  END IF;
  IF v_id_sucursal IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.sucursales s
    WHERE s.id_empresa = p_id_empresa
      AND s.id_sucursal = v_id_sucursal
      AND s.activa
  ) THEN
    RAISE EXCEPTION 'Selecciona una sucursal activa para el pedido.';
  END IF;

  FOR v_item IN
    SELECT x.id_producto, x.cantidad
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    ORDER BY x.id_producto
  LOOP
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta,
      p.imagen_principal, COALESCE(um.decimales_cantidad, 3) AS decimales
    INTO v_producto
    FROM public.productos p
    LEFT JOIN public.unidades_medidas um
      ON um.id_empresa = p.id_empresa
      AND um.id_unidad_medida = p.id_unidad_medida
    WHERE p.id_empresa = p_id_empresa
      AND p.id_producto = v_item.id_producto
      AND p.activo
    FOR SHARE OF p;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Uno de los productos ya no está disponible.';
    END IF;
    IF v_item.cantidad <> round(v_item.cantidad, v_producto.decimales) THEN
      RAISE EXCEPTION 'La cantidad del producto % excede la precisión de su unidad.',
        v_item.id_producto;
    END IF;
    SELECT COALESCE(sum(f.cantidad_disponible), 0)
    INTO v_existencia
    FROM public.capas_inventario_fifo f
    WHERE f.id_empresa = p_id_empresa
      AND f.id_sucursal = v_id_sucursal
      AND f.id_producto = v_item.id_producto
      AND f.cantidad_disponible > 0;
    IF v_existencia < v_item.cantidad THEN
      RAISE EXCEPTION 'Existencias insuficientes para el producto % en la sucursal elegida.',
        v_producto.nombre;
    END IF;

    v_linea := v_linea + 1;
    v_precio_lista := v_producto.precio_venta;
    v_precio_final := v_precio_lista;
    v_id_descuento := NULL;
    SELECT promo.* INTO v_promocion
    FROM public._mejor_descuento_producto(
      p_id_empresa, v_producto.id_producto,
      (now() AT TIME ZONE 'America/Managua')::date
    ) promo;
    IF FOUND THEN
      v_precio_final := v_promocion.precio_final;
      v_id_descuento := v_promocion.id_descuento;
    END IF;
    v_subtotal := round(v_item.cantidad * v_precio_final, 2);
    v_descuento_linea :=
      round(v_item.cantidad * v_precio_lista, 2) - v_subtotal;
    IF v_descuento_linea <= 0 THEN
      v_id_descuento := NULL;
      v_descuento_linea := 0;
    END IF;
    IF v_subtotal <= 0 THEN
      RAISE EXCEPTION 'El importe de cada producto debe ser mayor que cero.';
    END IF;
    v_total := v_total + v_subtotal;
    v_descuento_total := v_descuento_total + v_descuento_linea;
    v_resumen := v_resumen || jsonb_build_array(jsonb_build_object(
      'numero_linea', v_linea,
      'id_producto', v_producto.id_producto,
      'sku', v_producto.sku,
      'nombre', v_producto.nombre,
      'imagen', v_producto.imagen_principal,
      'cantidad', v_item.cantidad,
      'precio_lista_unitario', v_precio_lista,
      'precio_unitario', v_precio_final,
      'descuento_unitario', v_precio_lista - v_precio_final,
      'descuento_linea', v_descuento_linea,
      'id_descuento', v_id_descuento,
      'nombre_descuento', CASE WHEN v_id_descuento IS NOT NULL THEN v_promocion.nombre END,
      'subtotal_linea', v_subtotal
    ));
  END LOOP;

  v_estado_pago := CASE WHEN v_metodo_pago = 'TARJETA_SIMULADA'
    THEN 'SIMULADO' ELSE 'PENDIENTE' END;
  INSERT INTO public.pedidos_web (
    id_empresa, id_sucursal, user_id, nombre_cliente, telefono, email,
    tipo_entrega, direccion_entrega, notas, metodo_pago_preferido,
    subtotal, impuesto, total, total_descuento, estado_pago, clave_idempotencia, huella_solicitud
  )
  VALUES (
    p_id_empresa, v_id_sucursal, p_user_id, v_nombre, v_telefono, v_email,
    v_tipo_entrega, v_direccion, v_notas, v_metodo_pago,
    v_total, 0, v_total, v_descuento_total, v_estado_pago,
    trim(p_clave_idempotencia), v_huella
  )
  RETURNING id_pedido, numero_orden INTO v_id_pedido, v_numero_orden;

  INSERT INTO public.detalles_pedido_web (
    id_empresa, id_pedido, numero_linea, id_producto, sku_snapshot,
    nombre_snapshot, imagen_snapshot, cantidad, precio_unitario, subtotal_linea,
    precio_lista_unitario, descuento_unitario, descuento_linea,
    id_descuento, nombre_descuento_snapshot
  )
  SELECT
    p_id_empresa, v_id_pedido, (x.item ->> 'numero_linea')::integer,
    (x.item ->> 'id_producto')::bigint, x.item ->> 'sku', x.item ->> 'nombre',
    x.item ->> 'imagen', (x.item ->> 'cantidad')::numeric,
    (x.item ->> 'precio_unitario')::numeric, (x.item ->> 'subtotal_linea')::numeric,
    (x.item ->> 'precio_lista_unitario')::numeric,
    (x.item ->> 'descuento_unitario')::numeric,
    (x.item ->> 'descuento_linea')::numeric,
    NULLIF(x.item ->> 'id_descuento', '')::bigint,
    NULLIF(x.item ->> 'nombre_descuento', '')
  FROM jsonb_array_elements(v_resumen) AS x(item);

  IF p_user_id IS NULL THEN
    v_token := gen_random_uuid();
    INSERT INTO public.accesos_pedido_web (id_pedido, token_acceso)
    VALUES (v_id_pedido, v_token);
  END IF;

  RETURN jsonb_build_object(
    'id_pedido', v_id_pedido,
    'numero_orden', v_numero_orden,
    'estado', 'PENDIENTE',
    'estado_pago', v_estado_pago,
    'total', v_total,
    'descuento_total', v_descuento_total,
    'items', v_resumen
  ) || CASE WHEN p_user_id IS NULL
    THEN jsonb_build_object('token_acceso', v_token)
    ELSE '{}'::jsonb
  END;
END;
$$;

CREATE OR REPLACE FUNCTION public.consultar_pedido_web(
  p_id_pedido bigint,
  p_token_acceso uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_pedido public.pedidos_web%ROWTYPE;
  v_token_valido boolean := false;
  v_items jsonb;
BEGIN
  SELECT p.* INTO v_pedido
  FROM public.pedidos_web p
  WHERE p.id_pedido = p_id_pedido;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'No se encontró el pedido o el acceso no es válido.';
  END IF;
  IF v_usuario IS NOT NULL AND v_pedido.user_id = v_usuario THEN
    v_token_valido := true;
  ELSIF p_token_acceso IS NOT NULL THEN
    SELECT EXISTS (
      SELECT 1 FROM public.accesos_pedido_web a
      WHERE a.id_pedido = p_id_pedido AND a.token_acceso = p_token_acceso
    ) INTO v_token_valido;
  END IF;
  IF NOT v_token_valido THEN
    RAISE EXCEPTION 'No se encontró el pedido o el acceso no es válido.';
  END IF;

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'id_producto', d.id_producto,
    'sku', d.sku_snapshot,
    'nombre', d.nombre_snapshot,
    'imagen', d.imagen_snapshot,
    'cantidad', d.cantidad,
    'precio_lista_unitario', d.precio_lista_unitario,
    'precio_unitario', d.precio_unitario,
    'descuento_linea', d.descuento_linea,
    'nombre_descuento', d.nombre_descuento_snapshot,
    'subtotal', d.subtotal_linea
  ) ORDER BY d.numero_linea), '[]'::jsonb)
  INTO v_items
  FROM public.detalles_pedido_web d
  WHERE d.id_empresa = v_pedido.id_empresa AND d.id_pedido = p_id_pedido;

  RETURN jsonb_build_object(
    'id_pedido', v_pedido.id_pedido,
    'numero_orden', v_pedido.numero_orden,
    'estado', v_pedido.estado,
    'estado_pago', v_pedido.estado_pago,
    'total', v_pedido.total,
    'descuento_total', v_pedido.total_descuento,
    'tipo_entrega', v_pedido.tipo_entrega,
    'sucursal', v_pedido.id_sucursal,
    'items', v_items
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.aceptar_pedido_web(
  p_id_pedido bigint,
  p_id_sesion bigint,
  p_metodo_pago_real text,
  p_efectivo_recibido numeric DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_pedido public.pedidos_web%ROWTYPE;
  v_items jsonb;
  v_pagos jsonb;
  v_venta bigint;
  v_total_actual numeric(14,2);
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT (SELECT public.es_staff()) THEN
    RAISE EXCEPTION 'Solo el personal autorizado puede aceptar pedidos web.';
  END IF;
  SELECT p.* INTO v_pedido
  FROM public.pedidos_web p
  WHERE p.id_pedido = p_id_pedido
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'El pedido web no existe.';
  END IF;
  IF NOT (SELECT public.puede_ver_caja(v_pedido.id_empresa, v_pedido.id_sucursal)) THEN
    RAISE EXCEPTION 'No tienes acceso a la sucursal del pedido.';
  END IF;
  IF v_pedido.id_venta IS NOT NULL THEN
    RETURN v_pedido.id_venta;
  END IF;
  IF v_pedido.estado <> 'PENDIENTE' THEN
    RAISE EXCEPTION 'Solo se pueden aceptar pedidos pendientes.';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.sesiones_caja s
    WHERE s.id_sesion = p_id_sesion
      AND s.id_empresa = v_pedido.id_empresa
      AND s.id_sucursal = v_pedido.id_sucursal
      AND s.estado = 'ABIERTA'
  ) THEN
    RAISE EXCEPTION 'La sesión de caja debe estar abierta en la sucursal del pedido.';
  END IF;
  IF COALESCE(upper(trim(p_metodo_pago_real)), '')
     NOT IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA') THEN
    RAISE EXCEPTION 'Confirma el método de pago real recibido.';
  END IF;
  IF upper(trim(p_metodo_pago_real)) = 'EFECTIVO'
     AND COALESCE(p_efectivo_recibido, 0) < v_pedido.total THEN
    RAISE EXCEPTION 'El efectivo recibido no cubre el total del pedido.';
  END IF;
  IF upper(trim(p_metodo_pago_real)) <> 'EFECTIVO' AND p_efectivo_recibido IS NOT NULL THEN
    RAISE EXCEPTION 'El efectivo recibido solo aplica para pagos en efectivo.';
  END IF;

  SELECT COALESCE(sum(round(
    d.cantidad * COALESCE(promo.precio_final, p.precio_venta), 2
  )), 0)
  INTO v_total_actual
  FROM public.detalles_pedido_web d
  JOIN public.productos p
    ON p.id_empresa = d.id_empresa AND p.id_producto = d.id_producto AND p.activo
  LEFT JOIN LATERAL public._mejor_descuento_producto(
    v_pedido.id_empresa, d.id_producto,
    (now() AT TIME ZONE 'America/Managua')::date
  ) promo ON true
  WHERE d.id_empresa = v_pedido.id_empresa AND d.id_pedido = p_id_pedido;
  IF v_total_actual <> v_pedido.total OR EXISTS (
    SELECT 1
    FROM public.detalles_pedido_web d
    LEFT JOIN public.productos p
      ON p.id_empresa = d.id_empresa AND p.id_producto = d.id_producto AND p.activo
    LEFT JOIN LATERAL public._mejor_descuento_producto(
      v_pedido.id_empresa, d.id_producto,
      (now() AT TIME ZONE 'America/Managua')::date
    ) promo ON true
    WHERE d.id_empresa = v_pedido.id_empresa
      AND d.id_pedido = p_id_pedido
      AND (
        p.id_producto IS NULL
        OR d.precio_lista_unitario IS DISTINCT FROM p.precio_venta
        OR d.precio_unitario IS DISTINCT FROM COALESCE(promo.precio_final, p.precio_venta)
        OR d.id_descuento IS DISTINCT FROM promo.id_descuento
        OR d.descuento_linea IS DISTINCT FROM (
          round(d.cantidad * p.precio_venta, 2)
          - round(d.cantidad * COALESCE(promo.precio_final, p.precio_venta), 2)
        )
      )
  ) THEN
    RAISE EXCEPTION 'El precio o catálogo cambió; actualiza el pedido antes de aceptar el pago.';
  END IF;

  SELECT jsonb_agg(jsonb_build_object(
    'id_producto', d.id_producto, 'cantidad', d.cantidad
  ) ORDER BY d.numero_linea)
  INTO v_items
  FROM public.detalles_pedido_web d
  WHERE d.id_empresa = v_pedido.id_empresa AND d.id_pedido = p_id_pedido;
  v_pagos := jsonb_build_array(jsonb_build_object(
    'metodo_pago', upper(trim(p_metodo_pago_real)),
    'monto', v_pedido.total
  ));
  IF upper(trim(p_metodo_pago_real)) = 'EFECTIVO' THEN
    v_pagos := jsonb_build_array(jsonb_build_object(
      'metodo_pago', 'EFECTIVO',
      'monto', v_pedido.total,
      'efectivo_recibido', p_efectivo_recibido
    ));
  END IF;

  v_venta := public.registrar_venta_pos(
    p_id_sesion,
    v_items,
    v_pagos,
    'PEDIDO_WEB:' || v_pedido.id_pedido::text,
    NULL
  );
  UPDATE public.pedidos_web
  SET estado = 'LISTO',
      estado_pago = 'CONFIRMADO',
      metodo_pago_real = upper(trim(p_metodo_pago_real)),
      id_venta = v_venta,
      aceptado_por = (SELECT auth.uid()),
      aceptado_en = clock_timestamp(),
      actualizado_en = clock_timestamp()
  WHERE id_empresa = v_pedido.id_empresa AND id_pedido = p_id_pedido;
  RETURN v_venta;
END;
$$;

CREATE OR REPLACE FUNCTION public.cotizar_venta_pos(
  p_id_sesion bigint,
  p_items jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_empresa integer;
  v_sucursal integer;
  v_estado text;
  v_zona text;
  v_fecha date;
  v_producto record;
  v_promocion record;
  v_precio_lista numeric(14,2);
  v_precio_final numeric(14,2);
  v_subtotal numeric(14,2);
  v_descuento numeric(14,2);
  v_total numeric(14,2) := 0;
  v_total_lista numeric(14,2) := 0;
  v_total_descuento numeric(14,2) := 0;
  v_items jsonb := '[]'::jsonb;
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT (SELECT public.es_staff()) THEN
    RAISE EXCEPTION 'Solo el personal autorizado puede cotizar ventas.';
  END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 50 THEN
    RAISE EXCEPTION 'La cotizacion debe incluir entre 1 y 50 productos.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric)
    WHERE i.id_producto IS NULL OR i.cantidad IS NULL
      OR i.cantidad <= 0 OR i.cantidad <> round(i.cantidad, 3)
  ) OR EXISTS (
    SELECT i.id_producto FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric)
    GROUP BY i.id_producto HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'La cotizacion contiene cantidades o productos invalidos.';
  END IF;

  SELECT s.id_empresa, s.id_sucursal, s.estado, s.zona_horaria
  INTO v_empresa, v_sucursal, v_estado, v_zona
  FROM public.sesiones_caja s WHERE s.id_sesion = p_id_sesion;
  IF v_empresa IS NULL OR v_estado <> 'ABIERTA'
     OR NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, false)) THEN
    RAISE EXCEPTION 'No tienes una sesion de caja abierta y autorizada.';
  END IF;
  v_fecha := (clock_timestamp() AT TIME ZONE v_zona)::date;

  FOR v_producto IN
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta, i.cantidad
    FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric)
    JOIN public.productos p ON p.id_empresa = v_empresa AND p.id_producto = i.id_producto
    WHERE p.activo
    ORDER BY p.id_producto
  LOOP
    v_precio_lista := v_producto.precio_venta;
    v_precio_final := v_precio_lista;
    SELECT promo.* INTO v_promocion
    FROM public._mejor_descuento_producto(v_empresa, v_producto.id_producto, v_fecha) promo;
    IF FOUND THEN
      v_precio_final := v_promocion.precio_final;
    END IF;
    v_subtotal := round(v_producto.cantidad * v_precio_final, 2);
    v_descuento := round(v_producto.cantidad * v_precio_lista, 2) - v_subtotal;
    v_total := v_total + v_subtotal;
    v_total_lista := v_total_lista + round(v_producto.cantidad * v_precio_lista, 2);
    v_total_descuento := v_total_descuento + v_descuento;
    v_items := v_items || jsonb_build_array(jsonb_build_object(
      'id_producto', v_producto.id_producto, 'sku', v_producto.sku,
      'nombre', v_producto.nombre, 'cantidad', v_producto.cantidad,
      'precio_lista_unitario', v_precio_lista,
      'precio_unitario', v_precio_final,
      'descuento_linea', v_descuento,
      'nombre_descuento', CASE WHEN v_descuento > 0 THEN v_promocion.nombre END,
      'subtotal_linea', v_subtotal
    ));
  END LOOP;
  IF jsonb_array_length(v_items) <> jsonb_array_length(p_items) THEN
    RAISE EXCEPTION 'Uno o mas productos no existen o estan inactivos.';
  END IF;
  RETURN jsonb_build_object(
    'subtotal_lista', v_total_lista, 'descuento_total', v_total_descuento,
    'total', v_total, 'items', v_items
  );
END;
$$;

