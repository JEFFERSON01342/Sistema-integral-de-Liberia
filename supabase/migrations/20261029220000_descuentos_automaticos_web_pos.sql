CREATE OR REPLACE FUNCTION public._mejor_descuento_producto(
  p_id_empresa integer,
  p_id_producto bigint,
  p_fecha date DEFAULT ((now() AT TIME ZONE 'America/Managua')::date)
)
RETURNS TABLE (
  id_descuento bigint,
  nombre text,
  precio_lista numeric(14,2),
  descuento_unitario numeric(14,2),
  precio_final numeric(14,2)
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT d.id,
    d.nombre,
    p.precio_venta::numeric(14,2),
    LEAST(
      p.precio_venta - 0.01,
      round(CASE d.tipo
        WHEN 'porcentaje' THEN p.precio_venta * d.valor / 100
        ELSE d.valor
      END, 2)
    )::numeric(14,2),
    (p.precio_venta - LEAST(
      p.precio_venta - 0.01,
      round(CASE d.tipo
        WHEN 'porcentaje' THEN p.precio_venta * d.valor / 100
        ELSE d.valor
      END, 2)
    ))::numeric(14,2)
  FROM public.descuentos d
  JOIN public.productos p
    ON p.id_empresa = d.id_empresa AND p.id_producto = p_id_producto
  WHERE d.id_empresa = p_id_empresa
    AND d.activo
    AND d.codigo_descuento IS NULL
    AND (d.fecha_inicio IS NULL OR d.fecha_inicio <= p_fecha)
    AND (d.fecha_fin IS NULL OR d.fecha_fin >= p_fecha)
    AND p.activo
    AND p.precio_venta > 0.01
    AND (d.usos_maximos IS NULL OR (
      SELECT count(*)
      FROM public.aplicaciones_descuento a
      WHERE a.id_empresa = d.id_empresa AND a.id_descuento = d.id
    ) < d.usos_maximos)
    AND (
      d.aplica_a = 'todos'
      OR (d.aplica_a = 'productos' AND EXISTS (
        SELECT 1 FROM public.descuento_productos dp
        WHERE dp.id_empresa = d.id_empresa AND dp.id_descuento = d.id
          AND dp.id_producto = p.id_producto
      ))
      OR (d.aplica_a = 'categorias' AND EXISTS (
        SELECT 1 FROM public.descuento_categorias dc
        WHERE dc.id_empresa = d.id_empresa AND dc.id_descuento = d.id
          AND dc.id_categoria = p.id_categoria
      ))
    )
  ORDER BY LEAST(
    p.precio_venta - 0.01,
    round(CASE d.tipo
      WHEN 'porcentaje' THEN p.precio_venta * d.valor / 100
      ELSE d.valor
    END, 2)
  ) DESC, d.id
  LIMIT 1;
$$;

