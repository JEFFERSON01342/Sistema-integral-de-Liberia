CREATE TABLE public.descuentos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) BETWEEN 2 AND 120),
  descripcion text,
  tipo text NOT NULL CHECK (tipo IN ('porcentaje', 'monto')),
  valor numeric(14,2) NOT NULL CHECK (
    (tipo = 'porcentaje' AND valor > 0 AND valor < 100)
    OR (tipo = 'monto' AND valor > 0)
  ),
  codigo_descuento text,
  fecha_inicio date,
  fecha_fin date,
  aplica_a text NOT NULL DEFAULT 'todos'
    CHECK (aplica_a IN ('todos', 'categorias', 'productos')),
  temporada text,
  banner_texto text,
  usos_maximos integer CHECK (usos_maximos IS NULL OR usos_maximos > 0),
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id),
  CHECK (codigo_descuento IS NULL),
  CHECK (fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

