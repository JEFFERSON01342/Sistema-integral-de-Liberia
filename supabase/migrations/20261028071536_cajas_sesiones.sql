CREATE OR REPLACE FUNCTION public.proteger_caja_con_sesiones()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.codigo IS DISTINCT FROM OLD.codigo
     AND EXISTS (
       SELECT 1
       FROM public.sesiones_caja AS sc
       WHERE sc.id_caja = OLD.id_caja
     ) THEN
    RAISE EXCEPTION 'No se puede cambiar el código de una caja que ya tiene sesiones.';
  END IF;

  IF OLD.activa AND NOT NEW.activa
     AND EXISTS (
       SELECT 1
       FROM public.sesiones_caja AS sc
       WHERE sc.id_caja = OLD.id_caja
         AND sc.estado = 'ABIERTA'
     ) THEN
    RAISE EXCEPTION 'Cierre la sesión activa antes de desactivar la caja.';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER cajas_proteger_historial
BEFORE UPDATE ON public.cajas
FOR EACH ROW
EXECUTE FUNCTION public.proteger_caja_con_sesiones();

CREATE TRIGGER cajas_actualizar_updated_at
BEFORE UPDATE ON public.cajas
