CREATE OR REPLACE FUNCTION public.abrir_sesion_caja(
  p_id_caja bigint,
  p_fondo_inicial numeric
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_zona_horaria text;
  v_fecha_operativa date;
  v_ahora timestamptz := clock_timestamp();
  v_id_periodo bigint;
  v_id_sesion bigint;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para abrir una caja.';
  END IF;

  IF p_fondo_inicial IS NULL
     OR p_fondo_inicial < 0
     OR p_fondo_inicial <> round(p_fondo_inicial, 2) THEN
    RAISE EXCEPTION 'El fondo inicial debe ser cero o un monto positivo con máximo dos decimales.';
  END IF;

  SELECT c.id_empresa, c.id_sucursal
  INTO v_empresa, v_sucursal
  FROM public.cajas AS c
  WHERE c.id_caja = p_id_caja
    AND c.activa
  FOR UPDATE;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'La caja no existe o está inactiva.';
  END IF;

  IF NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, false)) THEN
    RAISE EXCEPTION 'No tienes permiso para abrir esta caja.';
  END IF;

  SELECT e.zona_horaria
  INTO v_zona_horaria
  FROM public.empresa AS e
  WHERE e.id_empresa = v_empresa
    AND e.activa;

  IF v_zona_horaria IS NULL THEN
    RAISE EXCEPTION 'La empresa no existe o está inactiva.';
  END IF;

  v_fecha_operativa := (v_ahora AT TIME ZONE v_zona_horaria)::date;

  SELECT pc.id_periodo
  INTO v_id_periodo
  FROM public.periodos_contables AS pc
  WHERE pc.id_empresa = v_empresa
    AND v_fecha_operativa BETWEEN pc.fecha_inicio AND pc.fecha_fin
    AND pc.estado = 'ABIERTO'
  FOR SHARE;

  IF v_id_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha operativa actual.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.sesiones_caja AS sc
    WHERE sc.id_caja = p_id_caja
      AND sc.estado = 'ABIERTA'
  ) THEN
    RAISE EXCEPTION 'Esta caja ya tiene una sesión abierta; debe cerrarse antes de abrir otra.';
  END IF;

  INSERT INTO public.sesiones_caja (
    id_empresa, id_sucursal, id_caja, zona_horaria, fecha_operativa,
    fondo_inicial, abierta_por, abierta_en
  )
  VALUES (
    v_empresa, v_sucursal, p_id_caja, v_zona_horaria, v_fecha_operativa,
    p_fondo_inicial, v_usuario, v_ahora
  )
  RETURNING id_sesion INTO v_id_sesion;

  INSERT INTO public.movimientos_caja (
    id_empresa, id_sucursal, id_caja, id_sesion, tipo, monto,
    descripcion, fecha_operativa, registrado_en, registrado_por
  )
  VALUES (
    v_empresa, v_sucursal, p_id_caja, v_id_sesion, 'APERTURA',
    p_fondo_inicial, 'Fondo de apertura de caja',
    v_fecha_operativa, v_ahora, v_usuario
  );

  RETURN v_id_sesion;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_movimiento_caja(
  p_id_sesion bigint,
  p_tipo text,
  p_monto numeric,
  p_descripcion text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_caja bigint;
  v_estado text;
  v_zona_horaria text;
  v_ahora timestamptz := clock_timestamp();
  v_fecha_operativa date;
  v_id_periodo bigint;
  v_id_movimiento bigint;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para registrar un movimiento de caja.';
  END IF;

  IF p_tipo NOT IN ('INGRESO', 'RETIRO') THEN
    RAISE EXCEPTION 'Solo se permiten ingresos o retiros manuales; las ventas se registran desde su propio flujo.';
  END IF;

  IF p_monto IS NULL OR p_monto <= 0 OR p_monto <> round(p_monto, 2) THEN
    RAISE EXCEPTION 'El monto debe ser positivo y tener máximo dos decimales.';
  END IF;

  IF p_descripcion IS NULL OR char_length(trim(p_descripcion)) < 3 THEN
    RAISE EXCEPTION 'La descripción del movimiento debe tener al menos tres caracteres.';
  END IF;

  SELECT sc.id_empresa, sc.id_sucursal, sc.id_caja, sc.estado, sc.zona_horaria
  INTO v_empresa, v_sucursal, v_caja, v_estado, v_zona_horaria
  FROM public.sesiones_caja AS sc
  WHERE sc.id_sesion = p_id_sesion
  FOR UPDATE;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'La sesión de caja no existe.';
  END IF;

  IF NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, false)) THEN
    RAISE EXCEPTION 'No tienes permiso para registrar movimientos en esta caja.';
  END IF;

  IF v_estado <> 'ABIERTA' THEN
    RAISE EXCEPTION 'No se pueden registrar movimientos en una sesión cerrada.';
  END IF;

  v_fecha_operativa := (v_ahora AT TIME ZONE v_zona_horaria)::date;

  SELECT pc.id_periodo
  INTO v_id_periodo
  FROM public.periodos_contables AS pc
  WHERE pc.id_empresa = v_empresa
    AND v_fecha_operativa BETWEEN pc.fecha_inicio AND pc.fecha_fin
    AND pc.estado = 'ABIERTO'
  FOR SHARE;

  IF v_id_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha operativa actual.';
  END IF;

  INSERT INTO public.movimientos_caja (
    id_empresa, id_sucursal, id_caja, id_sesion, tipo, monto,
    descripcion, fecha_operativa, registrado_en, registrado_por
  )
  VALUES (
    v_empresa, v_sucursal, v_caja, p_id_sesion, p_tipo, p_monto,
    trim(p_descripcion), v_fecha_operativa, v_ahora, v_usuario
  )
  RETURNING id_movimiento INTO v_id_movimiento;

  RETURN v_id_movimiento;
END;
$$;

CREATE OR REPLACE FUNCTION public.cerrar_sesion_caja_interno(
  p_id_sesion bigint,
  p_efectivo_contado numeric,
  p_motivo text,
  p_excepcional boolean
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_estado text;
  v_zona_horaria text;
  v_ahora timestamptz := clock_timestamp();
  v_fecha_operativa date;
  v_efectivo_esperado numeric(14, 2);
  v_diferencia numeric(14, 2);
  v_motivo text := NULLIF(trim(p_motivo), '');
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para cerrar una caja.';
  END IF;

  IF p_efectivo_contado IS NULL
     OR p_efectivo_contado < 0
     OR p_efectivo_contado <> round(p_efectivo_contado, 2) THEN
    RAISE EXCEPTION 'El efectivo contado debe ser cero o un monto positivo con máximo dos decimales.';
  END IF;

  SELECT sc.id_empresa, sc.id_sucursal, sc.estado, sc.zona_horaria
  INTO v_empresa, v_sucursal, v_estado, v_zona_horaria
  FROM public.sesiones_caja AS sc
  WHERE sc.id_sesion = p_id_sesion
  FOR UPDATE;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'La sesión de caja no existe.';
  END IF;

  IF NOT (
    SELECT public.puede_operar_caja(v_empresa, v_sucursal, p_excepcional)
  ) THEN
    RAISE EXCEPTION 'No tienes permiso para cerrar esta sesión de caja.';
  END IF;

  IF v_estado <> 'ABIERTA' THEN
    RAISE EXCEPTION 'La sesión ya está cerrada.';
  END IF;

  IF p_excepcional AND char_length(COALESCE(v_motivo, '')) < 3 THEN
    RAISE EXCEPTION 'El cierre excepcional requiere un motivo de al menos tres caracteres.';
  END IF;

  SELECT COALESCE(sum(
    CASE
      WHEN mc.tipo IN (
        'APERTURA', 'INGRESO', 'VENTA_EFECTIVO', 'DEVOLUCION_EFECTIVO'
      ) THEN mc.monto
      ELSE -mc.monto
    END
  ), 0)::numeric(14, 2)
  INTO v_efectivo_esperado
  FROM public.movimientos_caja AS mc
  WHERE mc.id_sesion = p_id_sesion;

  v_diferencia := p_efectivo_contado - v_efectivo_esperado;

  IF v_diferencia <> 0 AND char_length(COALESCE(v_motivo, '')) < 3 THEN
    RAISE EXCEPTION 'La diferencia de caja requiere un motivo de al menos tres caracteres.';
  END IF;

  v_fecha_operativa := (v_ahora AT TIME ZONE v_zona_horaria)::date;

  UPDATE public.sesiones_caja
  SET estado = 'CERRADA',
      fecha_cierre_operativa = v_fecha_operativa,
      efectivo_esperado_cierre = v_efectivo_esperado,
      efectivo_contado_cierre = p_efectivo_contado,
      diferencia_cierre = v_diferencia,
      tipo_cierre = CASE WHEN p_excepcional THEN 'EXCEPCIONAL' ELSE 'NORMAL' END,
      motivo_cierre = v_motivo,
      cerrada_por = v_usuario,
      cerrada_en = v_ahora
  WHERE id_sesion = p_id_sesion;
END;
$$;

CREATE OR REPLACE FUNCTION public.cerrar_sesion_caja(
