-- Fase 5: terminales, sesiones de caja y registro inmutable de efectivo.
-- Ejecutar solo en el proyecto nuevo, después de las migraciones 001-004.
-- Las fechas y marcas de tiempo se asignan en PostgreSQL, nunca desde el cliente.

BEGIN;

CREATE TABLE public.cajas (
  id_caja bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  codigo text NOT NULL CHECK (char_length(trim(codigo)) > 0),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cajas_sucursal_codigo_key UNIQUE (id_sucursal, codigo),
  CONSTRAINT cajas_empresa_sucursal_caja_key
    UNIQUE (id_empresa, id_sucursal, id_caja),
  CONSTRAINT cajas_sucursal_empresa_fkey
    FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal)
);

CREATE TABLE public.sesiones_caja (
  id_sesion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_caja bigint NOT NULL,
  zona_horaria text NOT NULL,
  fecha_operativa date NOT NULL,
  estado text NOT NULL DEFAULT 'ABIERTA'
    CHECK (estado IN ('ABIERTA', 'CERRADA')),
  fondo_inicial numeric(14, 2) NOT NULL CHECK (fondo_inicial >= 0),
  abierta_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  abierta_en timestamptz NOT NULL,
  fecha_cierre_operativa date,
  efectivo_esperado_cierre numeric(14, 2),
  efectivo_contado_cierre numeric(14, 2),
  diferencia_cierre numeric(14, 2),
  tipo_cierre text CHECK (tipo_cierre IN ('NORMAL', 'EXCEPCIONAL')),
  motivo_cierre text,
  cerrada_por uuid REFERENCES auth.users (id) ON DELETE RESTRICT,
  cerrada_en timestamptz,
  CONSTRAINT sesiones_caja_empresa_sucursal_caja_sesion_key
    UNIQUE (id_empresa, id_sucursal, id_caja, id_sesion),
  CONSTRAINT sesiones_caja_caja_fkey
    FOREIGN KEY (id_empresa, id_sucursal, id_caja)
    REFERENCES public.cajas (id_empresa, id_sucursal, id_caja),
  CONSTRAINT sesiones_caja_cierre_check CHECK (
    (
      estado = 'ABIERTA'
      AND fecha_cierre_operativa IS NULL
      AND efectivo_esperado_cierre IS NULL
      AND efectivo_contado_cierre IS NULL
      AND diferencia_cierre IS NULL
      AND tipo_cierre IS NULL
      AND motivo_cierre IS NULL
      AND cerrada_por IS NULL
      AND cerrada_en IS NULL
    )
    OR
    (
      estado = 'CERRADA'
      AND fecha_cierre_operativa IS NOT NULL
      AND efectivo_esperado_cierre IS NOT NULL
      AND efectivo_contado_cierre IS NOT NULL
      AND diferencia_cierre = efectivo_contado_cierre - efectivo_esperado_cierre
      AND tipo_cierre IS NOT NULL
      AND cerrada_por IS NOT NULL
      AND cerrada_en IS NOT NULL
      AND (
        (diferencia_cierre = 0 AND motivo_cierre IS NULL)
        OR char_length(trim(motivo_cierre)) >= 3
      )
      AND (
        tipo_cierre <> 'EXCEPCIONAL'
        OR char_length(trim(motivo_cierre)) >= 3
      )
    )
  )
);

CREATE UNIQUE INDEX sesiones_caja_una_abierta_por_terminal
  ON public.sesiones_caja (id_caja)
  WHERE estado = 'ABIERTA';

CREATE INDEX sesiones_caja_empresa_sucursal_fecha_idx
  ON public.sesiones_caja (id_empresa, id_sucursal, fecha_operativa DESC);

CREATE TABLE public.movimientos_caja (
  id_movimiento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_caja bigint NOT NULL,
  id_sesion bigint NOT NULL,
  tipo text NOT NULL CHECK (
    tipo IN (
      'APERTURA',
      'INGRESO',
      'RETIRO',
      'VENTA_EFECTIVO',
      'DEVOLUCION_EFECTIVO',
      'ANULACION_VENTA_EFECTIVO'
    )
  ),
  monto numeric(14, 2) NOT NULL CHECK (
    (tipo = 'APERTURA' AND monto >= 0)
    OR (tipo <> 'APERTURA' AND monto > 0)
  ),
  descripcion text,
  fecha_operativa date NOT NULL,
  registrado_en timestamptz NOT NULL,
  registrado_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  origen_tipo text,
  origen_id text,
  idempotencia_key text,
  CONSTRAINT movimientos_caja_sesion_fkey
    FOREIGN KEY (id_empresa, id_sucursal, id_caja, id_sesion)
    REFERENCES public.sesiones_caja
      (id_empresa, id_sucursal, id_caja, id_sesion),
  CONSTRAINT movimientos_caja_idempotencia_key
    UNIQUE (id_empresa, id_sesion, idempotencia_key),
  CONSTRAINT movimientos_caja_origen_check CHECK (
    (origen_tipo IS NULL AND origen_id IS NULL)
    OR (
      char_length(trim(origen_tipo)) > 0
      AND char_length(trim(origen_id)) > 0
    )
  )
);

CREATE INDEX movimientos_caja_sesion_fecha_idx
  ON public.movimientos_caja (id_sesion, registrado_en, id_movimiento);

CREATE INDEX movimientos_caja_empresa_fecha_idx
  ON public.movimientos_caja (id_empresa, fecha_operativa, id_sucursal);

CREATE OR REPLACE FUNCTION public.puede_ver_caja(
  p_id_empresa integer,
  p_id_sucursal integer
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.perfiles AS p
    WHERE p.id = (SELECT auth.uid())
      AND p.activo
      AND p.rol IN ('superadmin', 'admin', 'gerente', 'cajero')
      AND (
        p.rol = 'superadmin'
        OR (
          p.id_empresa = p_id_empresa
          AND p.id_sucursal = p_id_sucursal
        )
      )
  );
$$;

CREATE OR REPLACE FUNCTION public.puede_operar_caja(
  p_id_empresa integer,
  p_id_sucursal integer,
  p_requiere_supervisor boolean DEFAULT false
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.perfiles AS p
    WHERE p.id = (SELECT auth.uid())
      AND p.activo
      AND (
        p.rol = 'superadmin'
        OR (
          p.id_empresa = p_id_empresa
          AND p.id_sucursal = p_id_sucursal
          AND (
            (p_requiere_supervisor AND p.rol IN ('admin', 'gerente'))
            OR (NOT p_requiere_supervisor AND p.rol IN ('admin', 'gerente', 'cajero'))
          )
        )
      )
  );
$$;

