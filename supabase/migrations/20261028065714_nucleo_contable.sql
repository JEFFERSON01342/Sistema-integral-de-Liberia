CREATE OR REPLACE FUNCTION public.crear_comprobante_borrador(
  p_id_empresa integer,
  p_id_sucursal integer,
  p_fecha date,
  p_tipo text,
  p_descripcion text,
  p_lineas jsonb,
  p_idempotencia_key text DEFAULT NULL,
  p_origen_tipo text DEFAULT NULL,
  p_origen_id text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_id_periodo bigint;
  v_estado_periodo text;
  v_id_comprobante bigint;
  v_line jsonb;
  v_numero_linea integer := 0;
  v_id_cuenta bigint;
  v_debe numeric;
  v_haber numeric;
  v_total_debe numeric(14, 2) := 0;
  v_total_haber numeric(14, 2) := 0;
BEGIN
  IF v_usuario IS NULL
     OR (SELECT public.puede_administrar_empresa(p_id_empresa)) IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'No tienes permiso para crear comprobantes en esta empresa.';
  END IF;

  IF p_fecha IS NULL OR p_descripcion IS NULL OR char_length(trim(p_descripcion)) = 0 THEN
    RAISE EXCEPTION 'La fecha y la descripción del comprobante son obligatorias.';
  END IF;

  IF p_tipo IS NULL OR p_tipo NOT IN ('APERTURA', 'VENTA', 'COMPRA', 'AJUSTE', 'DEVOLUCION',
                    'GASTO', 'PAGO', 'MANUAL', 'CIERRE') THEN
    RAISE EXCEPTION 'El tipo de comprobante no es válido.';
  END IF;

  IF jsonb_typeof(p_lineas) <> 'array' OR jsonb_array_length(p_lineas) < 2 THEN
    RAISE EXCEPTION 'El comprobante debe tener al menos dos líneas.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.sucursales AS s
    WHERE s.id_empresa = p_id_empresa
      AND s.id_sucursal = p_id_sucursal
      AND s.activa
  ) THEN
    RAISE EXCEPTION 'La sucursal no existe, está inactiva o no pertenece a la empresa.';
  END IF;

  SELECT pc.id_periodo, pc.estado
  INTO v_id_periodo, v_estado_periodo
  FROM public.periodos_contables AS pc
  WHERE pc.id_empresa = p_id_empresa
    AND p_fecha BETWEEN pc.fecha_inicio AND pc.fecha_fin;

  IF v_id_periodo IS NULL THEN
    RAISE EXCEPTION 'No existe un período contable para la fecha del comprobante.';
  END IF;

  IF v_estado_periodo <> 'ABIERTO' THEN
    RAISE EXCEPTION 'El período contable de la fecha está cerrado.';
  END IF;

  INSERT INTO public.comprobantes_contables (
    id_empresa, id_sucursal, id_periodo, tipo, fecha, descripcion,
    origen_tipo, origen_id, idempotencia_key, creado_por
  )
  VALUES (
    p_id_empresa, p_id_sucursal, v_id_periodo, p_tipo, p_fecha,
    trim(p_descripcion), p_origen_tipo, p_origen_id, p_idempotencia_key, v_usuario
  )
  RETURNING id_comprobante INTO v_id_comprobante;

  FOR v_line IN SELECT value FROM jsonb_array_elements(p_lineas)
  LOOP
    v_numero_linea := v_numero_linea + 1;
    v_id_cuenta := (v_line ->> 'id_cuenta')::bigint;
    v_debe := COALESCE((v_line ->> 'debe')::numeric, 0);
    v_haber := COALESCE((v_line ->> 'haber')::numeric, 0);

    IF v_debe < 0 OR v_haber < 0
       OR v_debe <> round(v_debe, 2)
       OR v_haber <> round(v_haber, 2)
       OR NOT ((v_debe > 0 AND v_haber = 0) OR (v_haber > 0 AND v_debe = 0)) THEN
      RAISE EXCEPTION 'Cada línea debe tener un monto positivo, con máximo dos decimales, en Debe o Haber.';
    END IF;

    IF NOT EXISTS (
      SELECT 1
      FROM public.cuentas_contables AS c
      WHERE c.id_empresa = p_id_empresa
        AND c.id_cuenta = v_id_cuenta
        AND c.activa
        AND NOT c.es_grupo
        AND c.permite_movimientos
    ) THEN
      RAISE EXCEPTION 'Una cuenta no existe, está inactiva, es de grupo o no permite movimientos.';
    END IF;

    INSERT INTO public.lineas_comprobante_contable (
      id_empresa, id_comprobante, id_cuenta, numero_linea,
      descripcion, debe, haber
    )
    VALUES (
      p_id_empresa, v_id_comprobante, v_id_cuenta, v_numero_linea,
      NULLIF(trim(v_line ->> 'descripcion'), ''), v_debe, v_haber
    );

    v_total_debe := v_total_debe + v_debe;
    v_total_haber := v_total_haber + v_haber;
  END LOOP;

  IF v_total_debe <> v_total_haber THEN
    RAISE EXCEPTION 'El comprobante no cuadra: Debe y Haber deben ser iguales.';
  END IF;

  RETURN v_id_comprobante;
END;
$$;

CREATE OR REPLACE FUNCTION public.contabilizar_comprobante(p_id_comprobante bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_periodo bigint;
  v_estado_comprobante text;
  v_estado_periodo text;
  v_cantidad bigint;
  v_debe numeric(14, 2);
  v_haber numeric(14, 2);
BEGIN
  SELECT c.id_empresa, c.id_periodo, c.estado
  INTO v_empresa, v_periodo, v_estado_comprobante
  FROM public.comprobantes_contables AS c
  WHERE c.id_comprobante = p_id_comprobante
  FOR UPDATE;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'El comprobante no existe.';
  END IF;

  IF v_usuario IS NULL
     OR (SELECT public.puede_administrar_empresa(v_empresa)) IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'No tienes permiso para contabilizar en esta empresa.';
  END IF;

  IF v_estado_comprobante <> 'BORRADOR' THEN
    RAISE EXCEPTION 'Solo se pueden contabilizar comprobantes en borrador.';
  END IF;

  SELECT pc.estado INTO v_estado_periodo
  FROM public.periodos_contables AS pc
  WHERE pc.id_periodo = v_periodo AND pc.id_empresa = v_empresa
  FOR UPDATE;

  IF v_estado_periodo IS DISTINCT FROM 'ABIERTO' THEN
    RAISE EXCEPTION 'El período contable está cerrado o no existe.';
  END IF;

  SELECT count(*), COALESCE(sum(l.debe), 0), COALESCE(sum(l.haber), 0)
  INTO v_cantidad, v_debe, v_haber
  FROM public.lineas_comprobante_contable AS l
  WHERE l.id_comprobante = p_id_comprobante
    AND l.id_empresa = v_empresa;

  IF v_cantidad < 2 THEN
    RAISE EXCEPTION 'El comprobante debe contener al menos dos líneas.';
  END IF;

  IF v_debe <> v_haber THEN
    RAISE EXCEPTION 'El comprobante no cuadra: Debe y Haber deben ser iguales.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.lineas_comprobante_contable AS l
    JOIN public.cuentas_contables AS c
      ON c.id_empresa = l.id_empresa
     AND c.id_cuenta = l.id_cuenta
    WHERE l.id_comprobante = p_id_comprobante
      AND (NOT c.activa OR c.es_grupo OR NOT c.permite_movimientos)
  ) THEN
    RAISE EXCEPTION 'Todas las cuentas del comprobante deben estar activas y permitir movimientos.';
  END IF;

  UPDATE public.comprobantes_contables
  SET estado = 'CONTABILIZADO',
      contabilizado_por = v_usuario,
      contabilizado_en = now()
  WHERE id_comprobante = p_id_comprobante
    AND id_empresa = v_empresa;
END;
$$;

CREATE OR REPLACE FUNCTION public.cancelar_comprobante_borrador(
  p_id_comprobante bigint,
  p_motivo text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_estado text;
BEGIN
  SELECT c.id_empresa, c.estado
  INTO v_empresa, v_estado
  FROM public.comprobantes_contables AS c
  WHERE c.id_comprobante = p_id_comprobante
  FOR UPDATE;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'El comprobante no existe.';
  END IF;

  IF v_usuario IS NULL
     OR (SELECT public.puede_administrar_empresa(v_empresa)) IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'No tienes permiso para cancelar comprobantes de esta empresa.';
  END IF;

  IF v_estado <> 'BORRADOR' THEN
    RAISE EXCEPTION 'Solo se pueden cancelar comprobantes en borrador.';
  END IF;

  IF p_motivo IS NULL OR char_length(trim(p_motivo)) < 3 THEN
    RAISE EXCEPTION 'El motivo de cancelación debe tener al menos tres caracteres.';
  END IF;

  UPDATE public.comprobantes_contables
  SET estado = 'CANCELADO',
      cancelado_por = v_usuario,
      cancelado_en = now(),
      motivo_cancelacion = trim(p_motivo)
  WHERE id_comprobante = p_id_comprobante
    AND id_empresa = v_empresa;
END;
$$;

CREATE OR REPLACE FUNCTION public.revertir_comprobante_contable(
  p_id_comprobante bigint,
  p_fecha_reversion date,
  p_motivo text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_periodo bigint;
  v_estado text;
  v_tipo text;
  v_reverso_de bigint;
  v_revertido_por bigint;
  v_id_reversion bigint;
BEGIN
  SELECT c.id_empresa, c.id_sucursal, c.estado, c.tipo,
         c.reverso_de_id, c.revertido_por_id
  INTO v_empresa, v_sucursal, v_estado, v_tipo, v_reverso_de, v_revertido_por
  FROM public.comprobantes_contables AS c
  WHERE c.id_comprobante = p_id_comprobante
  FOR UPDATE;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'El comprobante no existe.';
  END IF;

  IF v_usuario IS NULL
     OR (SELECT public.puede_administrar_empresa(v_empresa)) IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'No tienes permiso para revertir comprobantes de esta empresa.';
  END IF;

  IF v_estado <> 'CONTABILIZADO' THEN
    RAISE EXCEPTION 'Solo se pueden revertir comprobantes contabilizados.';
  END IF;

  IF v_tipo = 'REVERSION' OR v_reverso_de IS NOT NULL THEN
    RAISE EXCEPTION 'No se puede revertir un comprobante que ya es una reversión.';
  END IF;

  IF v_revertido_por IS NOT NULL THEN
    RAISE EXCEPTION 'Este comprobante ya fue revertido.';
  END IF;

  IF p_fecha_reversion IS NULL OR p_motivo IS NULL OR char_length(trim(p_motivo)) < 3 THEN
    RAISE EXCEPTION 'La fecha y un motivo de reversión de al menos tres caracteres son obligatorios.';
  END IF;

  SELECT pc.id_periodo INTO v_periodo
  FROM public.periodos_contables AS pc
  WHERE pc.id_empresa = v_empresa
    AND p_fecha_reversion BETWEEN pc.fecha_inicio AND pc.fecha_fin
    AND pc.estado = 'ABIERTO'
  FOR UPDATE;

  IF v_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha de reversión.';
  END IF;

  INSERT INTO public.comprobantes_contables (
    id_empresa, id_sucursal, id_periodo, tipo, fecha, descripcion,
    origen_tipo, origen_id, reverso_de_id, creado_por
  )
  SELECT v_empresa, v_sucursal, v_periodo, 'REVERSION', p_fecha_reversion,
         'Reversión de ' || c.numero || ': ' || trim(p_motivo),
         'COMPROBANTE', c.id_comprobante::text, c.id_comprobante, v_usuario
  FROM public.comprobantes_contables AS c
  WHERE c.id_comprobante = p_id_comprobante
  RETURNING id_comprobante INTO v_id_reversion;

  INSERT INTO public.lineas_comprobante_contable (
    id_empresa, id_comprobante, id_cuenta, numero_linea,
    descripcion, debe, haber
  )
  SELECT l.id_empresa, v_id_reversion, l.id_cuenta, l.numero_linea,
         'Reversión: ' || COALESCE(l.descripcion, c.descripcion),
         l.haber, l.debe
  FROM public.lineas_comprobante_contable AS l
  JOIN public.comprobantes_contables AS c
    ON c.id_empresa = l.id_empresa
   AND c.id_comprobante = l.id_comprobante
  WHERE l.id_comprobante = p_id_comprobante
    AND l.id_empresa = v_empresa
  ORDER BY l.numero_linea;

  PERFORM public.contabilizar_comprobante(v_id_reversion);

  UPDATE public.comprobantes_contables
  SET revertido_por_id = v_id_reversion
  WHERE id_empresa = v_empresa
    AND id_comprobante = p_id_comprobante;

  RETURN v_id_reversion;
END;
$$;

