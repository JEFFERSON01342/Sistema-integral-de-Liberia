CREATE TABLE public.cuentas_contables (
  id_cuenta bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  codigo text NOT NULL CHECK (char_length(trim(codigo)) > 0),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  naturaleza text NOT NULL
    CHECK (naturaleza IN ('ACTIVO', 'PASIVO', 'PATRIMONIO', 'INGRESO', 'COSTO', 'GASTO')),
  saldo_normal text NOT NULL
    CHECK (saldo_normal IN ('DEBE', 'HABER')),
  id_cuenta_padre bigint,
  es_grupo boolean NOT NULL DEFAULT false,
  permite_movimientos boolean NOT NULL DEFAULT true,
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cuentas_contables_empresa_codigo_key UNIQUE (id_empresa, codigo),
  CONSTRAINT cuentas_contables_empresa_id_key UNIQUE (id_empresa, id_cuenta),
  CONSTRAINT cuentas_contables_grupo_no_recibe_movimientos_check
    CHECK (NOT es_grupo OR NOT permite_movimientos),
  CONSTRAINT cuentas_contables_no_es_su_padre_check
    CHECK (id_cuenta_padre IS NULL OR id_cuenta_padre <> id_cuenta),
  CONSTRAINT cuentas_contables_padre_empresa_fkey
    FOREIGN KEY (id_empresa, id_cuenta_padre)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta)
);

CREATE TABLE public.periodos_contables (
  id_periodo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  anio integer NOT NULL,
  mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  fecha_inicio date NOT NULL,
  fecha_fin date NOT NULL,
  estado text NOT NULL DEFAULT 'ABIERTO'
    CHECK (estado IN ('ABIERTO', 'CERRADO')),
  cerrado_por uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  cerrado_en timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT periodos_contables_mes_key UNIQUE (id_empresa, anio, mes),
  CONSTRAINT periodos_contables_empresa_id_key UNIQUE (id_empresa, id_periodo),
  CONSTRAINT periodos_contables_fechas_mes_check CHECK (
    fecha_inicio = make_date(anio, mes, 1)
    AND fecha_fin = (make_date(anio, mes, 1) + interval '1 month - 1 day')::date
  ),
  CONSTRAINT periodos_contables_cierre_check CHECK (
    (estado = 'ABIERTO' AND cerrado_por IS NULL AND cerrado_en IS NULL)
    OR (estado = 'CERRADO' AND cerrado_por IS NOT NULL AND cerrado_en IS NOT NULL)
  )
);

CREATE TABLE public.comprobantes_contables (
  id_comprobante bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  id_sucursal integer NOT NULL,
  id_periodo bigint NOT NULL,
  numero text GENERATED ALWAYS AS ('CC-' || id_comprobante::text) STORED,
  tipo text NOT NULL
    CHECK (tipo IN ('APERTURA', 'VENTA', 'COMPRA', 'AJUSTE', 'DEVOLUCION', 'GASTO', 'PAGO', 'REVERSION', 'MANUAL', 'CIERRE')),
  fecha date NOT NULL,
  descripcion text NOT NULL CHECK (char_length(trim(descripcion)) > 0),
  estado text NOT NULL DEFAULT 'BORRADOR'
    CHECK (estado IN ('BORRADOR', 'CONTABILIZADO', 'CANCELADO')),
  origen_tipo text,
  origen_id text,
  idempotencia_key text,
  reverso_de_id bigint,
  revertido_por_id bigint,
  creado_por uuid NOT NULL DEFAULT auth.uid()
    REFERENCES auth.users (id) ON DELETE RESTRICT,
  creado_en timestamptz NOT NULL DEFAULT now(),
  contabilizado_por uuid REFERENCES auth.users (id) ON DELETE RESTRICT,
  contabilizado_en timestamptz,
  cancelado_por uuid REFERENCES auth.users (id) ON DELETE RESTRICT,
  cancelado_en timestamptz,
  motivo_cancelacion text,
  CONSTRAINT comprobantes_contables_empresa_numero_key UNIQUE (id_empresa, numero),
  CONSTRAINT comprobantes_contables_empresa_id_key UNIQUE (id_empresa, id_comprobante),
  CONSTRAINT comprobantes_contables_empresa_idempotencia_key
    UNIQUE (id_empresa, idempotencia_key),
  CONSTRAINT comprobantes_contables_un_reverso_key
    UNIQUE (id_empresa, reverso_de_id),
  CONSTRAINT comprobantes_contables_revertido_por_key
    UNIQUE (id_empresa, revertido_por_id),
  CONSTRAINT comprobantes_contables_origen_key
    UNIQUE (id_empresa, origen_tipo, origen_id),
  CONSTRAINT comprobantes_contables_sucursal_empresa_fkey
    FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal),
  CONSTRAINT comprobantes_contables_periodo_empresa_fkey
    FOREIGN KEY (id_empresa, id_periodo)
    REFERENCES public.periodos_contables (id_empresa, id_periodo),
  CONSTRAINT comprobantes_contables_reverso_empresa_fkey
    FOREIGN KEY (id_empresa, reverso_de_id)
    REFERENCES public.comprobantes_contables (id_empresa, id_comprobante),
  CONSTRAINT comprobantes_contables_revertido_por_empresa_fkey
    FOREIGN KEY (id_empresa, revertido_por_id)
    REFERENCES public.comprobantes_contables (id_empresa, id_comprobante),
  CONSTRAINT comprobantes_contables_tipo_reverso_check
    CHECK (reverso_de_id IS NULL OR (tipo = 'REVERSION' AND reverso_de_id <> id_comprobante)),
  CONSTRAINT comprobantes_contables_estado_detalle_check CHECK (
    (
      estado = 'BORRADOR'
      AND contabilizado_por IS NULL AND contabilizado_en IS NULL
      AND cancelado_por IS NULL AND cancelado_en IS NULL AND motivo_cancelacion IS NULL
    )
    OR (
      estado = 'CONTABILIZADO'
      AND contabilizado_por IS NOT NULL AND contabilizado_en IS NOT NULL
      AND cancelado_por IS NULL AND cancelado_en IS NULL AND motivo_cancelacion IS NULL
    )
    OR (
      estado = 'CANCELADO'
      AND contabilizado_por IS NULL AND contabilizado_en IS NULL
      AND cancelado_por IS NOT NULL AND cancelado_en IS NOT NULL
      AND char_length(trim(motivo_cancelacion)) >= 3
    )
  )
);

