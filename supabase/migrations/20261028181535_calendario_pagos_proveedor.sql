-- Fase 23: condiciones de pago configurables, calendario de cuotas y cuenta origen por pago.

BEGIN;

ALTER TABLE public.proveedores
  ADD COLUMN cantidad_cuotas_credito integer NOT NULL DEFAULT 1
    CHECK (cantidad_cuotas_credito BETWEEN 1 AND 120),
  ADD COLUMN frecuencia_cuotas_credito_dias integer NOT NULL DEFAULT 30
    CHECK (frecuencia_cuotas_credito_dias BETWEEN 1 AND 365),
  ADD COLUMN anticipo_credito_porcentaje numeric(5,2) NOT NULL DEFAULT 0
    CHECK (anticipo_credito_porcentaje BETWEEN 0 AND 99.99),
  ADD CONSTRAINT proveedores_anticipo_cuotas_check
    CHECK (anticipo_credito_porcentaje = 0 OR cantidad_cuotas_credito >= 2);

GRANT UPDATE (
  plazo_credito_dias, cantidad_cuotas_credito,
  frecuencia_cuotas_credito_dias, anticipo_credito_porcentaje
) ON TABLE public.proveedores TO authenticated;

CREATE TABLE public.cuotas_cuentas_por_pagar (
  id_cuota bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_cuenta_por_pagar bigint NOT NULL,
  numero_cuota integer NOT NULL CHECK (numero_cuota > 0),
  fecha_vencimiento date NOT NULL,
  monto numeric(14,2) NOT NULL CHECK (monto > 0),
  creada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id_cuenta_por_pagar, id_cuota),
  UNIQUE (id_empresa, id_cuenta_por_pagar, numero_cuota),
  FOREIGN KEY (id_empresa, id_cuenta_por_pagar)
    REFERENCES public.cuentas_por_pagar (id_empresa, id_cuenta_por_pagar)
);

ALTER TABLE public.pagos_proveedor
  ADD COLUMN id_cuenta_pago bigint;

DROP TRIGGER pagos_proveedor_inmutables ON public.pagos_proveedor;

UPDATE public.pagos_proveedor p
SET id_cuenta_pago = c.id_cuenta
FROM public.cuentas_contables c
WHERE c.id_empresa = p.id_empresa
  AND c.codigo = CASE p.metodo_pago
    WHEN 'EFECTIVO' THEN '1.1.02'
    ELSE '1.1.04'
  END;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.pagos_proveedor
    WHERE id_cuenta_pago IS NULL
  ) THEN
    RAISE EXCEPTION
      'No se pudo asociar una cuenta contable a todos los pagos existentes.';
  END IF;
END;
$$;

ALTER TABLE public.pagos_proveedor
  ALTER COLUMN id_cuenta_pago SET NOT NULL,
  ADD CONSTRAINT pagos_proveedor_cuenta_pago_empresa_fkey
    FOREIGN KEY (id_empresa, id_cuenta_pago)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta);

CREATE TRIGGER pagos_proveedor_inmutables
BEFORE UPDATE OR DELETE ON public.pagos_proveedor
FOR EACH ROW EXECUTE FUNCTION public.proteger_documento_operativo_inmutable();

ALTER TABLE public.aplicaciones_pago_proveedor
  ADD CONSTRAINT aplicaciones_pago_proveedor_empresa_pago_cxp_key
    UNIQUE (id_empresa, id_pago_proveedor, id_cuenta_por_pagar);

CREATE TABLE public.aplicaciones_pago_cuota_proveedor (
  id_empresa integer NOT NULL,
  id_pago_proveedor bigint NOT NULL,
  id_cuenta_por_pagar bigint NOT NULL,
  id_cuota bigint NOT NULL,
  monto numeric(14,2) NOT NULL CHECK (monto > 0),
  PRIMARY KEY (id_pago_proveedor, id_cuota),
  FOREIGN KEY (id_empresa, id_pago_proveedor, id_cuenta_por_pagar)
    REFERENCES public.aplicaciones_pago_proveedor
      (id_empresa, id_pago_proveedor, id_cuenta_por_pagar),
  FOREIGN KEY (id_empresa, id_cuenta_por_pagar, id_cuota)
    REFERENCES public.cuotas_cuentas_por_pagar
      (id_empresa, id_cuenta_por_pagar, id_cuota)
);

CREATE INDEX cuotas_cuentas_por_pagar_vencimiento_idx
  ON public.cuotas_cuentas_por_pagar
    (id_empresa, id_cuenta_por_pagar, fecha_vencimiento, numero_cuota);
CREATE INDEX aplicaciones_pago_cuota_proveedor_cuota_idx
  ON public.aplicaciones_pago_cuota_proveedor (id_empresa, id_cuota);

CREATE OR REPLACE FUNCTION public.generar_calendario_cxp(
  p_id_cuenta_por_pagar bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_cxp record;
  v_numero_cuotas integer;
  v_frecuencia integer;
  v_porcentaje_anticipo numeric(5,2);
  v_cuotas_regulares integer;
  v_anticipo numeric(14,2);
  v_restante numeric(14,2);
  v_importe_cuota numeric(14,2);
  v_fecha_base date;
  v_numero integer;
BEGIN
  SELECT c.id_empresa, c.id_cuenta_por_pagar, c.id_proveedor,
         c.fecha_emision, c.fecha_vencimiento, c.total,
         p.cantidad_cuotas_credito, p.frecuencia_cuotas_credito_dias,
         p.anticipo_credito_porcentaje
  INTO v_cxp
  FROM public.cuentas_por_pagar c
  JOIN public.proveedores p
    ON p.id_empresa = c.id_empresa AND p.id_proveedor = c.id_proveedor
  WHERE c.id_cuenta_por_pagar = p_id_cuenta_por_pagar;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'No se encontro la cuenta por pagar para generar su calendario.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.cuotas_cuentas_por_pagar q
    WHERE q.id_empresa = v_cxp.id_empresa
      AND q.id_cuenta_por_pagar = p_id_cuenta_por_pagar
  ) THEN
    RETURN;
  END IF;

  v_numero_cuotas := v_cxp.cantidad_cuotas_credito;
  v_frecuencia := v_cxp.frecuencia_cuotas_credito_dias;
  v_porcentaje_anticipo := v_cxp.anticipo_credito_porcentaje;
  IF v_numero_cuotas NOT BETWEEN 1 AND 120
     OR v_frecuencia NOT BETWEEN 1 AND 365
     OR v_porcentaje_anticipo NOT BETWEEN 0 AND 99.99
     OR (v_porcentaje_anticipo > 0 AND v_numero_cuotas < 2) THEN
    RAISE EXCEPTION 'Las condiciones de cuotas del proveedor no son validas.';
  END IF;

  IF v_porcentaje_anticipo > 0 THEN
    v_anticipo := round(v_cxp.total * v_porcentaje_anticipo / 100, 2);
    IF v_anticipo <= 0 OR v_anticipo >= v_cxp.total THEN
      RAISE EXCEPTION 'El anticipo configurado no produce un calendario de cuotas valido para el total de la cuenta.';
    END IF;
    v_restante := v_cxp.total - v_anticipo;
    v_cuotas_regulares := v_numero_cuotas - 1;
    v_fecha_base := v_cxp.fecha_vencimiento;
    INSERT INTO public.cuotas_cuentas_por_pagar (
      id_empresa, id_cuenta_por_pagar, numero_cuota, fecha_vencimiento, monto
    )
    VALUES (
      v_cxp.id_empresa, p_id_cuenta_por_pagar, 1, v_cxp.fecha_emision, v_anticipo
    );
    v_importe_cuota := round(v_restante / v_cuotas_regulares, 2);
    FOR v_numero IN 1..v_cuotas_regulares LOOP
      INSERT INTO public.cuotas_cuentas_por_pagar (
        id_empresa, id_cuenta_por_pagar, numero_cuota, fecha_vencimiento, monto
      )
      VALUES (
        v_cxp.id_empresa, p_id_cuenta_por_pagar, v_numero + 1,
        v_fecha_base + ((v_numero - 1) * v_frecuencia),
        CASE WHEN v_numero = v_cuotas_regulares
          THEN v_restante - (v_importe_cuota * (v_cuotas_regulares - 1))
          ELSE v_importe_cuota
        END
      );
    END LOOP;
  ELSE
    v_cuotas_regulares := v_numero_cuotas;
    v_importe_cuota := round(v_cxp.total / v_cuotas_regulares, 2);
    FOR v_numero IN 1..v_cuotas_regulares LOOP
      INSERT INTO public.cuotas_cuentas_por_pagar (
        id_empresa, id_cuenta_por_pagar, numero_cuota, fecha_vencimiento, monto
      )
      VALUES (
        v_cxp.id_empresa, p_id_cuenta_por_pagar, v_numero,
        v_cxp.fecha_vencimiento + ((v_numero - 1) * v_frecuencia),
        CASE WHEN v_numero = v_cuotas_regulares
          THEN v_cxp.total - (v_importe_cuota * (v_cuotas_regulares - 1))
          ELSE v_importe_cuota
        END
      );
    END LOOP;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.generar_calendario_cxp(bigint)
  FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.crear_calendario_cxp_al_insertar()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  PERFORM public.generar_calendario_cxp(NEW.id_cuenta_por_pagar);
  RETURN NEW;
END;
$$;

CREATE TRIGGER cuentas_por_pagar_generar_calendario
AFTER INSERT ON public.cuentas_por_pagar
FOR EACH ROW EXECUTE FUNCTION public.crear_calendario_cxp_al_insertar();
REVOKE ALL ON FUNCTION public.crear_calendario_cxp_al_insertar()
  FROM PUBLIC, anon, authenticated, service_role;

INSERT INTO public.cuotas_cuentas_por_pagar (
  id_empresa, id_cuenta_por_pagar, numero_cuota, fecha_vencimiento, monto
)
SELECT c.id_empresa, c.id_cuenta_por_pagar, 1, c.fecha_vencimiento, c.total
FROM public.cuentas_por_pagar c
WHERE NOT EXISTS (
  SELECT 1 FROM public.cuotas_cuentas_por_pagar q
  WHERE q.id_empresa = c.id_empresa
    AND q.id_cuenta_por_pagar = c.id_cuenta_por_pagar
);

INSERT INTO public.aplicaciones_pago_cuota_proveedor (
  id_empresa, id_pago_proveedor, id_cuenta_por_pagar, id_cuota, monto
)
SELECT a.id_empresa, a.id_pago_proveedor, a.id_cuenta_por_pagar,
       q.id_cuota, a.monto
FROM public.aplicaciones_pago_proveedor a
JOIN public.cuotas_cuentas_por_pagar q
  ON q.id_empresa = a.id_empresa
 AND q.id_cuenta_por_pagar = a.id_cuenta_por_pagar
 AND q.numero_cuota = 1;

CREATE OR REPLACE VIEW public.calendario_saldos_cuentas_por_pagar
WITH (security_invoker = true)
AS
SELECT q.id_empresa, q.id_cuenta_por_pagar, q.id_cuota, q.numero_cuota,
       q.fecha_vencimiento, q.monto,
       COALESCE(sum(a.monto), 0)::numeric(14,2) AS monto_pagado,
       (q.monto - COALESCE(sum(a.monto), 0))::numeric(14,2) AS saldo_pendiente,
       GREATEST(((clock_timestamp() AT TIME ZONE e.zona_horaria)::date
         - q.fecha_vencimiento), 0) AS dias_vencidos,
       CASE
         WHEN q.monto = COALESCE(sum(a.monto), 0) THEN 'PAGADA'
         WHEN q.fecha_vencimiento < (clock_timestamp() AT TIME ZONE e.zona_horaria)::date THEN 'VENCIDA'
         ELSE 'PENDIENTE'
       END AS estado
FROM public.cuotas_cuentas_por_pagar q
JOIN public.empresa e ON e.id_empresa = q.id_empresa
LEFT JOIN public.aplicaciones_pago_cuota_proveedor a
  ON a.id_empresa = q.id_empresa AND a.id_cuota = q.id_cuota
GROUP BY q.id_empresa, q.id_cuenta_por_pagar, q.id_cuota, e.zona_horaria;

ALTER TABLE public.cuotas_cuentas_por_pagar ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aplicaciones_pago_cuota_proveedor ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cuotas_cuentas_por_pagar,
  public.aplicaciones_pago_cuota_proveedor,
  public.calendario_saldos_cuentas_por_pagar
  FROM anon, authenticated;
GRANT SELECT ON TABLE public.cuotas_cuentas_por_pagar,
  public.aplicaciones_pago_cuota_proveedor,
  public.calendario_saldos_cuentas_por_pagar
  TO authenticated;
