-- Ejecutar solo una vez y solo en el proyecto NUEVO de Supabase,
-- después de 001_auth_perfiles.sql.

BEGIN;

CREATE TABLE public.empresa (
  id_empresa integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  moneda_codigo text NOT NULL DEFAULT 'NIO'
    CHECK (moneda_codigo ~ '^[A-Z]{3}$'),
  zona_horaria text NOT NULL DEFAULT 'America/Managua',
  activa boolean NOT NULL DEFAULT true,
  creado_por uuid NOT NULL DEFAULT auth.uid()
    REFERENCES auth.users (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.sucursales (
  id_sucursal integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  codigo text NOT NULL CHECK (char_length(trim(codigo)) > 0),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  direccion text,
  telefono text,
  es_principal boolean NOT NULL DEFAULT false,
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sucursales_empresa_codigo_key UNIQUE (id_empresa, codigo),
  CONSTRAINT sucursales_empresa_id_key UNIQUE (id_empresa, id_sucursal)
);

CREATE UNIQUE INDEX sucursales_una_principal_por_empresa
  ON public.sucursales (id_empresa)
  WHERE es_principal;

CREATE TABLE public.bodegas (
  id_bodega bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  codigo text NOT NULL CHECK (char_length(trim(codigo)) > 0),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  descripcion text,
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bodegas_una_por_sucursal_key UNIQUE (id_sucursal),
  CONSTRAINT bodegas_empresa_codigo_key UNIQUE (id_empresa, codigo),
  CONSTRAINT bodegas_empresa_sucursal_id_key
    UNIQUE (id_empresa, id_sucursal, id_bodega),
  CONSTRAINT bodegas_sucursal_empresa_fkey
    FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal)
);

CREATE TABLE public.ubicaciones_bodega (
  id_ubicacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_bodega bigint NOT NULL,
  codigo text NOT NULL CHECK (char_length(trim(codigo)) > 0),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  tipo_area text NOT NULL DEFAULT 'ALMACENAMIENTO'
    CHECK (tipo_area IN ('RECEPCION', 'ALMACENAMIENTO', 'PICKING', 'DESPACHO', 'DEVOLUCIONES')),
  pasillo text,
  estante text,
  nivel text,
  posicion text,
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ubicaciones_bodega_codigo_key UNIQUE (id_bodega, codigo),
  CONSTRAINT ubicaciones_bodega_empresa_sucursal_fkey
    FOREIGN KEY (id_empresa, id_sucursal, id_bodega)
    REFERENCES public.bodegas (id_empresa, id_sucursal, id_bodega)
);

CREATE INDEX sucursales_empresa_idx ON public.sucursales (id_empresa);
CREATE INDEX bodegas_empresa_sucursal_idx ON public.bodegas (id_empresa, id_sucursal);
CREATE INDEX ubicaciones_empresa_sucursal_idx
  ON public.ubicaciones_bodega (id_empresa, id_sucursal, id_bodega);

ALTER TABLE public.perfiles
  ADD CONSTRAINT perfiles_empresa_fkey
    FOREIGN KEY (id_empresa) REFERENCES public.empresa (id_empresa),
  ADD CONSTRAINT perfiles_empresa_sucursal_fkey
    FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal),
  ADD CONSTRAINT perfiles_sucursal_requiere_empresa_check
    CHECK (id_sucursal IS NULL OR id_empresa IS NOT NULL);

CREATE OR REPLACE FUNCTION public.es_superadmin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.perfiles AS p
    WHERE p.id = (SELECT auth.uid())
      AND p.activo
      AND p.rol = 'superadmin'
  );
$$;

CREATE OR REPLACE FUNCTION public.puede_ver_empresa(p_id_empresa integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.perfiles AS p
    WHERE p.id = (SELECT auth.uid())
      AND p.activo
      AND p.rol IN ('superadmin', 'admin', 'gerente', 'cajero', 'despacho', 'vendedor')
      AND (p.rol = 'superadmin' OR p.id_empresa = p_id_empresa)
  );
$$;

CREATE OR REPLACE FUNCTION public.puede_administrar_empresa(p_id_empresa integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.perfiles AS p
    WHERE p.id = (SELECT auth.uid())
      AND p.activo
      AND p.rol IN ('superadmin', 'admin')
      AND (p.rol = 'superadmin' OR p.id_empresa = p_id_empresa)
  );
$$;

REVOKE ALL ON FUNCTION public.es_superadmin() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.puede_ver_empresa(integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.puede_administrar_empresa(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.es_superadmin() TO authenticated;
GRANT EXECUTE ON FUNCTION public.puede_ver_empresa(integer) TO authenticated;
GRANT EXECUTE ON FUNCTION public.puede_administrar_empresa(integer) TO authenticated;

ALTER TABLE public.empresa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sucursales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bodegas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ubicaciones_bodega ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.empresa, public.sucursales, public.bodegas,
  public.ubicaciones_bodega FROM anon, authenticated;

GRANT SELECT, INSERT ON TABLE public.empresa TO authenticated;
GRANT UPDATE (nombre, moneda_codigo, zona_horaria, activa)
  ON TABLE public.empresa TO authenticated;

GRANT SELECT, INSERT ON TABLE public.sucursales TO authenticated;
GRANT UPDATE (codigo, nombre, direccion, telefono, es_principal, activa)
  ON TABLE public.sucursales TO authenticated;

GRANT SELECT, INSERT ON TABLE public.bodegas TO authenticated;
GRANT UPDATE (codigo, nombre, descripcion, activa)
  ON TABLE public.bodegas TO authenticated;

GRANT SELECT, INSERT ON TABLE public.ubicaciones_bodega TO authenticated;
GRANT UPDATE (
  codigo, nombre, tipo_area, pasillo, estante, nivel, posicion, activa
) ON TABLE public.ubicaciones_bodega TO authenticated;

CREATE OR REPLACE FUNCTION public.actualizar_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER empresa_actualizar_updated_at
BEFORE UPDATE ON public.empresa
FOR EACH ROW
EXECUTE FUNCTION public.actualizar_updated_at();

CREATE TRIGGER sucursales_actualizar_updated_at
BEFORE UPDATE ON public.sucursales
FOR EACH ROW
EXECUTE FUNCTION public.actualizar_updated_at();

CREATE TRIGGER bodegas_actualizar_updated_at
BEFORE UPDATE ON public.bodegas
FOR EACH ROW
EXECUTE FUNCTION public.actualizar_updated_at();

CREATE TRIGGER ubicaciones_actualizar_updated_at
BEFORE UPDATE ON public.ubicaciones_bodega
FOR EACH ROW
EXECUTE FUNCTION public.actualizar_updated_at();

REVOKE ALL ON FUNCTION public.actualizar_updated_at() FROM PUBLIC;

CREATE POLICY empresa_select_por_empresa
ON public.empresa
FOR SELECT
TO authenticated
