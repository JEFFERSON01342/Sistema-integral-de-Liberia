CREATE OR REPLACE FUNCTION public.validar_asignacion_caja()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.activo AND NOT NEW.activo AND EXISTS (
    SELECT 1
    FROM public.sesiones_caja s
    WHERE s.id_caja = OLD.id_caja
      AND s.estado = 'ABIERTA'
  ) THEN
    RAISE EXCEPTION 'No se puede quitar la asignación mientras la caja tenga una sesión abierta.';
  END IF;
  IF NEW.activo AND (
    NOT EXISTS (
      SELECT 1
      FROM public.cajas c
      WHERE c.id_empresa = NEW.id_empresa
        AND c.id_sucursal = NEW.id_sucursal
        AND c.id_caja = NEW.id_caja
        AND c.activa
    )
    OR NOT EXISTS (
      SELECT 1
      FROM public.perfiles p
      WHERE p.id = NEW.id_cajero
        AND p.id_empresa = NEW.id_empresa
        AND p.id_sucursal = NEW.id_sucursal
        AND p.rol = 'cajero'
        AND p.activo
    )
  ) THEN
    RAISE EXCEPTION 'La caja debe estar activa y el cajero debe pertenecer a la sucursal.';
  END IF;
  RETURN NEW;
END;
$$;

