CREATE OR REPLACE FUNCTION public.reintegrar_retiro_deposito_revertido()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_transferencia public.transferencias_caja_banco%ROWTYPE;
  v_sesion public.sesiones_caja%ROWTYPE;
  v_ahora timestamptz := clock_timestamp();
BEGIN
  IF NEW.revertido_por_id IS NOT DISTINCT FROM OLD.revertido_por_id THEN
    RETURN NEW;
  END IF;
  SELECT t.* INTO v_transferencia
  FROM public.transferencias_caja_banco t
  WHERE t.id_empresa = NEW.id_empresa
    AND t.id_comprobante = NEW.id_comprobante;
  IF NOT FOUND OR v_transferencia.id_sesion IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT s.* INTO v_sesion
  FROM public.sesiones_caja s
  WHERE s.id_sesion = v_transferencia.id_sesion
  FOR UPDATE;
  IF NOT FOUND OR v_sesion.estado <> 'ABIERTA' THEN
    RAISE EXCEPTION 'No se puede revertir este depósito: la sesión POS vinculada ya no está abierta.';
  END IF;

  INSERT INTO public.movimientos_caja (
    id_empresa, id_sucursal, id_caja, id_sesion, tipo, monto,
    descripcion, fecha_operativa, registrado_en, registrado_por,
    origen_tipo, origen_id, idempotencia_key
  )
  VALUES (
    v_transferencia.id_empresa,
    v_transferencia.id_sucursal,
    v_sesion.id_caja,
    v_sesion.id_sesion,
    'INGRESO',
    v_transferencia.monto,
    'Reintegro de depósito revertido: ' || v_transferencia.descripcion,
    (v_ahora AT TIME ZONE v_sesion.zona_horaria)::date,
    v_ahora,
    (SELECT auth.uid()),
    'REVERSION_DEPOSITO_CAJA_BANCO',
    NEW.revertido_por_id::text,
    'REV-TRASLADO-' || NEW.revertido_por_id::text
  );
  RETURN NEW;
END;
$$;

CREATE TRIGGER comprobante_revertido_reintegrar_retiro
AFTER UPDATE OF revertido_por_id ON public.comprobantes_contables
FOR EACH ROW EXECUTE FUNCTION public.reintegrar_retiro_deposito_revertido();

