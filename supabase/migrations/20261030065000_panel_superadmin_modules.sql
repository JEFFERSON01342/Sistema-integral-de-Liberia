CREATE OR REPLACE FUNCTION public.preparar_ticket_it()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_perfil public.perfiles%ROWTYPE;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT p.* INTO v_perfil
    FROM public.perfiles p
    WHERE p.id = (SELECT auth.uid())
      AND p.activo;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Se requiere un perfil activo para crear tickets.';
    END IF;
    IF NEW.id_usuario IS DISTINCT FROM (SELECT auth.uid()) THEN
      RAISE EXCEPTION 'El autor del ticket debe ser el usuario autenticado.';
    END IF;
    IF v_perfil.rol = 'superadmin' THEN
      IF NEW.id_empresa IS NULL
         OR NOT (SELECT public.puede_ver_empresa(NEW.id_empresa)) THEN
        RAISE EXCEPTION 'Selecciona una empresa válida para el ticket.';
      END IF;
      NEW.id_sucursal := NULL;
    ELSE
      IF v_perfil.id_empresa IS NULL THEN
        RAISE EXCEPTION 'El perfil debe estar asociado a una empresa para crear tickets.';
      END IF;
      NEW.id_empresa := v_perfil.id_empresa;
      NEW.id_sucursal := v_perfil.id_sucursal;
    END IF;
  ELSE
    NEW.id_empresa := OLD.id_empresa;
    NEW.id_sucursal := OLD.id_sucursal;
    NEW.id_usuario := OLD.id_usuario;
    NEW.created_at := OLD.created_at;
    NEW.updated_at := clock_timestamp();
  END IF;
  RETURN NEW;
END;
$$;

