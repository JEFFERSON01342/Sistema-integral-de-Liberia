CREATE OR REPLACE FUNCTION public.asignar_caja_cajero(
  p_id_caja bigint,
  p_id_cajero uuid,
  p_turno text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_id_asignacion bigint;
BEGIN
  IF v_usuario IS NULL
     OR p_turno IS NULL
     OR p_turno NOT IN ('Mañana', 'Tarde', 'Completo') THEN
    RAISE EXCEPTION 'La sesión o el turno de la asignación no son válidos.';
  END IF;
  SELECT c.id_empresa, c.id_sucursal
  INTO v_empresa, v_sucursal
  FROM public.cajas c
  WHERE c.id_caja = p_id_caja
    AND c.activa
  FOR UPDATE;
  IF v_empresa IS NULL
     OR NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, true)) THEN
    RAISE EXCEPTION 'No tienes permiso para asignar esta caja.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.sesiones_caja s
    WHERE s.id_caja = p_id_caja
      AND s.estado = 'ABIERTA'
  ) THEN
    RAISE EXCEPTION 'No se puede reasignar una caja con una sesión abierta.';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.perfiles p
    WHERE p.id = p_id_cajero
      AND p.id_empresa = v_empresa
      AND p.id_sucursal = v_sucursal
      AND p.rol = 'cajero'
      AND p.activo
  ) THEN
    RAISE EXCEPTION 'El usuario seleccionado no es un cajero activo de esta sucursal.';
  END IF;

  UPDATE public.asignaciones_caja
  SET activo = false
  WHERE id_empresa = v_empresa
    AND id_sucursal = v_sucursal
    AND id_caja = p_id_caja
    AND activo;

  INSERT INTO public.asignaciones_caja (
    id_empresa, id_sucursal, id_caja, id_cajero, turno, activo, creada_por
  )
  VALUES (
    v_empresa, v_sucursal, p_id_caja, p_id_cajero, p_turno, true, v_usuario
  )
  RETURNING id INTO v_id_asignacion;
  RETURN v_id_asignacion;
END;
$$;

REVOKE ALL ON FUNCTION public.asignar_caja_cajero(bigint, uuid, text)
  FROM PUBLIC, anon, authenticated, service_role;
