CREATE OR REPLACE FUNCTION public.sp_registrar_pago_gasto_fijo(
  p_id_gasto_fijo bigint,
  p_id_sucursal integer,
  p_monto_real numeric,
  p_fecha_pago date,
  p_id_cuenta_pago bigint,
  p_clave_idempotencia text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_cuenta_gasto bigint;
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
  v_huella text;
  v_existente bigint;
  v_huella_existente text;
  v_id_pago bigint;
  v_id_comprobante bigint;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para registrar un pago.';
  END IF;
  IF p_monto_real IS NULL OR p_monto_real <= 0
     OR p_monto_real <> round(p_monto_real, 2)
     OR p_fecha_pago IS NULL
     OR char_length(v_clave) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'El monto, la fecha o la clave de idempotencia no son válidos.';
  END IF;

  SELECT g.id_empresa, g.id_cuenta_gasto
  INTO v_empresa, v_cuenta_gasto
  FROM public.gastos_fijos g
  WHERE g.id_gasto_fijo = p_id_gasto_fijo
    AND g.activa;
  IF v_empresa IS NULL
     OR NOT (SELECT public.puede_operar_caja(v_empresa, p_id_sucursal, true)) THEN
    RAISE EXCEPTION 'No tienes permiso para registrar este pago.';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.sucursales s
    WHERE s.id_empresa = v_empresa
      AND s.id_sucursal = p_id_sucursal
      AND s.activa
  ) THEN
    RAISE EXCEPTION 'La sucursal no existe o está inactiva.';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.cuentas_contables c
    WHERE c.id_empresa = v_empresa
      AND c.id_cuenta = v_cuenta_gasto
      AND c.naturaleza = 'GASTO'
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos
  ) OR NOT EXISTS (
    SELECT 1
    FROM public.cuentas_contables c
    WHERE c.id_empresa = v_empresa
      AND c.id_cuenta = p_id_cuenta_pago
      AND c.naturaleza = 'ACTIVO'
      AND (c.es_efectivo OR c.es_banco)
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos
  ) THEN
    RAISE EXCEPTION 'Selecciona cuentas activas de gasto y de caja o banco.';
  END IF;

  v_huella := md5(
    p_id_gasto_fijo::text || '|' || p_id_sucursal::text || '|'
    || p_monto_real::text || '|' || p_fecha_pago::text || '|'
    || p_id_cuenta_pago::text
  );
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('PGF:' || v_empresa::text || ':' || v_clave, 0)
  );
  SELECT p.id_pago_gasto_fijo, p.huella_solicitud
  INTO v_existente, v_huella_existente
  FROM public.pagos_gastos_fijos p
  WHERE p.id_empresa = v_empresa
    AND p.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_huella_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó con datos distintos.';
    END IF;
    RETURN v_existente;
  END IF;

  v_id_pago := nextval(
    pg_get_serial_sequence('public.pagos_gastos_fijos', 'id_pago_gasto_fijo')::regclass
  );
  v_id_comprobante := public._registrar_asiento_operativo(
    v_empresa,
    p_id_sucursal,
    p_fecha_pago,
    'PAGO',
    'Pago de gasto fijo GF-' || v_id_pago::text,
    'PAGO_GASTO_FIJO',
    v_clave,
    jsonb_build_array(
      jsonb_build_object(
        'id_cuenta', v_cuenta_gasto,
        'debe', p_monto_real,
        'haber', 0,
        'descripcion', 'Gasto fijo'
      ),
      jsonb_build_object(
        'id_cuenta', p_id_cuenta_pago,
        'debe', 0,
        'haber', p_monto_real,
        'descripcion', 'Pago de gasto fijo'
      )
    )
  );

  INSERT INTO public.pagos_gastos_fijos (
    id_pago_gasto_fijo, id_empresa, id_sucursal, id_gasto_fijo,
    fecha_pago, monto_real, id_cuenta_pago, id_comprobante,
    clave_idempotencia, huella_solicitud, registrado_por
  )
  VALUES (
    v_id_pago, v_empresa, p_id_sucursal, p_id_gasto_fijo,
    p_fecha_pago, p_monto_real, p_id_cuenta_pago, v_id_comprobante,
    v_clave, v_huella, v_usuario
  );

  UPDATE public.gastos_fijos
  SET fecha_ultimo_registro = GREATEST(
        COALESCE(fecha_ultimo_registro, p_fecha_pago),
        p_fecha_pago
      ),
      updated_at = clock_timestamp()
  WHERE id_empresa = v_empresa
    AND id_gasto_fijo = p_id_gasto_fijo;

  RETURN v_id_pago;
END;
$$;

