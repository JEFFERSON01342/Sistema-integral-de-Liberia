CREATE OR REPLACE FUNCTION public.registrar_deposito_caja_banco(
  p_id_sucursal integer,
  p_id_cuenta_caja bigint,
  p_id_cuenta_banco bigint,
  p_monto numeric,
  p_fecha date,
  p_descripcion text,
  p_referencia text,
  p_id_sesion bigint,
  p_clave_idempotencia text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_zona text;
  v_fecha_actual date;
  v_descripcion text := trim(COALESCE(p_descripcion, ''));
  v_descripcion_contable text;
  v_referencia text := NULLIF(trim(COALESCE(p_referencia, '')), '');
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
  v_huella text;
  v_existente bigint;
  v_huella_existente text;
  v_id_transferencia bigint;
  v_id_comprobante bigint;
  v_saldo_caja numeric(14,2);
  v_saldo_sesion numeric(14,2);
  v_sesion record;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para registrar el depósito.';
  END IF;
  IF p_monto IS NULL OR p_monto <= 0
     OR p_monto <> round(p_monto, 2)
     OR p_fecha IS NULL
     OR char_length(v_descripcion) NOT BETWEEN 3 AND 240
     OR char_length(COALESCE(v_referencia, '')) > 120
     OR char_length(v_clave) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'El monto, fecha, descripción, referencia o clave no son válidos.';
  END IF;
  v_descripcion_contable := concat_ws(
    ' · ',
    v_descripcion,
    CASE WHEN v_referencia IS NOT NULL THEN 'Referencia: ' || v_referencia END
  );

  SELECT s.id_empresa, e.zona_horaria
  INTO v_empresa, v_zona
  FROM public.sucursales s
  JOIN public.empresa e ON e.id_empresa = s.id_empresa AND e.activa
  WHERE s.id_sucursal = p_id_sucursal
    AND s.activa;
  IF v_empresa IS NULL
     OR NOT (SELECT public.puede_operar_caja(v_empresa, p_id_sucursal, true)) THEN
    RAISE EXCEPTION 'Solo un administrador o gerente puede registrar depósitos en esta sucursal activa.';
  END IF;

  v_fecha_actual := (clock_timestamp() AT TIME ZONE v_zona)::date;
  IF p_fecha > v_fecha_actual THEN
    RAISE EXCEPTION 'La fecha del depósito no puede estar en el futuro.';
  END IF;

  v_huella := md5(concat_ws('|',
    p_id_sucursal::text,
    p_id_cuenta_caja::text,
    p_id_cuenta_banco::text,
    p_monto::numeric(14,2)::text,
    p_fecha::text,
    v_descripcion,
    COALESCE(v_referencia, ''),
    COALESCE(p_id_sesion::text, '')
  ));
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('DCB:' || v_empresa::text || ':' || v_clave, 0)
  );
  SELECT t.id_transferencia, t.huella_solicitud
  INTO v_existente, v_huella_existente
  FROM public.transferencias_caja_banco t
  WHERE t.id_empresa = v_empresa
    AND t.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_huella_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó con datos distintos.';
    END IF;
    RETURN v_existente;
  END IF;

  PERFORM c.id_cuenta
  FROM public.cuentas_contables c
  WHERE c.id_empresa = v_empresa
    AND c.id_cuenta IN (p_id_cuenta_caja, p_id_cuenta_banco)
  ORDER BY c.id_cuenta
  FOR UPDATE;

  IF NOT EXISTS (
    SELECT 1
    FROM public.cuentas_contables c
    WHERE c.id_empresa = v_empresa
      AND c.id_cuenta = p_id_cuenta_caja
      AND c.naturaleza = 'ACTIVO'
      AND c.es_efectivo
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos
  ) OR NOT EXISTS (
    SELECT 1
    FROM public.cuentas_contables c
    WHERE c.id_empresa = v_empresa
      AND c.id_cuenta = p_id_cuenta_banco
      AND c.naturaleza = 'ACTIVO'
      AND c.es_banco
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos
  ) THEN
    RAISE EXCEPTION 'El origen debe ser una cuenta activa de efectivo y el destino una cuenta bancaria activa.';
  END IF;

  SELECT COALESCE(sum(l.debe - l.haber), 0)::numeric(14,2)
  INTO v_saldo_caja
  FROM public.lineas_comprobante_contable l
  JOIN public.comprobantes_contables c
    ON c.id_empresa = l.id_empresa
   AND c.id_comprobante = l.id_comprobante
  WHERE l.id_empresa = v_empresa
    AND l.id_cuenta = p_id_cuenta_caja
    AND c.estado = 'CONTABILIZADO'
    AND c.fecha <= p_fecha;
  IF v_saldo_caja < p_monto THEN
    RAISE EXCEPTION 'El saldo contable de la cuenta de efectivo no cubre el depósito.';
  END IF;

  IF p_id_sesion IS NOT NULL THEN
    SELECT s.id_empresa, s.id_sucursal, s.id_caja, s.estado, s.zona_horaria
    INTO v_sesion
    FROM public.sesiones_caja s
    WHERE s.id_sesion = p_id_sesion
    FOR UPDATE;
    IF v_sesion.id_empresa IS DISTINCT FROM v_empresa
       OR v_sesion.id_sucursal IS DISTINCT FROM p_id_sucursal
       OR v_sesion.estado IS DISTINCT FROM 'ABIERTA' THEN
      RAISE EXCEPTION 'La sesión seleccionada debe estar abierta en la sucursal del depósito.';
    END IF;
    IF NOT (SELECT public.puede_operar_caja(v_empresa, p_id_sucursal, true)) THEN
      RAISE EXCEPTION 'No tienes permiso para registrar el retiro en esta sesión.';
    END IF;
    SELECT COALESCE(sum(
      CASE
        WHEN m.tipo IN ('APERTURA', 'INGRESO', 'VENTA_EFECTIVO')
          THEN m.monto
        ELSE -m.monto
      END
    ), 0)::numeric(14,2)
    INTO v_saldo_sesion
    FROM public.movimientos_caja m
    WHERE m.id_sesion = p_id_sesion;
    IF v_saldo_sesion < p_monto THEN
      RAISE EXCEPTION 'El efectivo esperado en la sesión no cubre el depósito.';
    END IF;
  END IF;

  v_id_comprobante := public._registrar_asiento_operativo(
    v_empresa,
    p_id_sucursal,
    p_fecha,
    'MANUAL',
    v_descripcion_contable,
    'DEPOSITO_CAJA_BANCO',
    v_clave,
    jsonb_build_array(
      jsonb_build_object(
        'id_cuenta', p_id_cuenta_banco,
        'debe', p_monto,
        'haber', 0,
        'descripcion', v_descripcion_contable
      ),
      jsonb_build_object(
        'id_cuenta', p_id_cuenta_caja,
        'debe', 0,
        'haber', p_monto,
        'descripcion', v_descripcion_contable
      )
    )
  );

  INSERT INTO public.transferencias_caja_banco (
    id_empresa, id_sucursal, id_cuenta_caja, id_cuenta_banco, id_sesion,
    monto, fecha, referencia, descripcion, id_comprobante,
    clave_idempotencia, huella_solicitud, registrada_por
  )
  VALUES (
    v_empresa, p_id_sucursal, p_id_cuenta_caja, p_id_cuenta_banco, p_id_sesion,
    p_monto, p_fecha, v_referencia, v_descripcion, v_id_comprobante,
    v_clave, v_huella, v_usuario
  )
  RETURNING id_transferencia INTO v_id_transferencia;

  IF p_id_sesion IS NOT NULL THEN
    INSERT INTO public.movimientos_caja (
      id_empresa, id_sucursal, id_caja, id_sesion, tipo, monto,
      descripcion, fecha_operativa, registrado_en, registrado_por,
      origen_tipo, origen_id, idempotencia_key
    )
    VALUES (
      v_empresa, p_id_sucursal, v_sesion.id_caja, p_id_sesion, 'RETIRO', p_monto,
      v_descripcion_contable,
      (clock_timestamp() AT TIME ZONE v_sesion.zona_horaria)::date,
      clock_timestamp(), v_usuario,
      'DEPOSITO_CAJA_BANCO', v_clave, v_clave
    );
  END IF;
  RETURN v_id_transferencia;
END;
$$;

