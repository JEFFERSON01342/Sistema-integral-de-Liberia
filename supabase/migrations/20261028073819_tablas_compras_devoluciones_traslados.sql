-- No carga productos, clientes, proveedores, existencias ni documentos.
-- Los documentos se escriben solo mediante futuras RPC transaccionales.

BEGIN;

ALTER TABLE public.ubicaciones_bodega
  ADD CONSTRAINT ubicaciones_bodega_empresa_sucursal_ubicacion_key
  UNIQUE (id_empresa, id_sucursal, id_ubicacion);

CREATE TABLE public.proveedores (
  id_proveedor bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  codigo text NOT NULL CHECK (char_length(trim(codigo)) > 0),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  nombre_legal text,
  identificacion_fiscal text,
  telefono text,
  email text,
  direccion text,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_empresa, codigo),
  UNIQUE (id_empresa, id_proveedor)
);
CREATE UNIQUE INDEX proveedores_identificacion_key
  ON public.proveedores (id_empresa, identificacion_fiscal)
  WHERE identificacion_fiscal IS NOT NULL;

CREATE TABLE public.clientes (
  id_cliente bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  codigo text NOT NULL CHECK (char_length(trim(codigo)) > 0),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  identificacion text,
  telefono text,
  email text,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_empresa, codigo),
  UNIQUE (id_empresa, id_cliente)
);
CREATE UNIQUE INDEX clientes_identificacion_key
  ON public.clientes (id_empresa, identificacion)
  WHERE identificacion IS NOT NULL;

ALTER TABLE public.ventas
  ADD COLUMN id_cliente bigint,
  ADD CONSTRAINT ventas_cliente_fkey
    FOREIGN KEY (id_empresa, id_cliente)
    REFERENCES public.clientes (id_empresa, id_cliente);

CREATE TABLE public.ordenes_compra (
  id_orden_compra bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_proveedor bigint NOT NULL,
  numero text GENERATED ALWAYS AS ('OC-' || id_orden_compra::text) STORED,
  estado text NOT NULL DEFAULT 'BORRADOR'
    CHECK (estado IN ('BORRADOR', 'ENVIADA', 'PARCIAL', 'RECIBIDA', 'CANCELADA')),
  observaciones text,
  creada_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  creada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  actualizada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id_orden_compra),
  UNIQUE (id_empresa, numero),
  FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal),
  FOREIGN KEY (id_empresa, id_proveedor)
    REFERENCES public.proveedores (id_empresa, id_proveedor)
);

CREATE TABLE public.detalles_orden_compra (
  id_detalle_orden bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_orden_compra bigint NOT NULL,
  id_producto bigint NOT NULL,
  numero_linea integer NOT NULL CHECK (numero_linea > 0),
  cantidad_solicitada numeric(14,3) NOT NULL CHECK (cantidad_solicitada > 0),
  cantidad_aceptada_acumulada numeric(14,3) NOT NULL DEFAULT 0
    CHECK (cantidad_aceptada_acumulada >= 0),
  cantidad_rechazada_acumulada numeric(14,3) NOT NULL DEFAULT 0
    CHECK (cantidad_rechazada_acumulada >= 0),
  UNIQUE (id_orden_compra, numero_linea),
  UNIQUE (id_empresa, id_detalle_orden),
  FOREIGN KEY (id_empresa, id_orden_compra)
    REFERENCES public.ordenes_compra (id_empresa, id_orden_compra),
  FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto),
  CHECK (cantidad_aceptada_acumulada + cantidad_rechazada_acumulada <= cantidad_solicitada)
);

CREATE TABLE public.recepciones_compra (
  id_recepcion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_orden_compra bigint NOT NULL,
  id_ubicacion bigint NOT NULL,
  numero text GENERATED ALWAYS AS ('RC-' || id_recepcion::text) STORED,
  documento_proveedor text,
  subtotal numeric(14,2) NOT NULL CHECK (subtotal > 0),
  observaciones text,
  id_comprobante bigint NOT NULL,
  recibida_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  recibida_en timestamptz NOT NULL,
  fecha_operativa date NOT NULL,
  UNIQUE (id_empresa, id_recepcion),
  UNIQUE (id_empresa, numero),
  FOREIGN KEY (id_empresa, id_orden_compra)
    REFERENCES public.ordenes_compra (id_empresa, id_orden_compra),
  FOREIGN KEY (id_empresa, id_sucursal, id_ubicacion)
    REFERENCES public.ubicaciones_bodega (id_empresa, id_sucursal, id_ubicacion),
  FOREIGN KEY (id_empresa, id_comprobante)
    REFERENCES public.comprobantes_contables (id_empresa, id_comprobante)
);

CREATE TABLE public.detalles_recepcion_compra (
  id_detalle_recepcion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_recepcion bigint NOT NULL,
  id_detalle_orden bigint NOT NULL,
  id_producto bigint NOT NULL,
  cantidad_aceptada numeric(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_aceptada >= 0),
  cantidad_rechazada numeric(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_rechazada >= 0),
  costo_unitario numeric(14,4) NOT NULL CHECK (costo_unitario > 0),
  subtotal_aceptado numeric(14,2) NOT NULL CHECK (subtotal_aceptado >= 0),
  UNIQUE (id_recepcion, id_detalle_orden),
  UNIQUE (id_empresa, id_detalle_recepcion),
  FOREIGN KEY (id_empresa, id_recepcion)
    REFERENCES public.recepciones_compra (id_empresa, id_recepcion),
  FOREIGN KEY (id_empresa, id_detalle_orden)
    REFERENCES public.detalles_orden_compra (id_empresa, id_detalle_orden),
  FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto),
  CHECK (subtotal_aceptado = round(cantidad_aceptada * costo_unitario, 2)),
  CHECK (cantidad_aceptada + cantidad_rechazada > 0)
);

CREATE TABLE public.devoluciones_venta (
  id_devolucion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_venta bigint NOT NULL,
  id_caja bigint NOT NULL,
  id_sesion bigint NOT NULL,
  numero text GENERATED ALWAYS AS ('DV-' || id_devolucion::text) STORED,
  metodo_reembolso text NOT NULL
    CHECK (metodo_reembolso IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA')),
  subtotal numeric(14,2) NOT NULL CHECK (subtotal > 0),
  impuesto numeric(14,2) NOT NULL DEFAULT 0 CHECK (impuesto >= 0),
  total numeric(14,2) NOT NULL CHECK (total = subtotal + impuesto),
  costo_fifo_revertido numeric(14,2) NOT NULL CHECK (costo_fifo_revertido >= 0),
  motivo text NOT NULL CHECK (char_length(trim(motivo)) >= 3),
  id_comprobante bigint NOT NULL,
  clave_idempotencia text NOT NULL
    CHECK (char_length(trim(clave_idempotencia)) BETWEEN 1 AND 128),
  procesada_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  procesada_en timestamptz NOT NULL,
  fecha_operativa date NOT NULL,
  UNIQUE (id_empresa, id_devolucion),
  UNIQUE (id_empresa, numero),
  UNIQUE (id_empresa, clave_idempotencia),
  FOREIGN KEY (id_empresa, id_venta)
    REFERENCES public.ventas (id_empresa, id_venta),
  FOREIGN KEY (id_empresa, id_sucursal, id_caja, id_sesion)
    REFERENCES public.sesiones_caja (id_empresa, id_sucursal, id_caja, id_sesion),
  FOREIGN KEY (id_empresa, id_comprobante)
    REFERENCES public.comprobantes_contables (id_empresa, id_comprobante)
);

CREATE TABLE public.detalles_devolucion_venta (
  id_detalle_devolucion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_devolucion bigint NOT NULL,
  id_detalle_venta bigint NOT NULL REFERENCES public.detalle_ventas (id_detalle),
  id_producto bigint NOT NULL,
  cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
  precio_unitario numeric(14,2) NOT NULL CHECK (precio_unitario > 0),
  subtotal numeric(14,2) NOT NULL
    CHECK (subtotal = round(cantidad * precio_unitario, 2)),
  costo_fifo_revertido numeric(14,2) NOT NULL CHECK (costo_fifo_revertido >= 0),
  UNIQUE (id_empresa, id_detalle_devolucion),
  FOREIGN KEY (id_empresa, id_devolucion)
    REFERENCES public.devoluciones_venta (id_empresa, id_devolucion),
  FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto)
);

CREATE TABLE public.devoluciones_fifo (
  id_devolucion_fifo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_detalle_devolucion bigint NOT NULL,
  id_capa_origen bigint NOT NULL,
  id_capa_reingreso bigint NOT NULL,
  cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
  costo_unitario numeric(14,4) NOT NULL CHECK (costo_unitario > 0),
  costo_total numeric(14,2) NOT NULL CHECK (costo_total >= 0),
  FOREIGN KEY (id_empresa, id_detalle_devolucion)
    REFERENCES public.detalles_devolucion_venta (id_empresa, id_detalle_devolucion),
  FOREIGN KEY (id_empresa, id_capa_origen)
    REFERENCES public.capas_inventario_fifo (id_empresa, id_capa),
  FOREIGN KEY (id_empresa, id_capa_reingreso)
    REFERENCES public.capas_inventario_fifo (id_empresa, id_capa)
);

CREATE TABLE public.transferencias_inventario (
  id_transferencia bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_ubicacion_origen bigint NOT NULL,
  id_ubicacion_destino bigint NOT NULL,
  numero text GENERATED ALWAYS AS ('TR-' || id_transferencia::text) STORED,
  motivo text NOT NULL CHECK (char_length(trim(motivo)) >= 3),
  transferida_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  transferida_en timestamptz NOT NULL,
  fecha_operativa date NOT NULL,
  UNIQUE (id_empresa, id_transferencia),
  UNIQUE (id_empresa, numero),
  FOREIGN KEY (id_empresa, id_sucursal, id_ubicacion_origen)
    REFERENCES public.ubicaciones_bodega (id_empresa, id_sucursal, id_ubicacion),
  FOREIGN KEY (id_empresa, id_sucursal, id_ubicacion_destino)
    REFERENCES public.ubicaciones_bodega (id_empresa, id_sucursal, id_ubicacion),
  CHECK (id_ubicacion_origen <> id_ubicacion_destino)
);

CREATE TABLE public.detalles_transferencia_inventario (
  id_detalle_transferencia bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_transferencia bigint NOT NULL,
  id_producto bigint NOT NULL,
  cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
  costo_total numeric(14,2) NOT NULL CHECK (costo_total >= 0),
  UNIQUE (id_transferencia, id_producto),
  UNIQUE (id_empresa, id_detalle_transferencia),
  FOREIGN KEY (id_empresa, id_transferencia)
    REFERENCES public.transferencias_inventario (id_empresa, id_transferencia),
  FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto)
);

CREATE TABLE public.capas_transferencia_inventario (
  id_capa_transferencia bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_detalle_transferencia bigint NOT NULL,
  id_capa_origen bigint NOT NULL,
  id_capa_destino bigint NOT NULL,
  cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
  costo_unitario numeric(14,4) NOT NULL CHECK (costo_unitario > 0),
  FOREIGN KEY (id_empresa, id_detalle_transferencia)
    REFERENCES public.detalles_transferencia_inventario (id_empresa, id_detalle_transferencia),
  FOREIGN KEY (id_empresa, id_capa_origen)
    REFERENCES public.capas_inventario_fifo (id_empresa, id_capa),
  FOREIGN KEY (id_empresa, id_capa_destino)
    REFERENCES public.capas_inventario_fifo (id_empresa, id_capa)
);

CREATE TABLE public.ajustes_inventario (
  id_ajuste bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_ubicacion bigint NOT NULL,
  numero text GENERATED ALWAYS AS ('AI-' || id_ajuste::text) STORED,
  motivo text NOT NULL CHECK (char_length(trim(motivo)) >= 3),
  id_comprobante bigint NOT NULL,
  clave_idempotencia text NOT NULL
    CHECK (char_length(trim(clave_idempotencia)) BETWEEN 1 AND 128),
  registrado_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  registrado_en timestamptz NOT NULL,
  fecha_operativa date NOT NULL,
  UNIQUE (id_empresa, id_ajuste),
  UNIQUE (id_empresa, numero),
  UNIQUE (id_empresa, clave_idempotencia),
  FOREIGN KEY (id_empresa, id_sucursal, id_ubicacion)
    REFERENCES public.ubicaciones_bodega (id_empresa, id_sucursal, id_ubicacion),
  FOREIGN KEY (id_empresa, id_comprobante)
    REFERENCES public.comprobantes_contables (id_empresa, id_comprobante)
);

CREATE TABLE public.detalles_ajuste_inventario (
  id_detalle_ajuste bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_ajuste bigint NOT NULL,
  id_producto bigint NOT NULL,
  cantidad_delta numeric(14,3) NOT NULL CHECK (cantidad_delta <> 0),
  costo_unitario numeric(14,4) NOT NULL CHECK (costo_unitario > 0),
  costo_total numeric(14,2) NOT NULL CHECK (costo_total > 0),
  UNIQUE (id_ajuste, id_producto),
  FOREIGN KEY (id_empresa, id_ajuste)
    REFERENCES public.ajustes_inventario (id_empresa, id_ajuste),
  FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto),
  CHECK (costo_total = round(abs(cantidad_delta) * costo_unitario, 2))
);

