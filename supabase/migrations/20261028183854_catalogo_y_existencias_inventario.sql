-- Fase 26: clasificacion de productos, unidades y saldos consultables por sucursal.

BEGIN;

CREATE TABLE public.categorias_producto (
  id_categoria bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  descripcion text,
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id_categoria)
);

CREATE UNIQUE INDEX categorias_producto_nombre_empresa_key
  ON public.categorias_producto (id_empresa, lower(trim(nombre)));

CREATE TABLE public.unidades_medidas (
  id_unidad_medida bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  codigo text NOT NULL CHECK (codigo ~ '^[A-Z0-9_-]{1,12}$'),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  abreviatura text NOT NULL CHECK (char_length(trim(abreviatura)) BETWEEN 1 AND 12),
  decimales_cantidad smallint NOT NULL DEFAULT 3
    CHECK (decimales_cantidad BETWEEN 0 AND 3),
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, codigo),
  UNIQUE (id_empresa, id_unidad_medida)
);

CREATE UNIQUE INDEX unidades_medidas_nombre_empresa_key
  ON public.unidades_medidas (id_empresa, lower(trim(nombre)));

ALTER TABLE public.productos
  ADD COLUMN id_categoria bigint,
  ADD COLUMN id_unidad_medida bigint,
  ADD CONSTRAINT productos_categoria_empresa_fkey
    FOREIGN KEY (id_empresa, id_categoria)
    REFERENCES public.categorias_producto (id_empresa, id_categoria),
  ADD CONSTRAINT productos_unidad_empresa_fkey
    FOREIGN KEY (id_empresa, id_unidad_medida)
    REFERENCES public.unidades_medidas (id_empresa, id_unidad_medida);

CREATE TABLE public.stock_minimo_producto_sucursal (
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_producto bigint NOT NULL,
  stock_minimo numeric(14,3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (id_empresa, id_sucursal, id_producto),
  FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal),
  FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto)
);

CREATE INDEX stock_minimo_producto_sucursal_producto_idx
  ON public.stock_minimo_producto_sucursal (id_empresa, id_producto);

CREATE TRIGGER categorias_producto_actualizar_updated_at
BEFORE UPDATE ON public.categorias_producto
FOR EACH ROW EXECUTE FUNCTION public.actualizar_updated_at();

CREATE TRIGGER unidades_medidas_actualizar_updated_at
BEFORE UPDATE ON public.unidades_medidas
FOR EACH ROW EXECUTE FUNCTION public.actualizar_updated_at();

ALTER TABLE public.categorias_producto ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.unidades_medidas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_minimo_producto_sucursal ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.categorias_producto,
  public.unidades_medidas, public.stock_minimo_producto_sucursal FROM anon, authenticated;

GRANT SELECT, INSERT, UPDATE ON TABLE public.categorias_producto,
  public.unidades_medidas TO authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.stock_minimo_producto_sucursal
  TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.categorias_producto_id_categoria_seq,
  public.unidades_medidas_id_unidad_medida_seq TO authenticated;
GRANT UPDATE (id_categoria, id_unidad_medida) ON TABLE public.productos
  TO authenticated;

CREATE POLICY categorias_producto_select_empresa
  ON public.categorias_producto FOR SELECT TO authenticated
  USING ((SELECT public.puede_ver_empresa(id_empresa)));
CREATE POLICY categorias_producto_admin_manage
  ON public.categorias_producto FOR INSERT TO authenticated
  WITH CHECK ((SELECT public.puede_administrar_empresa(id_empresa)));
CREATE POLICY categorias_producto_admin_update
  ON public.categorias_producto FOR UPDATE TO authenticated
  USING ((SELECT public.puede_administrar_empresa(id_empresa)))
  WITH CHECK ((SELECT public.puede_administrar_empresa(id_empresa)));

CREATE POLICY unidades_medidas_select_empresa
  ON public.unidades_medidas FOR SELECT TO authenticated
  USING ((SELECT public.puede_ver_empresa(id_empresa)));
CREATE POLICY unidades_medidas_admin_manage
  ON public.unidades_medidas FOR INSERT TO authenticated
  WITH CHECK ((SELECT public.puede_administrar_empresa(id_empresa)));
CREATE POLICY unidades_medidas_admin_update
  ON public.unidades_medidas FOR UPDATE TO authenticated
  USING ((SELECT public.puede_administrar_empresa(id_empresa)))
  WITH CHECK ((SELECT public.puede_administrar_empresa(id_empresa)));

CREATE POLICY stock_minimo_select_empresa
  ON public.stock_minimo_producto_sucursal FOR SELECT TO authenticated
  USING ((SELECT public.puede_ver_empresa(id_empresa)));
CREATE POLICY stock_minimo_admin_insert
  ON public.stock_minimo_producto_sucursal FOR INSERT TO authenticated
  WITH CHECK ((SELECT public.puede_administrar_empresa(id_empresa)));
CREATE POLICY stock_minimo_admin_update
  ON public.stock_minimo_producto_sucursal FOR UPDATE TO authenticated
  USING ((SELECT public.puede_administrar_empresa(id_empresa)))
  WITH CHECK ((SELECT public.puede_administrar_empresa(id_empresa)));
CREATE POLICY stock_minimo_admin_delete
  ON public.stock_minimo_producto_sucursal FOR DELETE TO authenticated
  USING ((SELECT public.puede_administrar_empresa(id_empresa)));

CREATE OR REPLACE VIEW public.existencias_producto_sucursal
WITH (security_invoker = true)
AS
SELECT p.id_empresa,
       s.id_sucursal,
       p.id_producto,
       p.sku,
       p.nombre AS producto,
       p.codigo_barras,
       c.id_categoria,
       c.nombre AS categoria,
       u.id_unidad_medida,
       u.nombre AS unidad_medida,
       u.abreviatura AS unidad_abreviatura,
       COALESCE(stock.cantidad_disponible, 0)::numeric(14,3) AS cantidad_disponible,
       COALESCE(minimo.stock_minimo, 0)::numeric(14,3) AS stock_minimo,
       COALESCE(stock.valor_inventario, 0)::numeric(14,2) AS valor_inventario,
       CASE
         WHEN COALESCE(minimo.stock_minimo, 0) = 0 THEN 'SIN_CONFIGURAR'
         WHEN COALESCE(stock.cantidad_disponible, 0) = 0 THEN 'SIN_EXISTENCIA'
         WHEN stock.cantidad_disponible <= minimo.stock_minimo THEN 'BAJO'
         ELSE 'NORMAL'
       END AS estado_stock
FROM public.productos p
JOIN public.sucursales s
  ON s.id_empresa = p.id_empresa AND s.activa
LEFT JOIN public.categorias_producto c
  ON c.id_empresa = p.id_empresa AND c.id_categoria = p.id_categoria
LEFT JOIN public.unidades_medidas u
  ON u.id_empresa = p.id_empresa AND u.id_unidad_medida = p.id_unidad_medida
LEFT JOIN public.stock_minimo_producto_sucursal minimo
  ON minimo.id_empresa = p.id_empresa
 AND minimo.id_sucursal = s.id_sucursal
 AND minimo.id_producto = p.id_producto
LEFT JOIN LATERAL (
  SELECT sum(f.cantidad_disponible)::numeric(14,3) AS cantidad_disponible,
         round(sum(f.cantidad_disponible * f.costo_unitario), 2)::numeric(14,2)
           AS valor_inventario
  FROM public.capas_inventario_fifo f
  WHERE f.id_empresa = p.id_empresa
    AND f.id_sucursal = s.id_sucursal
    AND f.id_producto = p.id_producto
) stock ON true
WHERE p.activo;

REVOKE ALL ON TABLE public.existencias_producto_sucursal FROM anon, authenticated;
GRANT SELECT ON TABLE public.existencias_producto_sucursal TO authenticated;

INSERT INTO public.unidades_medidas (
  id_empresa, codigo, nombre, abreviatura, decimales_cantidad
)
SELECT e.id_empresa, u.codigo, u.nombre, u.abreviatura, u.decimales
FROM public.empresa e
CROSS JOIN (VALUES
  ('UND', 'Unidad', 'und', 0::smallint),
  ('PQT', 'Paquete', 'pqt', 0::smallint),
  ('CAJ', 'Caja', 'caj', 0::smallint),
  ('KG', 'Kilogramo', 'kg', 3::smallint),
  ('G', 'Gramo', 'g', 3::smallint),
  ('M', 'Metro', 'm', 3::smallint),
  ('CM', 'Centimetro', 'cm', 1::smallint),
  ('L', 'Litro', 'l', 3::smallint)
) AS u(codigo, nombre, abreviatura, decimales)
WHERE e.activa
ON CONFLICT (id_empresa, codigo) DO NOTHING;

COMMIT;
