CREATE OR REPLACE VIEW public.saldos_cuentas_por_pagar
WITH (security_invoker = true)
AS
SELECT c.id_empresa, c.id_cuenta_por_pagar, c.id_proveedor,
       c.id_recepcion, c.id_sucursal, c.fecha_emision, c.fecha_vencimiento,
       c.total, COALESCE(sum(a.monto), 0)::numeric(14,2) AS monto_pagado,
       (c.total - COALESCE(sum(a.monto), 0))::numeric(14,2) AS saldo_pendiente,
       GREATEST(((clock_timestamp() AT TIME ZONE e.zona_horaria)::date
         - c.fecha_vencimiento), 0) AS dias_vencidos,
       CASE
         WHEN c.total = COALESCE(sum(a.monto), 0) THEN 'PAGADA'
         WHEN c.fecha_vencimiento < (clock_timestamp() AT TIME ZONE e.zona_horaria)::date THEN 'VENCIDA'
         ELSE 'PENDIENTE'
       END AS estado,
       c.id_adquisicion_activo
FROM public.cuentas_por_pagar c
JOIN public.empresa e ON e.id_empresa = c.id_empresa
LEFT JOIN public.aplicaciones_pago_proveedor a
  ON a.id_empresa = c.id_empresa
 AND a.id_cuenta_por_pagar = c.id_cuenta_por_pagar
GROUP BY c.id_empresa, c.id_cuenta_por_pagar, e.zona_horaria;

CREATE OR REPLACE FUNCTION public.guardar_categoria_activo_fijo(
  p_id_empresa integer,
  p_id_categoria bigint,
  p_codigo text,
  p_nombre text,
  p_vida_util_meses integer,
  p_referencia_normativa text,
  p_id_cuenta_activo bigint,
  p_id_cuenta_depreciacion_acumulada bigint,
  p_id_cuenta_gasto_depreciacion bigint,
  p_activa boolean DEFAULT true
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_id_categoria bigint;
BEGIN
  IF v_usuario IS NULL
     OR NOT (SELECT public.puede_administrar_empresa(p_id_empresa)) THEN
    RAISE EXCEPTION 'Solo un administrador puede configurar categorias de activos fijos.';
  END IF;
  IF char_length(trim(COALESCE(p_codigo, ''))) NOT BETWEEN 1 AND 40
     OR char_length(trim(COALESCE(p_nombre, ''))) NOT BETWEEN 1 AND 120
     OR p_vida_util_meses NOT BETWEEN 1 AND 1200 THEN
    RAISE EXCEPTION 'Codigo, nombre y vida util de la categoria no son validos.';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.cuentas_contables a
    JOIN public.cuentas_contables d
      ON d.id_empresa = a.id_empresa
    JOIN public.cuentas_contables g
      ON g.id_empresa = a.id_empresa
    WHERE a.id_empresa = p_id_empresa
      AND a.id_cuenta = p_id_cuenta_activo
      AND a.codigo IN ('1.2.01', '1.2.02', '1.2.03')
      AND a.naturaleza = 'ACTIVO' AND a.saldo_normal = 'DEBE'
      AND a.activa AND NOT a.es_grupo AND a.permite_movimientos
      AND d.id_cuenta = p_id_cuenta_depreciacion_acumulada
      AND d.codigo IN ('1.3.01', '1.3.02')
      AND d.naturaleza = 'ACTIVO' AND d.saldo_normal = 'HABER'
      AND d.activa AND NOT d.es_grupo AND d.permite_movimientos
      AND g.id_cuenta = p_id_cuenta_gasto_depreciacion
      AND g.codigo = '6.5.01'
      AND g.naturaleza = 'GASTO' AND g.saldo_normal = 'DEBE'
      AND g.activa AND NOT g.es_grupo AND g.permite_movimientos
  ) THEN
    RAISE EXCEPTION 'Las cuentas deben ser cuentas activas de activo fijo, depreciacion acumulada y gasto por depreciacion.';
  END IF;
  IF p_id_categoria IS NULL THEN
    INSERT INTO public.categorias_activos_fijos (
      id_empresa, codigo, nombre, vida_util_meses, referencia_normativa,
      id_cuenta_activo, id_cuenta_depreciacion_acumulada,
      id_cuenta_gasto_depreciacion, activa
    )
    VALUES (
      p_id_empresa, trim(p_codigo), trim(p_nombre), p_vida_util_meses,
      NULLIF(trim(p_referencia_normativa), ''), p_id_cuenta_activo,
      p_id_cuenta_depreciacion_acumulada, p_id_cuenta_gasto_depreciacion,
      COALESCE(p_activa, true)
    )
    RETURNING id_categoria INTO v_id_categoria;
  ELSE
    UPDATE public.categorias_activos_fijos
    SET codigo = trim(p_codigo),
        nombre = trim(p_nombre),
        vida_util_meses = p_vida_util_meses,
        referencia_normativa = NULLIF(trim(p_referencia_normativa), ''),
        id_cuenta_activo = p_id_cuenta_activo,
        id_cuenta_depreciacion_acumulada = p_id_cuenta_depreciacion_acumulada,
        id_cuenta_gasto_depreciacion = p_id_cuenta_gasto_depreciacion,
        activa = COALESCE(p_activa, true),
        actualizada_en = clock_timestamp()
    WHERE id_empresa = p_id_empresa AND id_categoria = p_id_categoria
    RETURNING id_categoria INTO v_id_categoria;
    IF v_id_categoria IS NULL THEN
      RAISE EXCEPTION 'La categoria no existe en la empresa indicada.';
    END IF;
  END IF;
  RETURN v_id_categoria;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_adquisicion_activo_fijo(
  p_id_sucursal integer,
  p_id_categoria bigint,
  p_codigo text,
  p_nombre text,
  p_descripcion text,
  p_numero_serie text,
  p_fecha_adquisicion date,
  p_fecha_puesta_en_servicio date,
  p_costo_adquisicion numeric,
  p_valor_residual numeric,
  p_tipo_adquisicion text,
  p_id_cuenta_contrapartida bigint,
  p_id_proveedor bigint,
  p_documento_referencia text,
  p_ubicacion text,
  p_responsable text,
  p_clave_idempotencia text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_zona text;
  v_fecha date;
  v_id_categoria bigint;
  v_vida_util integer;
  v_cuenta_activo bigint;
  v_cuenta_depreciacion bigint;
  v_cuenta_gasto bigint;
  v_cuenta_contrapartida bigint;
  v_cuenta_proveedor bigint;
  v_plazo integer;
  v_id_adquisicion bigint;
  v_id_activo bigint;
  v_id_comprobante bigint;
  v_existente bigint;
  v_hash_existente text;
  v_huella text;
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
BEGIN
  IF v_usuario IS NULL
     OR NOT (SELECT public.puede_operar_caja(
       (SELECT s.id_empresa FROM public.sucursales s WHERE s.id_sucursal = p_id_sucursal),
       p_id_sucursal, true
     )) THEN
    RAISE EXCEPTION 'No tienes permiso para registrar activos en esta sucursal.';
  END IF;
  SELECT s.id_empresa, e.zona_horaria
  INTO v_empresa, v_zona
  FROM public.sucursales s
  JOIN public.empresa e ON e.id_empresa = s.id_empresa AND e.activa
  WHERE s.id_sucursal = p_id_sucursal AND s.activa;
  IF v_empresa IS NULL
     OR NOT (SELECT public.puede_administrar_empresa(v_empresa)) THEN
    RAISE EXCEPTION 'Solo un administrador puede registrar adquisiciones de activos fijos.';
  END IF;
  IF char_length(v_clave) NOT BETWEEN 1 AND 128
     OR char_length(trim(COALESCE(p_codigo, ''))) NOT BETWEEN 1 AND 80
     OR char_length(trim(COALESCE(p_nombre, ''))) NOT BETWEEN 1 AND 160
     OR p_fecha_adquisicion IS NULL
     OR p_fecha_puesta_en_servicio IS NULL
     OR p_fecha_puesta_en_servicio < p_fecha_adquisicion
     OR p_costo_adquisicion IS NULL OR p_costo_adquisicion <= 0
     OR p_costo_adquisicion <> round(p_costo_adquisicion, 2)
     OR COALESCE(p_valor_residual, 0) < 0
     OR COALESCE(p_valor_residual, 0) >= p_costo_adquisicion
     OR COALESCE(p_valor_residual, 0) <> round(COALESCE(p_valor_residual, 0), 2)
     OR p_tipo_adquisicion IS NULL
     OR p_tipo_adquisicion NOT IN ('CONTADO', 'CREDITO') THEN
    RAISE EXCEPTION 'Los datos de adquisicion, fechas, costo o valor residual no son validos.';
  END IF;

  SELECT c.id_categoria, c.vida_util_meses, c.id_cuenta_activo,
         c.id_cuenta_depreciacion_acumulada, c.id_cuenta_gasto_depreciacion
  INTO v_id_categoria, v_vida_util, v_cuenta_activo,
       v_cuenta_depreciacion, v_cuenta_gasto
  FROM public.categorias_activos_fijos c
  WHERE c.id_empresa = v_empresa AND c.id_categoria = p_id_categoria AND c.activa;
  IF v_id_categoria IS NULL THEN
    RAISE EXCEPTION 'La categoria no existe, esta inactiva o pertenece a otra empresa.';
  END IF;

  IF p_tipo_adquisicion = 'CONTADO' THEN
    IF p_id_proveedor IS NOT NULL THEN
      RAISE EXCEPTION 'En adquisiciones al contado no se debe registrar una cuenta por pagar de proveedor.';
    END IF;
    SELECT c.id_cuenta INTO v_cuenta_contrapartida
    FROM public.cuentas_contables c
    WHERE c.id_empresa = v_empresa AND c.id_cuenta = p_id_cuenta_contrapartida
      AND c.codigo IN ('1.1.01', '1.1.03', '1.1.04')
      AND c.naturaleza = 'ACTIVO' AND c.saldo_normal = 'DEBE'
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
    IF v_cuenta_contrapartida IS NULL THEN
      RAISE EXCEPTION 'Selecciona una cuenta activa de caja, caja chica o bancos.';
    END IF;
  ELSE
    IF p_id_cuenta_contrapartida IS NOT NULL THEN
      RAISE EXCEPTION 'En adquisiciones a credito, la cuenta por pagar se determina automaticamente.';
    END IF;
    SELECT p.plazo_credito_dias INTO v_plazo
    FROM public.proveedores p
    WHERE p.id_empresa = v_empresa
      AND p.id_proveedor = p_id_proveedor AND p.activo;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'El proveedor no existe, esta inactivo o pertenece a otra empresa.';
    END IF;
    SELECT c.id_cuenta INTO v_cuenta_proveedor
    FROM public.cuentas_contables c
    WHERE c.id_empresa = v_empresa AND c.codigo = '2.1.01'
      AND c.naturaleza = 'PASIVO' AND c.saldo_normal = 'HABER'
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
    IF v_cuenta_proveedor IS NULL THEN
      RAISE EXCEPTION 'Falta configurar la cuenta de proveedores por pagar.';
    END IF;
  END IF;

  v_huella := md5(concat_ws('|',
    v_empresa, p_id_sucursal, p_id_categoria, trim(p_codigo), trim(p_nombre),
    COALESCE(trim(p_descripcion), ''), COALESCE(trim(p_numero_serie), ''),
    p_fecha_adquisicion, p_fecha_puesta_en_servicio, p_costo_adquisicion,
    COALESCE(p_valor_residual, 0), p_tipo_adquisicion,
    COALESCE(p_id_cuenta_contrapartida::text, ''),
    COALESCE(p_id_proveedor::text, ''),
    COALESCE(trim(p_documento_referencia), ''),
    COALESCE(trim(p_ubicacion), ''), COALESCE(trim(p_responsable), '')
  ));
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('AF:' || v_empresa::text || ':' || v_clave, 0)
  );
  SELECT a.id_adquisicion, a.huella_solicitud INTO v_existente, v_hash_existente
  FROM public.adquisiciones_activos_fijos a
  WHERE a.id_empresa = v_empresa AND a.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_hash_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se uso con datos distintos.';
    END IF;
    SELECT a.id_activo_fijo INTO v_id_activo
    FROM public.activos_fijos a
    WHERE a.id_empresa = v_empresa AND a.id_adquisicion = v_existente;
    RETURN v_id_activo;
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.activos_fijos a
    WHERE a.id_empresa = v_empresa AND a.codigo = trim(p_codigo)
  ) THEN
    RAISE EXCEPTION 'Ya existe un activo con ese codigo en la empresa.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.lotes_depreciacion_activos_fijos l
    JOIN public.periodos_contables pc
      ON pc.id_empresa = l.id_empresa AND pc.id_periodo = l.id_periodo
    WHERE l.id_empresa = v_empresa AND l.id_sucursal = p_id_sucursal
      AND pc.fecha_inicio >=
        (date_trunc('month', p_fecha_puesta_en_servicio)::date + interval '1 month')::date
  ) THEN
    RAISE EXCEPTION 'No se puede registrar retroactivamente un activo despues de contabilizar su periodo de depreciacion.';
  END IF;

  v_fecha := p_fecha_adquisicion;
  v_id_adquisicion := nextval(
    pg_get_serial_sequence('public.adquisiciones_activos_fijos', 'id_adquisicion')::regclass
  );
  v_id_comprobante := public._registrar_asiento_operativo(
    v_empresa, p_id_sucursal, v_fecha, 'COMPRA',
    'Adquisicion de activo fijo ' || trim(p_codigo),
    'ADQUISICION_ACTIVO_FIJO', v_id_adquisicion::text,
    jsonb_build_array(
      jsonb_build_object('id_cuenta', v_cuenta_activo,
        'debe', p_costo_adquisicion, 'haber', 0,
        'descripcion', 'Alta de activo fijo ' || trim(p_codigo)),
      jsonb_build_object(
        'id_cuenta', CASE WHEN p_tipo_adquisicion = 'CONTADO'
          THEN v_cuenta_contrapartida ELSE v_cuenta_proveedor END,
        'debe', 0, 'haber', p_costo_adquisicion,
        'descripcion', CASE WHEN p_tipo_adquisicion = 'CONTADO'
          THEN 'Pago de adquisicion de activo fijo'
          ELSE 'Cuenta por pagar por adquisicion de activo fijo' END)
    )
  );
  INSERT INTO public.adquisiciones_activos_fijos (
    id_adquisicion, id_empresa, id_sucursal, tipo_adquisicion,
    id_proveedor, id_cuenta_contrapartida, fecha_adquisicion,
    documento_referencia, monto, id_comprobante,
    clave_idempotencia, huella_solicitud, registrada_por
  )
  VALUES (
    v_id_adquisicion, v_empresa, p_id_sucursal, p_tipo_adquisicion,
    p_id_proveedor, v_cuenta_contrapartida, v_fecha,
    NULLIF(trim(p_documento_referencia), ''), p_costo_adquisicion,
    v_id_comprobante, v_clave, v_huella, v_usuario
  );
  INSERT INTO public.activos_fijos (
    id_empresa, id_sucursal, id_categoria, id_adquisicion,
    codigo, nombre, descripcion, numero_serie, fecha_adquisicion,
    fecha_puesta_en_servicio, costo_adquisicion, valor_residual,
    vida_util_meses, id_cuenta_activo,
    id_cuenta_depreciacion_acumulada, id_cuenta_gasto_depreciacion,
    ubicacion, responsable, registrada_por
  )
  VALUES (
    v_empresa, p_id_sucursal, v_id_categoria, v_id_adquisicion,
    trim(p_codigo), trim(p_nombre), NULLIF(trim(p_descripcion), ''),
    NULLIF(trim(p_numero_serie), ''), p_fecha_adquisicion,
    p_fecha_puesta_en_servicio, p_costo_adquisicion,
    COALESCE(p_valor_residual, 0), v_vida_util, v_cuenta_activo,
    v_cuenta_depreciacion, v_cuenta_gasto, NULLIF(trim(p_ubicacion), ''),
    NULLIF(trim(p_responsable), ''), v_usuario
  )
  RETURNING id_activo_fijo INTO v_id_activo;

  IF p_tipo_adquisicion = 'CREDITO' THEN
    INSERT INTO public.cuentas_por_pagar (
      id_empresa, id_proveedor, id_recepcion, id_adquisicion_activo,
      id_sucursal, documento_referencia, fecha_emision, fecha_vencimiento,
      total, id_comprobante
    )
    VALUES (
      v_empresa, p_id_proveedor, NULL, v_id_adquisicion, p_id_sucursal,
      NULLIF(trim(p_documento_referencia), ''), p_fecha_adquisicion,
      p_fecha_adquisicion + v_plazo, p_costo_adquisicion, v_id_comprobante
    );
  END IF;
  RETURN v_id_activo;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_depreciacion_activos_fijos(
  p_id_sucursal integer,
  p_anio integer,
  p_mes integer,
  p_clave_idempotencia text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_id_periodo bigint;
  v_fecha_inicio date;
  v_fecha_fin date;
  v_id_lote bigint;
  v_id_comprobante bigint;
  v_existente bigint;
  v_hash_existente text;
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
  v_huella text;
  v_activo record;
  v_inicio_depreciacion date;
  v_meses_transcurridos integer;
  v_base numeric(14,2);
  v_objetivo numeric(14,2);
  v_incremento numeric(14,2);
  v_acumulado numeric(14,2);
  v_total numeric(14,2) := 0;
  v_detalles jsonb := '[]'::jsonb;
  v_lineas jsonb;
BEGIN
  IF v_usuario IS NULL THEN RAISE EXCEPTION 'Debes iniciar sesion.'; END IF;
  IF p_mes NOT BETWEEN 1 AND 12
     OR char_length(v_clave) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'El periodo o la clave de idempotencia no son validos.';
  END IF;
  SELECT s.id_empresa INTO v_empresa
  FROM public.sucursales s
  WHERE s.id_sucursal = p_id_sucursal AND s.activa;
  IF v_empresa IS NULL
     OR NOT (SELECT public.puede_administrar_empresa(v_empresa)) THEN
    RAISE EXCEPTION 'Solo un administrador puede contabilizar depreciaciones.';
  END IF;
  SELECT pc.id_periodo, pc.fecha_inicio, pc.fecha_fin
  INTO v_id_periodo, v_fecha_inicio, v_fecha_fin
  FROM public.periodos_contables pc
  WHERE pc.id_empresa = v_empresa AND pc.anio = p_anio AND pc.mes = p_mes
    AND pc.estado = 'ABIERTO'
  FOR SHARE;
  IF v_id_periodo IS NULL THEN
    RAISE EXCEPTION 'No existe un periodo contable abierto para el mes solicitado.';
  END IF;

  v_huella := md5(v_empresa::text || '|' || p_id_sucursal::text || '|'
    || v_id_periodo::text);
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('DAF:' || v_empresa::text || ':' ||
      p_id_sucursal::text || ':' || v_id_periodo::text, 0)
  );
  SELECT l.id_lote, l.huella_solicitud
  INTO v_existente, v_hash_existente
  FROM public.lotes_depreciacion_activos_fijos l
  WHERE l.id_empresa = v_empresa AND l.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_hash_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se uso con otro periodo o sucursal.';
    END IF;
    RETURN v_existente;
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.lotes_depreciacion_activos_fijos l
    WHERE l.id_empresa = v_empresa AND l.id_sucursal = p_id_sucursal
      AND l.id_periodo = v_id_periodo
  ) THEN
    RAISE EXCEPTION 'La depreciacion de ese periodo ya fue contabilizada.';
  END IF;

  PERFORM a.id_activo_fijo
  FROM public.activos_fijos a
  WHERE a.id_empresa = v_empresa AND a.id_sucursal = p_id_sucursal
  ORDER BY a.id_activo_fijo
  FOR UPDATE;

  FOR v_activo IN
    SELECT a.id_activo_fijo, a.costo_adquisicion, a.valor_residual,
           a.vida_util_meses, a.fecha_puesta_en_servicio,
           COALESCE(d.acumulado, 0)::numeric(14,2) AS acumulado
    FROM public.activos_fijos a
    LEFT JOIN LATERAL (
      SELECT sum(x.importe)::numeric(14,2) AS acumulado
      FROM public.depreciaciones_activos_fijos x
      WHERE x.id_empresa = a.id_empresa
        AND x.id_activo_fijo = a.id_activo_fijo
    ) d ON true
    WHERE a.id_empresa = v_empresa AND a.id_sucursal = p_id_sucursal
    ORDER BY a.id_activo_fijo
  LOOP
    v_inicio_depreciacion :=
      (date_trunc('month', v_activo.fecha_puesta_en_servicio)::date
        + interval '1 month')::date;
    IF v_fecha_inicio < v_inicio_depreciacion THEN
      CONTINUE;
    END IF;
    v_meses_transcurridos :=
      (extract(year FROM v_fecha_inicio)::integer
        - extract(year FROM v_inicio_depreciacion)::integer) * 12
      + extract(month FROM v_fecha_inicio)::integer
      - extract(month FROM v_inicio_depreciacion)::integer + 1;
    v_base := v_activo.costo_adquisicion - v_activo.valor_residual;
    IF v_meses_transcurridos >= v_activo.vida_util_meses THEN
      v_objetivo := v_base;
    ELSE
      v_objetivo := round(
        v_base * v_meses_transcurridos / v_activo.vida_util_meses, 2
      );
    END IF;
    v_incremento := v_objetivo - v_activo.acumulado;
    IF v_incremento > 0 THEN
      v_detalles := v_detalles || jsonb_build_array(jsonb_build_object(
        'id_activo_fijo', v_activo.id_activo_fijo,
        'importe', v_incremento
      ));
      v_total := v_total + v_incremento;
    END IF;
  END LOOP;
  IF v_total <= 0 THEN
    RAISE EXCEPTION 'No hay depreciacion pendiente para ese periodo y sucursal.';
  END IF;

  WITH importes AS (
    SELECT a.id_cuenta_gasto_depreciacion AS id_cuenta,
           sum(x.importe)::numeric(14,2) AS monto
    FROM jsonb_to_recordset(v_detalles)
      x(id_activo_fijo bigint, importe numeric)
    JOIN public.activos_fijos a
      ON a.id_empresa = v_empresa AND a.id_activo_fijo = x.id_activo_fijo
    GROUP BY a.id_cuenta_gasto_depreciacion
    UNION ALL
    SELECT a.id_cuenta_depreciacion_acumulada AS id_cuenta,
           sum(x.importe)::numeric(14,2) AS monto
    FROM jsonb_to_recordset(v_detalles)
      x(id_activo_fijo bigint, importe numeric)
    JOIN public.activos_fijos a
      ON a.id_empresa = v_empresa AND a.id_activo_fijo = x.id_activo_fijo
    GROUP BY a.id_cuenta_depreciacion_acumulada
  )
  SELECT jsonb_agg(jsonb_build_object(
    'id_cuenta', i.id_cuenta,
    'debe', CASE WHEN i.id_cuenta IN (
      SELECT DISTINCT a.id_cuenta_gasto_depreciacion
      FROM jsonb_to_recordset(v_detalles)
        x(id_activo_fijo bigint, importe numeric)
      JOIN public.activos_fijos a
        ON a.id_empresa = v_empresa AND a.id_activo_fijo = x.id_activo_fijo
    ) THEN i.monto ELSE 0 END,
    'haber', CASE WHEN i.id_cuenta IN (
      SELECT DISTINCT a.id_cuenta_depreciacion_acumulada
      FROM jsonb_to_recordset(v_detalles)
        x(id_activo_fijo bigint, importe numeric)
      JOIN public.activos_fijos a
        ON a.id_empresa = v_empresa AND a.id_activo_fijo = x.id_activo_fijo
    ) THEN i.monto ELSE 0 END,
    'descripcion', CASE WHEN i.id_cuenta IN (
      SELECT DISTINCT a.id_cuenta_gasto_depreciacion
      FROM jsonb_to_recordset(v_detalles)
        x(id_activo_fijo bigint, importe numeric)
      JOIN public.activos_fijos a
        ON a.id_empresa = v_empresa AND a.id_activo_fijo = x.id_activo_fijo
    ) THEN 'Gasto de depreciacion fiscal'
    ELSE 'Depreciacion acumulada de activos fijos' END
  ) ORDER BY i.id_cuenta)
  INTO v_lineas
  FROM importes i;

  v_id_comprobante := public._registrar_asiento_operativo(
    v_empresa, p_id_sucursal, v_fecha_fin, 'AJUSTE',
    'Depreciacion fiscal de activos fijos ' || p_anio::text || '-' ||
      lpad(p_mes::text, 2, '0'),
    'DEPRECIACION_ACTIVO_FIJO',
    v_empresa::text || ':' || p_id_sucursal::text || ':' || v_id_periodo::text,
    v_lineas
  );
  INSERT INTO public.lotes_depreciacion_activos_fijos (
    id_empresa, id_sucursal, id_periodo, fecha_operativa, total,
    id_comprobante, clave_idempotencia, huella_solicitud, registrada_por
  )
  VALUES (
    v_empresa, p_id_sucursal, v_id_periodo, v_fecha_fin, v_total,
    v_id_comprobante, v_clave, v_huella, v_usuario
  )
  RETURNING id_lote INTO v_id_lote;
  INSERT INTO public.depreciaciones_activos_fijos (
    id_empresa, id_lote, id_activo_fijo, importe
  )
  SELECT v_empresa, v_id_lote, x.id_activo_fijo, x.importe
  FROM jsonb_to_recordset(v_detalles)
    x(id_activo_fijo bigint, importe numeric);
  RETURN v_id_lote;
END;
$$;

