BEGIN;

CREATE TABLE public.categorias_activos_fijos (
  id_categoria bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  codigo text NOT NULL CHECK (char_length(trim(codigo)) BETWEEN 1 AND 40),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) BETWEEN 1 AND 120),
  vida_util_meses integer NOT NULL CHECK (vida_util_meses BETWEEN 1 AND 1200),
  referencia_normativa text,
  id_cuenta_activo bigint NOT NULL,
  id_cuenta_depreciacion_acumulada bigint NOT NULL,
  id_cuenta_gasto_depreciacion bigint NOT NULL,
  activa boolean NOT NULL DEFAULT true,
  creada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  actualizada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id_categoria),
  UNIQUE (id_empresa, codigo),
  FOREIGN KEY (id_empresa, id_cuenta_activo)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta),
  FOREIGN KEY (id_empresa, id_cuenta_depreciacion_acumulada)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta),
  FOREIGN KEY (id_empresa, id_cuenta_gasto_depreciacion)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta)
);

CREATE TABLE public.adquisiciones_activos_fijos (
  id_adquisicion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  tipo_adquisicion text NOT NULL CHECK (tipo_adquisicion IN ('CONTADO', 'CREDITO')),
  id_proveedor bigint,
  id_cuenta_contrapartida bigint,
  fecha_adquisicion date NOT NULL,
  documento_referencia text,
  monto numeric(14,2) NOT NULL CHECK (monto > 0),
  id_comprobante bigint NOT NULL,
  clave_idempotencia text NOT NULL
    CHECK (char_length(trim(clave_idempotencia)) BETWEEN 1 AND 128),
  huella_solicitud text NOT NULL,
  registrada_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  registrada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id_adquisicion),
  UNIQUE (id_empresa, clave_idempotencia),
  FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal),
  FOREIGN KEY (id_empresa, id_proveedor)
    REFERENCES public.proveedores (id_empresa, id_proveedor),
  FOREIGN KEY (id_empresa, id_cuenta_contrapartida)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta),
  FOREIGN KEY (id_empresa, id_comprobante)
    REFERENCES public.comprobantes_contables (id_empresa, id_comprobante),
  CHECK (
    (tipo_adquisicion = 'CONTADO'
      AND id_cuenta_contrapartida IS NOT NULL)
    OR
    (tipo_adquisicion = 'CREDITO'
      AND id_proveedor IS NOT NULL
      AND id_cuenta_contrapartida IS NULL)
  )
);

CREATE TABLE public.activos_fijos (
  id_activo_fijo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_categoria bigint NOT NULL,
  id_adquisicion bigint NOT NULL,
  codigo text NOT NULL CHECK (char_length(trim(codigo)) BETWEEN 1 AND 80),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) BETWEEN 1 AND 160),
  descripcion text,
  numero_serie text,
  fecha_adquisicion date NOT NULL,
  fecha_puesta_en_servicio date NOT NULL,
  costo_adquisicion numeric(14,2) NOT NULL CHECK (costo_adquisicion > 0),
  valor_residual numeric(14,2) NOT NULL DEFAULT 0
    CHECK (valor_residual >= 0 AND valor_residual < costo_adquisicion),
  vida_util_meses integer NOT NULL CHECK (vida_util_meses BETWEEN 1 AND 1200),
  id_cuenta_activo bigint NOT NULL,
  id_cuenta_depreciacion_acumulada bigint NOT NULL,
  id_cuenta_gasto_depreciacion bigint NOT NULL,
  ubicacion text,
  responsable text,
  registrada_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  registrada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id_activo_fijo),
  UNIQUE (id_empresa, codigo),
  UNIQUE (id_empresa, id_adquisicion),
  FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal),
  FOREIGN KEY (id_empresa, id_categoria)
    REFERENCES public.categorias_activos_fijos (id_empresa, id_categoria),
  FOREIGN KEY (id_empresa, id_adquisicion)
    REFERENCES public.adquisiciones_activos_fijos (id_empresa, id_adquisicion),
  FOREIGN KEY (id_empresa, id_cuenta_activo)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta),
  FOREIGN KEY (id_empresa, id_cuenta_depreciacion_acumulada)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta),
  FOREIGN KEY (id_empresa, id_cuenta_gasto_depreciacion)
    REFERENCES public.cuentas_contables (id_empresa, id_cuenta),
  CHECK (fecha_puesta_en_servicio >= fecha_adquisicion)
);

