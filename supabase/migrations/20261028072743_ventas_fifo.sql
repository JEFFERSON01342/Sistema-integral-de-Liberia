  id_movimiento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_bodega bigint NOT NULL,
  id_ubicacion bigint NOT NULL,
  id_producto bigint NOT NULL,
  tipo text NOT NULL CHECK (
    tipo IN ('INVENTARIO_INICIAL', 'VENTA', 'COMPRA', 'TRANSFERENCIA_ENTRADA',
      'TRANSFERENCIA_SALIDA', 'AJUSTE_ENTRADA', 'AJUSTE_SALIDA')
  ),
  cantidad_delta numeric(14, 3) NOT NULL CHECK (cantidad_delta <> 0),
  costo_total numeric(14, 2) NOT NULL CHECK (costo_total >= 0),
  descripcion text,
  fecha_operativa date NOT NULL,
  registrado_en timestamptz NOT NULL,
  registrado_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  origen_tipo text,
  origen_id text,
  CONSTRAINT movimientos_inventario_producto_empresa_fkey
    FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto),
  CONSTRAINT movimientos_inventario_ubicacion_fkey
    FOREIGN KEY (id_empresa, id_sucursal, id_bodega, id_ubicacion)
    REFERENCES public.ubicaciones_bodega
      (id_empresa, id_sucursal, id_bodega, id_ubicacion),
  CONSTRAINT movimientos_inventario_origen_check CHECK (
    (origen_tipo IS NULL AND origen_id IS NULL)
    OR (
      char_length(trim(origen_tipo)) > 0
      AND char_length(trim(origen_id)) > 0
    )
  )
);

CREATE INDEX movimientos_inventario_producto_fecha_idx
  ON public.movimientos_inventario
    (id_empresa, id_sucursal, id_producto, registrado_en, id_movimiento);

CREATE TABLE public.ventas (
  id_venta bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_caja bigint NOT NULL,
  id_sesion bigint NOT NULL,
  numero text GENERATED ALWAYS AS ('V-' || id_venta::text) STORED,
  fecha_operativa date NOT NULL,
  registrada_en timestamptz NOT NULL,
  metodo_pago text NOT NULL
    CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA')),
  subtotal numeric(14, 2) NOT NULL CHECK (subtotal > 0),
  impuesto numeric(14, 2) NOT NULL DEFAULT 0 CHECK (impuesto >= 0),
  total numeric(14, 2) NOT NULL CHECK (total = subtotal + impuesto),
  efectivo_recibido numeric(14, 2),
  cambio numeric(14, 2),
  costo_total_fifo numeric(14, 2) NOT NULL CHECK (costo_total_fifo >= 0),
  id_comprobante bigint,
  idempotencia_key text NOT NULL CHECK (
    char_length(trim(idempotencia_key)) BETWEEN 1 AND 128
  ),
  huella_solicitud text NOT NULL,
  registrada_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  CONSTRAINT ventas_empresa_id_key UNIQUE (id_empresa, id_venta),
  CONSTRAINT ventas_empresa_numero_key UNIQUE (id_empresa, numero),
  CONSTRAINT ventas_idempotencia_key UNIQUE (id_empresa, idempotencia_key),
  CONSTRAINT ventas_comprobante_key UNIQUE (id_empresa, id_comprobante),
  CONSTRAINT ventas_sesion_fkey
    FOREIGN KEY (id_empresa, id_sucursal, id_caja, id_sesion)
    REFERENCES public.sesiones_caja
      (id_empresa, id_sucursal, id_caja, id_sesion),
  CONSTRAINT ventas_comprobante_fkey
    FOREIGN KEY (id_empresa, id_comprobante)
    REFERENCES public.comprobantes_contables (id_empresa, id_comprobante),
  CONSTRAINT ventas_pago_check CHECK (
    (
      metodo_pago = 'EFECTIVO'
      AND efectivo_recibido >= total
      AND cambio = efectivo_recibido - total
    )
    OR (
      metodo_pago IN ('TARJETA', 'TRANSFERENCIA')
      AND efectivo_recibido IS NULL
      AND cambio IS NULL
    )
  )
);

CREATE INDEX ventas_sucursal_fecha_idx
