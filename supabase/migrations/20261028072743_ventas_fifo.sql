CREATE TABLE public.productos (
  id_producto bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  sku text NOT NULL CHECK (char_length(trim(sku)) > 0),
  nombre text NOT NULL CHECK (char_length(trim(nombre)) > 0),
  descripcion text,
  precio_venta numeric(14, 2) NOT NULL CHECK (precio_venta > 0),
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT productos_empresa_sku_key UNIQUE (id_empresa, sku),
  CONSTRAINT productos_empresa_id_key UNIQUE (id_empresa, id_producto)
);

CREATE TABLE public.capas_inventario_fifo (
  id_capa bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_sucursal integer NOT NULL,
  id_bodega bigint NOT NULL,
  id_ubicacion bigint NOT NULL,
  id_producto bigint NOT NULL,
  cantidad_inicial numeric(14, 3) NOT NULL CHECK (cantidad_inicial > 0),
  cantidad_disponible numeric(14, 3) NOT NULL CHECK (
    cantidad_disponible >= 0 AND cantidad_disponible <= cantidad_inicial
  ),
  costo_unitario numeric(14, 4) NOT NULL CHECK (costo_unitario > 0),
  origen_tipo text NOT NULL CHECK (
    origen_tipo IN ('INVENTARIO_INICIAL', 'COMPRA', 'TRANSFERENCIA')
  ),
  origen_id text,
  recibido_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  registrado_por uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  CONSTRAINT capas_fifo_empresa_id_key UNIQUE (id_empresa, id_capa),
  CONSTRAINT capas_fifo_producto_empresa_fkey
    FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto),
  CONSTRAINT capas_fifo_ubicacion_fkey
    FOREIGN KEY (id_empresa, id_sucursal, id_bodega, id_ubicacion)
    REFERENCES public.ubicaciones_bodega
      (id_empresa, id_sucursal, id_bodega, id_ubicacion),
  CONSTRAINT capas_fifo_origen_check CHECK (
    origen_id IS NULL OR char_length(trim(origen_id)) > 0
  )
);

CREATE INDEX capas_fifo_saldo_idx
  ON public.capas_inventario_fifo
    (id_empresa, id_sucursal, id_ubicacion, id_producto, recibido_en, id_capa)
  WHERE cantidad_disponible > 0;

CREATE UNIQUE INDEX capas_fifo_inventario_inicial_idempotencia_key
