CREATE OR REPLACE FUNCTION public.registrar_inventario_inicial(
  p_id_producto bigint,
  p_cantidad numeric,
  p_costo_unitario numeric,
  p_motivo text,
  p_idempotencia_key text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_id_bodega bigint;
  v_id_ubicacion bigint;
  v_zona text;
  v_fecha date;
  v_ahora timestamptz := clock_timestamp();
  v_periodo bigint;
  v_producto_activo boolean;
  v_id_capa bigint;
  v_capa_producto bigint;
  v_capa_cantidad numeric(14, 3);
  v_capa_costo numeric(14, 4);
  v_id_comprobante bigint;
  v_id_cuenta_inventario bigint;
  v_id_capital bigint;
  v_id_movimiento bigint;
  v_total numeric(14, 2);
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para cargar inventario inicial.';
  END IF;

  IF p_cantidad IS NULL OR p_cantidad <= 0
     OR p_cantidad <> round(p_cantidad, 3)
     OR p_costo_unitario IS NULL OR p_costo_unitario <= 0
     OR p_costo_unitario <> round(p_costo_unitario, 4) THEN
    RAISE EXCEPTION 'La cantidad debe ser positiva con máximo tres decimales y el costo unitario positivo con máximo cuatro.';
  END IF;

  IF p_motivo IS NULL OR char_length(trim(p_motivo)) < 3 THEN
    RAISE EXCEPTION 'El motivo del inventario inicial debe tener al menos tres caracteres.';
  END IF;

  IF p_idempotencia_key IS NULL
     OR char_length(trim(p_idempotencia_key)) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'La clave de idempotencia es obligatoria y debe tener entre 1 y 128 caracteres.';
  END IF;

  SELECT p.id_empresa, p.activo
  INTO v_empresa, v_producto_activo
  FROM public.productos AS p
  WHERE p.id_producto = p_id_producto
  FOR UPDATE;

  IF v_empresa IS NULL OR NOT v_producto_activo THEN
    RAISE EXCEPTION 'El producto no existe o está inactivo.';
  END IF;

  IF NOT (SELECT public.puede_administrar_empresa(v_empresa)) THEN
    RAISE EXCEPTION 'Solo un administrador puede registrar inventario inicial.';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.capas_inventario_fifo AS cf
    WHERE cf.id_empresa = v_empresa AND cf.origen_tipo = 'INVENTARIO_INICIAL'
      AND cf.origen_id = trim(p_idempotencia_key)
  ) THEN
    SELECT cf.id_capa, cf.id_producto, cf.cantidad_inicial, cf.costo_unitario
    INTO v_id_capa, v_capa_producto, v_capa_cantidad, v_capa_costo
    FROM public.capas_inventario_fifo AS cf
    WHERE cf.id_empresa = v_empresa AND cf.origen_tipo = 'INVENTARIO_INICIAL'
      AND cf.origen_id = trim(p_idempotencia_key);
    IF v_capa_producto <> p_id_producto
       OR v_capa_cantidad <> p_cantidad
       OR v_capa_costo <> p_costo_unitario THEN
      RAISE EXCEPTION 'La clave de inventario inicial ya se usó con datos diferentes.';
    END IF;
    RETURN v_id_capa;
  END IF;

  SELECT s.id_sucursal, e.zona_horaria
  INTO v_sucursal, v_zona
  FROM public.sucursales AS s
  JOIN public.empresa AS e ON e.id_empresa = s.id_empresa
  WHERE s.id_empresa = v_empresa
    AND s.activa
    AND e.activa
    AND s.es_principal
  ORDER BY s.id_sucursal
  LIMIT 1;

  IF v_sucursal IS NULL THEN
    RAISE EXCEPTION 'La empresa no tiene una sucursal principal activa.';
  END IF;

  SELECT b.id_bodega INTO v_id_bodega
  FROM public.bodegas AS b
  WHERE b.id_empresa = v_empresa
    AND b.id_sucursal = v_sucursal
    AND b.activa
  ORDER BY b.id_bodega
  LIMIT 1;

  SELECT u.id_ubicacion INTO v_id_ubicacion
  FROM public.ubicaciones_bodega AS u
  WHERE u.id_empresa = v_empresa
    AND u.id_sucursal = v_sucursal
    AND u.id_bodega = v_id_bodega
    AND u.tipo_area = 'PICKING'
    AND u.activa
  ORDER BY u.id_ubicacion
  LIMIT 1;

  IF v_id_bodega IS NULL OR v_id_ubicacion IS NULL THEN
    RAISE EXCEPTION 'Falta una bodega activa o una ubicación de ventas/exhibición PICKING.';
  END IF;

  v_fecha := (v_ahora AT TIME ZONE v_zona)::date;

  SELECT pc.id_periodo INTO v_periodo
  FROM public.periodos_contables AS pc
  WHERE pc.id_empresa = v_empresa
    AND v_fecha BETWEEN pc.fecha_inicio AND pc.fecha_fin
    AND pc.estado = 'ABIERTO'
  FOR SHARE;

  IF v_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha operativa actual.';
  END IF;

  SELECT c.id_cuenta INTO v_id_cuenta_inventario
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa AND c.codigo = '1.1.06'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;

  SELECT c.id_cuenta INTO v_id_capital
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa AND c.codigo = '3.1.01'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;

  IF v_id_cuenta_inventario IS NULL OR v_id_capital IS NULL THEN
    RAISE EXCEPTION 'Falta configurar las cuentas activas de inventario y capital aportado.';
  END IF;

  v_total := round(p_cantidad * p_costo_unitario, 2);
  IF v_total <= 0 THEN
    RAISE EXCEPTION 'El valor del inventario inicial debe ser al menos 0.01.';
  END IF;

  INSERT INTO public.capas_inventario_fifo (
    id_empresa, id_sucursal, id_bodega, id_ubicacion, id_producto,
    cantidad_inicial, cantidad_disponible, costo_unitario,
    origen_tipo, origen_id, recibido_en, registrado_por
  )
  VALUES (
    v_empresa, v_sucursal, v_id_bodega, v_id_ubicacion, p_id_producto,
    p_cantidad, p_cantidad, p_costo_unitario,
    'INVENTARIO_INICIAL', trim(p_idempotencia_key), v_ahora, v_usuario
  )
  RETURNING id_capa INTO v_id_capa;

  INSERT INTO public.movimientos_inventario (
    id_empresa, id_sucursal, id_bodega, id_ubicacion, id_producto,
    tipo, cantidad_delta, costo_total, descripcion, fecha_operativa,
    registrado_en, registrado_por, origen_tipo, origen_id
  )
  VALUES (
    v_empresa, v_sucursal, v_id_bodega, v_id_ubicacion, p_id_producto,
    'INVENTARIO_INICIAL', p_cantidad, v_total, trim(p_motivo), v_fecha,
    v_ahora, v_usuario, 'CAPA_FIFO', v_id_capa::text
  )
  RETURNING id_movimiento INTO v_id_movimiento;

  INSERT INTO public.comprobantes_contables (
    id_empresa, id_sucursal, id_periodo, tipo, fecha, descripcion,
    origen_tipo, origen_id, idempotencia_key, creado_por
  )
  VALUES (
    v_empresa, v_sucursal, v_periodo, 'APERTURA', v_fecha,
    'Inventario inicial: ' || trim(p_motivo),
    'INVENTARIO_INICIAL', v_id_movimiento::text,
    'INVENTARIO_INICIAL:' || trim(p_idempotencia_key), v_usuario
  )
  RETURNING id_comprobante INTO v_id_comprobante;

  INSERT INTO public.lineas_comprobante_contable (
    id_empresa, id_comprobante, id_cuenta, numero_linea, descripcion, debe, haber
  )
  VALUES
    (v_empresa, v_id_comprobante, v_id_cuenta_inventario, 1, 'Inventario inicial', v_total, 0),
    (v_empresa, v_id_comprobante, v_id_capital, 2, 'Contrapartida de apertura', 0, v_total);

  UPDATE public.comprobantes_contables
  SET estado = 'CONTABILIZADO',
      contabilizado_por = v_usuario,
      contabilizado_en = v_ahora
  WHERE id_empresa = v_empresa
    AND id_comprobante = v_id_comprobante;

  RETURN v_id_capa;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_venta_pos(
  p_id_sesion bigint,
  p_items jsonb,
  p_metodo_pago text,
  p_efectivo_recibido numeric,
  p_idempotencia_key text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_caja bigint;
  v_estado_sesion text;
  v_zona text;
  v_fecha date;
  v_ahora timestamptz := clock_timestamp();
  v_periodo bigint;
  v_items jsonb;
  v_huella text;
  v_venta_existente bigint;
  v_huella_existente text;
  v_id_bodega bigint;
  v_id_ubicacion bigint;
  v_id_venta bigint;
  v_id_detalle bigint;
  v_id_comprobante bigint;
  v_id_cuenta_pago bigint;
  v_id_cuenta_ingreso bigint;
  v_id_cuenta_costo bigint;
  v_id_cuenta_inventario bigint;
  v_id_producto bigint;
  v_cantidad numeric(14, 3);
  v_precio numeric(14, 2);
  v_subtotal_linea numeric(14, 2);
  v_costo_linea numeric(14, 2);
  v_cantidad_pendiente numeric(14, 3);
  v_consumo numeric(14, 3);
  v_costo_unitario numeric(14, 4);
  v_costo_consumo numeric(14, 2);
  v_id_capa bigint;
  v_id_movimiento bigint;
  v_linea integer := 0;
  v_subtotal numeric(14, 2) := 0;
  v_costo_total numeric(14, 2) := 0;
  v_efectivo numeric(14, 2);
  v_cambio numeric(14, 2);
  v_clave text := trim(COALESCE(p_idempotencia_key, ''));
  v_producto record;
  v_capa record;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para registrar una venta.';
  END IF;

  IF p_metodo_pago IS NULL
     OR p_metodo_pago NOT IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA') THEN
    RAISE EXCEPTION 'El método de pago no es válido.';
  END IF;

  IF char_length(v_clave) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'La clave de idempotencia es obligatoria y debe tener entre 1 y 128 caracteres.';
  END IF;

  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Los productos de la venta deben enviarse como una lista.';
  END IF;

  IF jsonb_array_length(p_items) NOT BETWEEN 1 AND 50 THEN
    RAISE EXCEPTION 'La venta debe incluir entre 1 y 50 productos.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(p_items) AS e(value)
    WHERE jsonb_typeof(e.value) <> 'object'
       OR NOT (e.value ? 'id_producto')
       OR NOT (e.value ? 'cantidad')
       OR jsonb_typeof(e.value -> 'id_producto') <> 'number'
       OR jsonb_typeof(e.value -> 'cantidad') <> 'number'
  ) THEN
    RAISE EXCEPTION 'Cada producto debe incluir id_producto y cantidad numéricos.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric)
    WHERE i.id_producto IS NULL
       OR i.cantidad IS NULL
       OR i.cantidad <= 0
       OR i.cantidad <> round(i.cantidad, 3)
  ) THEN
    RAISE EXCEPTION 'Los productos deben tener identificador y cantidad positiva con máximo tres decimales.';
  END IF;

  IF EXISTS (
    SELECT i.id_producto
    FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric)
    GROUP BY i.id_producto
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'No repitas un producto en líneas diferentes; combina sus cantidades.';
  END IF;

  SELECT jsonb_agg(
    jsonb_build_object('id_producto', i.id_producto, 'cantidad', i.cantidad)
    ORDER BY i.id_producto
  )
  INTO v_items
  FROM jsonb_to_recordset(p_items) AS i(id_producto bigint, cantidad numeric);

  v_huella := md5(v_items::text || '|' || p_id_sesion::text || '|' || p_metodo_pago
    || '|' || COALESCE(p_efectivo_recibido::text, 'NULL'));

  SELECT sc.id_empresa, sc.id_sucursal, sc.id_caja, sc.estado, sc.zona_horaria
  INTO v_empresa, v_sucursal, v_caja, v_estado_sesion, v_zona
  FROM public.sesiones_caja AS sc
  WHERE sc.id_sesion = p_id_sesion
  FOR UPDATE;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'La sesión de caja no existe.';
  END IF;

  IF NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, false)) THEN
    RAISE EXCEPTION 'No tienes permiso para registrar ventas en esta sucursal.';
  END IF;

  SELECT v.id_venta, v.huella_solicitud
  INTO v_venta_existente, v_huella_existente
  FROM public.ventas AS v
  WHERE v.id_empresa = v_empresa
    AND v.idempotencia_key = v_clave;

  IF v_venta_existente IS NOT NULL THEN
    IF v_huella_existente <> v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó con datos diferentes.';
    END IF;
    RETURN v_venta_existente;
  END IF;

  IF v_estado_sesion <> 'ABIERTA' THEN
    RAISE EXCEPTION 'No se puede vender con una sesión de caja cerrada.';
  END IF;

  v_fecha := (v_ahora AT TIME ZONE v_zona)::date;

  SELECT pc.id_periodo INTO v_periodo
  FROM public.periodos_contables AS pc
  WHERE pc.id_empresa = v_empresa
    AND v_fecha BETWEEN pc.fecha_inicio AND pc.fecha_fin
    AND pc.estado = 'ABIERTO'
  FOR SHARE;

  IF v_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha real de la venta.';
  END IF;

  SELECT b.id_bodega INTO v_id_bodega
  FROM public.bodegas AS b
  WHERE b.id_empresa = v_empresa
    AND b.id_sucursal = v_sucursal
    AND b.activa
  ORDER BY b.id_bodega
  LIMIT 1;

  SELECT u.id_ubicacion INTO v_id_ubicacion
  FROM public.ubicaciones_bodega AS u
  WHERE u.id_empresa = v_empresa
    AND u.id_sucursal = v_sucursal
    AND u.id_bodega = v_id_bodega
    AND u.tipo_area = 'PICKING'
    AND u.activa
  ORDER BY u.id_ubicacion
  LIMIT 1;

  IF v_id_bodega IS NULL OR v_id_ubicacion IS NULL THEN
    RAISE EXCEPTION 'No existe una ubicación activa de ventas/exhibición para esta sucursal.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
    LEFT JOIN public.productos AS p
      ON p.id_empresa = v_empresa AND p.id_producto = i.id_producto
    WHERE p.id_producto IS NULL OR NOT p.activo
  ) THEN
    RAISE EXCEPTION 'Uno o más productos no existen, están inactivos o pertenecen a otra empresa.';
  END IF;

  PERFORM p.id_producto
  FROM public.productos AS p
  JOIN jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
    ON i.id_producto = p.id_producto
  WHERE p.id_empresa = v_empresa
  ORDER BY p.id_producto
  FOR UPDATE OF p;

  FOR v_producto IN
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta, i.cantidad
    FROM jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
    JOIN public.productos AS p
      ON p.id_empresa = v_empresa AND p.id_producto = i.id_producto
    ORDER BY p.id_producto
  LOOP
    SELECT COALESCE(sum(cf.cantidad_disponible), 0)
    INTO v_cantidad_pendiente
    FROM public.capas_inventario_fifo AS cf
    WHERE cf.id_empresa = v_empresa
      AND cf.id_sucursal = v_sucursal
      AND cf.id_ubicacion = v_id_ubicacion
      AND cf.id_producto = v_producto.id_producto;

    IF v_cantidad_pendiente < v_producto.cantidad THEN
      RAISE EXCEPTION 'Existencias insuficientes para el producto % (disponible %, solicitado %).',
        v_producto.sku, v_cantidad_pendiente, v_producto.cantidad;
    END IF;
  END LOOP;

  IF p_metodo_pago = 'EFECTIVO' THEN
    IF p_efectivo_recibido IS NULL
       OR p_efectivo_recibido <= 0
       OR p_efectivo_recibido <> round(p_efectivo_recibido, 2) THEN
      RAISE EXCEPTION 'El efectivo recibido debe ser positivo y tener máximo dos decimales.';
    END IF;
    v_efectivo := p_efectivo_recibido;
  ELSE
    IF p_efectivo_recibido IS NOT NULL THEN
      RAISE EXCEPTION 'No envíes efectivo recibido para pagos con tarjeta o transferencia.';
    END IF;
    v_efectivo := NULL;
  END IF;

  SELECT COALESCE(sum(round(i.cantidad * p.precio_venta, 2)), 0)::numeric(14, 2)
  INTO v_subtotal
  FROM jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
  JOIN public.productos AS p
    ON p.id_empresa = v_empresa AND p.id_producto = i.id_producto;

  IF v_subtotal <= 0 THEN
    RAISE EXCEPTION 'El total de la venta debe ser al menos 0.01.';
  END IF;

  IF p_metodo_pago = 'EFECTIVO' AND v_efectivo < v_subtotal THEN
    RAISE EXCEPTION 'El efectivo recibido no cubre el total de la venta (%).',
      v_subtotal;
  END IF;

  v_cambio := CASE
    WHEN p_metodo_pago = 'EFECTIVO' THEN v_efectivo - v_subtotal
    ELSE NULL
  END;

  INSERT INTO public.ventas (
    id_empresa, id_sucursal, id_caja, id_sesion, fecha_operativa,
    registrada_en, metodo_pago, subtotal, impuesto, total,
    efectivo_recibido, cambio, costo_total_fifo, idempotencia_key,
    huella_solicitud, registrada_por
  )
  VALUES (
    v_empresa, v_sucursal, v_caja, p_id_sesion, v_fecha,
    v_ahora, p_metodo_pago, v_subtotal, 0, v_subtotal,
    v_efectivo, v_cambio, 0, v_clave, v_huella, v_usuario
  )
  RETURNING id_venta INTO v_id_venta;

  v_subtotal := 0;

  FOR v_producto IN
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta, i.cantidad
    FROM jsonb_to_recordset(v_items) AS i(id_producto bigint, cantidad numeric)
    JOIN public.productos AS p
      ON p.id_empresa = v_empresa AND p.id_producto = i.id_producto
    ORDER BY p.id_producto
  LOOP
    v_linea := v_linea + 1;
    v_id_producto := v_producto.id_producto;
    v_cantidad := v_producto.cantidad;
    v_precio := v_producto.precio_venta;
    v_subtotal_linea := round(v_cantidad * v_precio, 2);
    v_costo_linea := 0;

    IF v_subtotal_linea <= 0 THEN
      RAISE EXCEPTION 'El subtotal de cada línea debe ser al menos 0.01.';
    END IF;

    INSERT INTO public.detalle_ventas (
      id_empresa, id_venta, id_producto, numero_linea,
      sku_snapshot, nombre_snapshot, cantidad, precio_unitario,
      subtotal_linea, costo_fifo
    )
    VALUES (
      v_empresa, v_id_venta, v_id_producto, v_linea,
      v_producto.sku, v_producto.nombre, v_cantidad, v_precio,
      v_subtotal_linea, 0
    )
    RETURNING id_detalle INTO v_id_detalle;

    v_cantidad_pendiente := v_cantidad;

    FOR v_capa IN
      SELECT cf.id_capa, cf.cantidad_disponible, cf.costo_unitario
      FROM public.capas_inventario_fifo AS cf
      WHERE cf.id_empresa = v_empresa
        AND cf.id_sucursal = v_sucursal
        AND cf.id_ubicacion = v_id_ubicacion
        AND cf.id_producto = v_id_producto
        AND cf.cantidad_disponible > 0
      ORDER BY cf.recibido_en, cf.id_capa
      FOR UPDATE OF cf
    LOOP
      EXIT WHEN v_cantidad_pendiente = 0;
      v_consumo := LEAST(v_cantidad_pendiente, v_capa.cantidad_disponible);
      v_costo_unitario := v_capa.costo_unitario;
      v_costo_consumo := round(v_consumo * v_costo_unitario, 2);
      v_cantidad_pendiente := v_cantidad_pendiente - v_consumo;
      v_costo_linea := v_costo_linea + v_costo_consumo;

      UPDATE public.capas_inventario_fifo
      SET cantidad_disponible = cantidad_disponible - v_consumo
      WHERE id_capa = v_capa.id_capa;

      INSERT INTO public.consumos_fifo_venta (
        id_empresa, id_venta, id_detalle, id_capa,
        cantidad, costo_unitario, costo_total
      )
      VALUES (
        v_empresa, v_id_venta, v_id_detalle, v_capa.id_capa,
        v_consumo, v_costo_unitario, v_costo_consumo
      );
    END LOOP;

    IF v_cantidad_pendiente <> 0 THEN
      RAISE EXCEPTION 'No fue posible asignar la cantidad completa de la capa FIFO para %.',
        v_producto.sku;
    END IF;

    v_costo_linea := round(v_costo_linea, 2);
    IF v_costo_linea <= 0 THEN
      RAISE EXCEPTION 'El costo FIFO del producto % debe ser al menos 0.01.',
        v_producto.sku;
    END IF;

    UPDATE public.detalle_ventas
    SET costo_fifo = v_costo_linea
    WHERE id_detalle = v_id_detalle;

    INSERT INTO public.movimientos_inventario (
      id_empresa, id_sucursal, id_bodega, id_ubicacion, id_producto,
      tipo, cantidad_delta, costo_total, descripcion, fecha_operativa,
      registrado_en, registrado_por, origen_tipo, origen_id
    )
    VALUES (
      v_empresa, v_sucursal, v_id_bodega, v_id_ubicacion, v_id_producto,
      'VENTA', -v_cantidad, v_costo_linea, 'Salida por venta POS',
      v_fecha, v_ahora, v_usuario, 'VENTA', v_id_venta::text
    );

    v_subtotal := v_subtotal + v_subtotal_linea;
    v_costo_total := v_costo_total + v_costo_linea;
  END LOOP;

  UPDATE public.ventas
  SET subtotal = v_subtotal,
      total = v_subtotal,
      efectivo_recibido = v_efectivo,
      cambio = v_cambio,
      costo_total_fifo = v_costo_total
  WHERE id_venta = v_id_venta;

  IF p_metodo_pago = 'EFECTIVO' THEN
    INSERT INTO public.movimientos_caja (
      id_empresa, id_sucursal, id_caja, id_sesion, tipo, monto,
      descripcion, fecha_operativa, registrado_en, registrado_por,
      origen_tipo, origen_id, idempotencia_key
    )
    VALUES (
      v_empresa, v_sucursal, v_caja, p_id_sesion, 'VENTA_EFECTIVO',
      v_subtotal, 'Venta ' || 'V-' || v_id_venta::text,
      v_fecha, v_ahora, v_usuario, 'VENTA', v_id_venta::text,
      'VENTA:' || v_id_venta::text
    );
  END IF;

  SELECT c.id_cuenta INTO v_id_cuenta_pago
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa
    AND c.codigo = CASE WHEN p_metodo_pago = 'EFECTIVO' THEN '1.1.02' ELSE '1.1.04' END
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;

  SELECT c.id_cuenta INTO v_id_cuenta_ingreso
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa AND c.codigo = '4.1.01'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;

  SELECT c.id_cuenta INTO v_id_cuenta_costo
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa AND c.codigo = '5.1.01'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;

  SELECT c.id_cuenta INTO v_id_cuenta_inventario
  FROM public.cuentas_contables AS c
  WHERE c.id_empresa = v_empresa AND c.codigo = '1.1.06'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;

  IF v_id_cuenta_pago IS NULL OR v_id_cuenta_ingreso IS NULL
     OR v_id_cuenta_costo IS NULL OR v_id_cuenta_inventario IS NULL THEN
    RAISE EXCEPTION 'Falta una cuenta contable activa requerida para registrar la venta.';
  END IF;

  INSERT INTO public.comprobantes_contables (
    id_empresa, id_sucursal, id_periodo, tipo, fecha, descripcion,
    origen_tipo, origen_id, idempotencia_key, creado_por
  )
  VALUES (
    v_empresa, v_sucursal, v_periodo, 'VENTA', v_fecha,
    'Venta POS V-' || v_id_venta::text || ' (' || p_metodo_pago || ')',
    'VENTA_POS', v_id_venta::text, 'VENTA_POS:' || v_id_venta::text, v_usuario
  )
  RETURNING id_comprobante INTO v_id_comprobante;

  INSERT INTO public.lineas_comprobante_contable (
    id_empresa, id_comprobante, id_cuenta, numero_linea, descripcion, debe, haber
  )
  VALUES
    (v_empresa, v_id_comprobante, v_id_cuenta_pago, 1,
      'Cobro de venta ' || 'V-' || v_id_venta::text, v_subtotal, 0),
    (v_empresa, v_id_comprobante, v_id_cuenta_ingreso, 2,
      'Ingreso por venta ' || 'V-' || v_id_venta::text, 0, v_subtotal),
    (v_empresa, v_id_comprobante, v_id_cuenta_costo, 3,
      'Costo FIFO de venta ' || 'V-' || v_id_venta::text, v_costo_total, 0),
    (v_empresa, v_id_comprobante, v_id_cuenta_inventario, 4,
      'Salida de inventario por venta ' || 'V-' || v_id_venta::text, 0, v_costo_total);

  UPDATE public.comprobantes_contables
  SET estado = 'CONTABILIZADO',
      contabilizado_por = v_usuario,
      contabilizado_en = v_ahora
  WHERE id_empresa = v_empresa
    AND id_comprobante = v_id_comprobante;

  UPDATE public.ventas
  SET id_comprobante = v_id_comprobante
  WHERE id_empresa = v_empresa
    AND id_venta = v_id_venta;

  RETURN v_id_venta;
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_inventario_inicial(
  bigint, numeric, numeric, text, text
) FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION public.registrar_venta_pos(
  bigint, jsonb, text, numeric, text
) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.registrar_inventario_inicial(
  bigint, numeric, numeric, text, text
) TO authenticated;
GRANT EXECUTE ON FUNCTION public.registrar_venta_pos(
  bigint, jsonb, text, numeric, text
) TO authenticated;

DO $$
DECLARE
  v_empresa record;
  v_sucursal record;
  v_fecha date;
  v_inicio date;
  v_fin date;
BEGIN
  IF (SELECT count(*) FROM public.empresa WHERE activa) <> 1 THEN
    RAISE EXCEPTION 'La preparación inicial requiere exactamente una empresa activa; revísela antes de continuar.';
  END IF;

  FOR v_empresa IN
    SELECT e.id_empresa, e.zona_horaria
    FROM public.empresa AS e
    WHERE e.activa
  LOOP
    v_fecha := (clock_timestamp() AT TIME ZONE v_empresa.zona_horaria)::date;
    v_inicio := date_trunc('month', v_fecha)::date;
    v_fin := (v_inicio + interval '1 month - 1 day')::date;

    INSERT INTO public.periodos_contables (
      id_empresa, anio, mes, fecha_inicio, fecha_fin
    )
    VALUES (
      v_empresa.id_empresa,
      extract(year FROM v_fecha)::integer,
      extract(month FROM v_fecha)::integer,
      v_inicio,
      v_fin
    )
    ON CONFLICT (id_empresa, anio, mes) DO NOTHING;

    SELECT s.id_sucursal, s.codigo
    INTO v_sucursal
    FROM public.sucursales AS s
    WHERE s.id_empresa = v_empresa.id_empresa
      AND s.es_principal
      AND s.activa
    ORDER BY s.id_sucursal
    LIMIT 1;

    IF v_sucursal.id_sucursal IS NULL THEN
      RAISE EXCEPTION 'La empresa activa no tiene una sucursal principal activa.';
    END IF;

    INSERT INTO public.cajas (
      id_empresa, id_sucursal, codigo, nombre, activa
    )
    VALUES (
      v_empresa.id_empresa,
      v_sucursal.id_sucursal,
      'CAJ-01',
      'Caja principal ' || v_sucursal.codigo,
      true
    )
    ON CONFLICT (id_sucursal, codigo) DO NOTHING;
  END LOOP;
END;
$$;

COMMIT;
