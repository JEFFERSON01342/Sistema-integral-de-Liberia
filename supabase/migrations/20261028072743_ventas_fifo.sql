CREATE OR REPLACE FUNCTION public.proteger_capa_fifo()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.id_empresa IS DISTINCT FROM OLD.id_empresa
     OR NEW.id_sucursal IS DISTINCT FROM OLD.id_sucursal
     OR NEW.id_bodega IS DISTINCT FROM OLD.id_bodega
     OR NEW.id_ubicacion IS DISTINCT FROM OLD.id_ubicacion
     OR NEW.id_producto IS DISTINCT FROM OLD.id_producto
     OR NEW.cantidad_inicial IS DISTINCT FROM OLD.cantidad_inicial
     OR NEW.costo_unitario IS DISTINCT FROM OLD.costo_unitario
     OR NEW.origen_tipo IS DISTINCT FROM OLD.origen_tipo
     OR NEW.origen_id IS DISTINCT FROM OLD.origen_id
     OR NEW.recibido_en IS DISTINCT FROM OLD.recibido_en
     OR NEW.registrado_por IS DISTINCT FROM OLD.registrado_por THEN
    RAISE EXCEPTION 'Los datos de origen y costo de una capa FIFO son inmutables.';
  END IF;

  IF NEW.cantidad_disponible > OLD.cantidad_disponible THEN
    RAISE EXCEPTION 'Una capa FIFO no puede recuperar cantidad consumida.';
  END IF;

  RETURN NEW;
END;
$$;

