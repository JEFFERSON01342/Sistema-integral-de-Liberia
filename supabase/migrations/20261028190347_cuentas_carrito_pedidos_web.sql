-- Cuentas de clientes, carrito persistente y pedidos de la tienda en línea.
-- Los pedidos no reservan inventario ni crean una venta hasta confirmar el pago real.

BEGIN;

CREATE TABLE public.carritos_web (
  id_carrito bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  actualizado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id_carrito),
  UNIQUE (id_empresa, user_id)
);

CREATE TABLE public.detalles_carrito_web (
  id_detalle_carrito bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_carrito bigint NOT NULL,
  id_producto bigint NOT NULL,
  cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
  actualizado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_carrito, id_producto),
  FOREIGN KEY (id_empresa, id_carrito)
    REFERENCES public.carritos_web (id_empresa, id_carrito) ON DELETE CASCADE,
  FOREIGN KEY (id_empresa, id_producto)
    REFERENCES public.productos (id_empresa, id_producto) ON DELETE CASCADE
);

CREATE TRIGGER detalles_carrito_web_precision_unidad
BEFORE INSERT OR UPDATE OF cantidad ON public.detalles_carrito_web
FOR EACH ROW EXECUTE FUNCTION public.validar_precision_cantidad_producto('cantidad');

CREATE TABLE public.pedidos_web (
  id_pedido bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL REFERENCES public.empresa (id_empresa),
  id_sucursal integer NOT NULL,
  user_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  numero_orden text GENERATED ALWAYS AS
    ('P-' || lpad(id_pedido::text, 6, '0')) STORED,
  nombre_cliente text NOT NULL CHECK (char_length(trim(nombre_cliente)) BETWEEN 2 AND 160),
  telefono text NOT NULL CHECK (char_length(trim(telefono)) BETWEEN 6 AND 32),
  email text,
  tipo_entrega text NOT NULL CHECK (tipo_entrega IN ('RETIRO', 'DOMICILIO')),
  direccion_entrega text,
  notas text,
  metodo_pago_preferido text NOT NULL
    CHECK (metodo_pago_preferido IN ('EFECTIVO', 'TARJETA_SIMULADA', 'TRANSFERENCIA')),
  metodo_pago_real text
    CHECK (metodo_pago_real IS NULL OR metodo_pago_real IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA')),
  subtotal numeric(14,2) NOT NULL CHECK (subtotal > 0),
  impuesto numeric(14,2) NOT NULL DEFAULT 0 CHECK (impuesto = 0),
  total numeric(14,2) NOT NULL CHECK (total = subtotal + impuesto),
  estado text NOT NULL DEFAULT 'PENDIENTE'
    CHECK (estado IN ('PENDIENTE', 'LISTO', 'ENTREGADO', 'RECHAZADO', 'CANCELADO')),
  estado_pago text NOT NULL DEFAULT 'PENDIENTE'
    CHECK (estado_pago IN ('PENDIENTE', 'SIMULADO', 'CONFIRMADO')),
  id_venta bigint,
  clave_idempotencia text NOT NULL
    CHECK (trim(clave_idempotencia) ~*
      '^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$'),
  huella_solicitud text NOT NULL,
  aceptado_por uuid REFERENCES auth.users (id) ON DELETE RESTRICT,
  aceptado_en timestamptz,
  creado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  actualizado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (id_empresa, id_pedido),
  UNIQUE (id_empresa, numero_orden),
  UNIQUE (id_empresa, clave_idempotencia),
  FOREIGN KEY (id_empresa, id_sucursal)
    REFERENCES public.sucursales (id_empresa, id_sucursal),
  FOREIGN KEY (id_empresa, id_venta)
    REFERENCES public.ventas (id_empresa, id_venta),
  CHECK (
    (tipo_entrega = 'DOMICILIO' AND char_length(trim(COALESCE(direccion_entrega, ''))) >= 5)
    OR (tipo_entrega = 'RETIRO' AND direccion_entrega IS NULL)
  ),
  CHECK (
    (id_venta IS NULL AND estado_pago <> 'CONFIRMADO'
      AND metodo_pago_real IS NULL AND aceptado_por IS NULL AND aceptado_en IS NULL)
    OR (id_venta IS NOT NULL AND estado_pago = 'CONFIRMADO'
      AND metodo_pago_real IS NOT NULL AND aceptado_por IS NOT NULL AND aceptado_en IS NOT NULL)
  ),
  CHECK (
    (id_venta IS NULL AND estado NOT IN ('LISTO', 'ENTREGADO'))
    OR (id_venta IS NOT NULL AND estado IN ('LISTO', 'ENTREGADO'))
  )
);

CREATE TABLE public.detalles_pedido_web (
  id_detalle_pedido bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa integer NOT NULL,
  id_pedido bigint NOT NULL,
  numero_linea integer NOT NULL CHECK (numero_linea > 0),
  id_producto bigint REFERENCES public.productos (id_producto) ON DELETE SET NULL,
  sku_snapshot text NOT NULL,
  nombre_snapshot text NOT NULL,
  imagen_snapshot text,
  cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
  precio_unitario numeric(14,2) NOT NULL CHECK (precio_unitario > 0),
  subtotal_linea numeric(14,2) NOT NULL
    CHECK (subtotal_linea = round(cantidad * precio_unitario, 2) AND subtotal_linea > 0),
  UNIQUE (id_pedido, numero_linea),
  FOREIGN KEY (id_empresa, id_pedido)
    REFERENCES public.pedidos_web (id_empresa, id_pedido) ON DELETE CASCADE
);

CREATE TRIGGER detalles_pedido_web_precision_unidad
BEFORE INSERT OR UPDATE OF cantidad ON public.detalles_pedido_web
FOR EACH ROW EXECUTE FUNCTION public.validar_precision_cantidad_producto('cantidad');

CREATE TABLE public.accesos_pedido_web (
  id_pedido bigint PRIMARY KEY REFERENCES public.pedidos_web (id_pedido) ON DELETE CASCADE,
  token_acceso uuid NOT NULL UNIQUE
);

CREATE INDEX pedidos_web_sucursal_estado_fecha_idx
  ON public.pedidos_web (id_empresa, id_sucursal, estado, creado_en DESC);
CREATE INDEX pedidos_web_cliente_fecha_idx
  ON public.pedidos_web (id_empresa, user_id, creado_en DESC)
  WHERE user_id IS NOT NULL;
CREATE INDEX detalles_pedido_web_producto_idx
  ON public.detalles_pedido_web (id_empresa, id_producto, id_pedido);

ALTER TABLE public.carritos_web ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalles_carrito_web ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pedidos_web ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalles_pedido_web ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.accesos_pedido_web ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.carritos_web, public.detalles_carrito_web,
  public.pedidos_web, public.detalles_pedido_web, public.accesos_pedido_web
  FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON TABLE public.carritos_web, public.detalles_carrito_web,
  public.pedidos_web, public.detalles_pedido_web TO authenticated;

CREATE POLICY carritos_web_select_propio
ON public.carritos_web FOR SELECT TO authenticated
USING (user_id = (SELECT auth.uid()));

CREATE POLICY detalles_carrito_web_select_propio
ON public.detalles_carrito_web FOR SELECT TO authenticated
USING (EXISTS (
  SELECT 1
  FROM public.carritos_web c
  WHERE c.id_empresa = detalles_carrito_web.id_empresa
    AND c.id_carrito = detalles_carrito_web.id_carrito
    AND c.user_id = (SELECT auth.uid())
));

CREATE POLICY pedidos_web_select_cliente_o_staff
ON public.pedidos_web FOR SELECT TO authenticated
USING (
  user_id = (SELECT auth.uid())
  OR (SELECT public.puede_ver_caja(id_empresa, id_sucursal))
);

CREATE POLICY detalles_pedido_web_select_cliente_o_staff
ON public.detalles_pedido_web FOR SELECT TO authenticated
USING (EXISTS (
  SELECT 1
  FROM public.pedidos_web p
  WHERE p.id_empresa = detalles_pedido_web.id_empresa
    AND p.id_pedido = detalles_pedido_web.id_pedido
    AND (
      p.user_id = (SELECT auth.uid())
      OR (SELECT public.puede_ver_caja(p.id_empresa, p.id_sucursal))
    )
));

CREATE VIEW public.catalogo_web_productos
WITH (security_barrier = true)
AS
SELECT
  p.id_empresa,
  p.id_producto,
  p.sku,
  p.nombre,
  p.descripcion,
  p.precio_venta,
  p.codigo_barras,
  p.imagen_principal,
  p.id_categoria,
  cp.nombre AS categoria,
  p.id_unidad_medida,
  um.nombre AS unidad_medida,
  um.abreviatura AS unidad_abreviatura,
  s.id_sucursal,
  s.nombre AS sucursal,
  COALESCE(sum(f.cantidad_disponible), 0)::numeric(14,3) AS cantidad_disponible
FROM public.productos p
JOIN public.empresa e ON e.id_empresa = p.id_empresa AND e.activa
JOIN public.sucursales s ON s.id_empresa = p.id_empresa AND s.activa
LEFT JOIN public.categorias_producto cp
  ON cp.id_empresa = p.id_empresa AND cp.id_categoria = p.id_categoria AND cp.activa
LEFT JOIN public.unidades_medidas um
  ON um.id_empresa = p.id_empresa AND um.id_unidad_medida = p.id_unidad_medida AND um.activa
LEFT JOIN public.capas_inventario_fifo f
  ON f.id_empresa = p.id_empresa
  AND f.id_sucursal = s.id_sucursal
  AND f.id_producto = p.id_producto
  AND f.cantidad_disponible > 0
WHERE p.activo
GROUP BY
  p.id_empresa, p.id_producto, p.sku, p.nombre, p.descripcion, p.precio_venta,
  p.codigo_barras, p.imagen_principal, p.id_categoria, cp.nombre,
  p.id_unidad_medida, um.nombre, um.abreviatura, s.id_sucursal, s.nombre;
GRANT SELECT ON public.catalogo_web_productos TO anon, authenticated;

CREATE OR REPLACE FUNCTION public._registrar_pedido_web(
  p_id_empresa integer,
  p_user_id uuid,
  p_datos jsonb,
  p_items jsonb,
  p_clave_idempotencia text,
  p_pago_simulado boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_id_sucursal integer;
  v_tipo_entrega text;
  v_metodo_pago text;
  v_nombre text;
  v_telefono text;
  v_email text;
  v_direccion text;
  v_notas text;
  v_estado_pago text;
  v_id_pedido bigint;
  v_numero_orden text;
  v_token uuid;
  v_huella text;
  v_item record;
  v_producto record;
  v_existencia numeric(14,3);
  v_total numeric(14,2) := 0;
  v_subtotal numeric(14,2);
  v_linea integer := 0;
  v_resumen jsonb := '[]'::jsonb;
  v_pedido_existente public.pedidos_web%ROWTYPE;
BEGIN
  IF p_id_empresa IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.empresa e WHERE e.id_empresa = p_id_empresa AND e.activa
  ) THEN
    RAISE EXCEPTION 'No hay una empresa activa para registrar el pedido.';
  END IF;
  IF p_user_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.perfiles p
    WHERE p.id = p_user_id AND p.activo AND p.rol = 'cliente'
  ) THEN
    RAISE EXCEPTION 'La cuenta no está habilitada como cliente de la tienda.';
  END IF;
  IF p_datos IS NULL OR jsonb_typeof(p_datos) <> 'object' THEN
    RAISE EXCEPTION 'Los datos de contacto y entrega son obligatorios.';
  END IF;
  IF p_clave_idempotencia IS NULL
     OR trim(p_clave_idempotencia) !~*
       '^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$' THEN
    RAISE EXCEPTION 'La clave de solicitud debe ser un UUID generado aleatoriamente.';
  END IF;

  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'El pedido debe contener entre 1 y 100 productos.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    WHERE x.id_producto IS NULL OR x.cantidad IS NULL OR x.cantidad <= 0
  ) OR EXISTS (
    SELECT x.id_producto
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    GROUP BY x.id_producto
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'El carrito contiene productos o cantidades inválidas o duplicadas.';
  END IF;
  SELECT md5(jsonb_build_object(
    'user_id', p_user_id,
    'datos', p_datos,
    'pago_simulado', COALESCE(p_pago_simulado, false),
    'items', COALESCE(jsonb_agg(jsonb_build_object(
      'id_producto', x.id_producto, 'cantidad', x.cantidad
    ) ORDER BY x.id_producto), '[]'::jsonb)
  )::text)
  INTO v_huella
  FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric);

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_id_empresa::text || ':' || trim(p_clave_idempotencia), 0)
  );
  SELECT p.* INTO v_pedido_existente
  FROM public.pedidos_web p
  WHERE p.id_empresa = p_id_empresa
    AND p.clave_idempotencia = trim(p_clave_idempotencia);
  IF FOUND THEN
    IF v_pedido_existente.user_id IS DISTINCT FROM p_user_id THEN
      RAISE EXCEPTION 'La clave de solicitud ya fue utilizada.';
    END IF;
    IF v_pedido_existente.huella_solicitud <> v_huella THEN
      RAISE EXCEPTION 'La clave de solicitud ya fue utilizada con otros datos.';
    END IF;
    SELECT a.token_acceso INTO v_token
    FROM public.accesos_pedido_web a
    WHERE a.id_pedido = v_pedido_existente.id_pedido;
    RETURN jsonb_build_object(
      'id_pedido', v_pedido_existente.id_pedido,
      'numero_orden', v_pedido_existente.numero_orden,
      'estado', v_pedido_existente.estado,
      'estado_pago', v_pedido_existente.estado_pago,
      'total', v_pedido_existente.total
    ) || CASE WHEN p_user_id IS NULL
      THEN jsonb_build_object('token_acceso', v_token)
      ELSE '{}'::jsonb
    END;
  END IF;

  v_tipo_entrega := upper(trim(COALESCE(p_datos ->> 'tipo_entrega', '')));
  IF v_tipo_entrega IN ('RECOGER EN TIENDA', 'RETIRO EN TIENDA', 'RECOGER', 'RETIRO') THEN
    v_tipo_entrega := 'RETIRO';
  ELSIF v_tipo_entrega = 'DOMICILIO' THEN
    v_tipo_entrega := 'DOMICILIO';
  ELSE
    RAISE EXCEPTION 'El tipo de entrega debe ser retiro o domicilio.';
  END IF;

  v_metodo_pago := upper(trim(COALESCE(p_datos ->> 'metodo_pago', '')));
  IF v_metodo_pago IN ('EFECTIVO EN LOCAL', 'PAGO EN LOCAL', 'EFECTIVO') THEN
    v_metodo_pago := 'EFECTIVO';
  ELSIF v_metodo_pago IN ('TARJETA', 'TARJETA_SIMULADA') THEN
    v_metodo_pago := 'TARJETA_SIMULADA';
  ELSIF v_metodo_pago = 'TRANSFERENCIA' THEN
    v_metodo_pago := 'TRANSFERENCIA';
  ELSE
    RAISE EXCEPTION 'El método de pago del pedido no es válido.';
  END IF;
  IF (v_metodo_pago = 'TARJETA_SIMULADA') IS DISTINCT FROM COALESCE(p_pago_simulado, false) THEN
    RAISE EXCEPTION 'La tarjeta solo puede registrarse como simulada después de completar la simulación.';
  END IF;

  v_nombre := trim(COALESCE(NULLIF(p_datos ->> 'nombre_cliente', ''), ''));
  v_telefono := trim(COALESCE(NULLIF(p_datos ->> 'telefono', ''), ''));
  v_email := NULLIF(trim(COALESCE(p_datos ->> 'email', '')), '');
  v_direccion := NULLIF(trim(COALESCE(p_datos ->> 'direccion_entrega', '')), '');
  v_notas := NULLIF(trim(COALESCE(p_datos ->> 'notas', '')), '');
  IF p_user_id IS NOT NULL THEN
    SELECT
      COALESCE(NULLIF(v_nombre, ''), p.nombre_completo, p.email),
      COALESCE(NULLIF(v_telefono, ''), p.telefono),
      COALESCE(v_email, p.email)
    INTO v_nombre, v_telefono, v_email
    FROM public.perfiles p
    WHERE p.id = p_user_id AND p.activo AND p.rol = 'cliente';
  END IF;
  IF char_length(v_nombre) NOT BETWEEN 2 AND 160
     OR char_length(v_telefono) NOT BETWEEN 6 AND 32 THEN
    RAISE EXCEPTION 'Ingresa un nombre y teléfono de contacto válidos.';
  END IF;
  IF v_tipo_entrega = 'DOMICILIO'
     AND char_length(COALESCE(v_direccion, '')) < 5 THEN
    RAISE EXCEPTION 'La dirección es obligatoria para entrega a domicilio.';
  END IF;
  IF v_tipo_entrega = 'RETIRO' AND v_direccion IS NOT NULL THEN
    RAISE EXCEPTION 'No se debe enviar dirección para un pedido de retiro.';
  END IF;

  v_id_sucursal := NULLIF(p_datos ->> 'id_sucursal', '')::integer;
  IF v_id_sucursal IS NULL AND v_tipo_entrega = 'DOMICILIO' THEN
    SELECT s.id_sucursal INTO v_id_sucursal
    FROM public.sucursales s
    WHERE s.id_empresa = p_id_empresa AND s.es_principal AND s.activa
    ORDER BY s.id_sucursal
    LIMIT 1;
  END IF;
  IF v_id_sucursal IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.sucursales s
    WHERE s.id_empresa = p_id_empresa
      AND s.id_sucursal = v_id_sucursal
      AND s.activa
  ) THEN
    RAISE EXCEPTION 'Selecciona una sucursal activa para el pedido.';
  END IF;

  FOR v_item IN
    SELECT x.id_producto, x.cantidad
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    ORDER BY x.id_producto
  LOOP
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta,
      p.imagen_principal, COALESCE(um.decimales_cantidad, 3) AS decimales
    INTO v_producto
    FROM public.productos p
    LEFT JOIN public.unidades_medidas um
      ON um.id_empresa = p.id_empresa
      AND um.id_unidad_medida = p.id_unidad_medida
    WHERE p.id_empresa = p_id_empresa
      AND p.id_producto = v_item.id_producto
      AND p.activo
    FOR SHARE OF p;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Uno de los productos ya no está disponible.';
    END IF;
    IF v_item.cantidad <> round(v_item.cantidad, v_producto.decimales) THEN
      RAISE EXCEPTION 'La cantidad del producto % excede la precisión de su unidad.',
        v_item.id_producto;
    END IF;
    SELECT COALESCE(sum(f.cantidad_disponible), 0)
    INTO v_existencia
    FROM public.capas_inventario_fifo f
    WHERE f.id_empresa = p_id_empresa
      AND f.id_sucursal = v_id_sucursal
      AND f.id_producto = v_item.id_producto
      AND f.cantidad_disponible > 0;
    IF v_existencia < v_item.cantidad THEN
      RAISE EXCEPTION 'Existencias insuficientes para el producto % en la sucursal elegida.',
        v_producto.nombre;
    END IF;

    v_linea := v_linea + 1;
    v_subtotal := round(v_item.cantidad * v_producto.precio_venta, 2);
    IF v_subtotal <= 0 THEN
      RAISE EXCEPTION 'El importe de cada producto debe ser mayor que cero.';
    END IF;
    v_total := v_total + v_subtotal;
    v_resumen := v_resumen || jsonb_build_array(jsonb_build_object(
      'numero_linea', v_linea,
      'id_producto', v_producto.id_producto,
      'sku', v_producto.sku,
      'nombre', v_producto.nombre,
      'imagen', v_producto.imagen_principal,
      'cantidad', v_item.cantidad,
      'precio_unitario', v_producto.precio_venta,
      'subtotal_linea', v_subtotal
    ));
  END LOOP;

  v_estado_pago := CASE WHEN v_metodo_pago = 'TARJETA_SIMULADA'
    THEN 'SIMULADO' ELSE 'PENDIENTE' END;
  INSERT INTO public.pedidos_web (
    id_empresa, id_sucursal, user_id, nombre_cliente, telefono, email,
    tipo_entrega, direccion_entrega, notas, metodo_pago_preferido,
    subtotal, impuesto, total, estado_pago, clave_idempotencia, huella_solicitud
  )
  VALUES (
    p_id_empresa, v_id_sucursal, p_user_id, v_nombre, v_telefono, v_email,
    v_tipo_entrega, v_direccion, v_notas, v_metodo_pago,
    v_total, 0, v_total, v_estado_pago, trim(p_clave_idempotencia), v_huella
  )
  RETURNING id_pedido, numero_orden INTO v_id_pedido, v_numero_orden;

  INSERT INTO public.detalles_pedido_web (
    id_empresa, id_pedido, numero_linea, id_producto, sku_snapshot,
    nombre_snapshot, imagen_snapshot, cantidad, precio_unitario, subtotal_linea
  )
  SELECT
    p_id_empresa, v_id_pedido, (x.item ->> 'numero_linea')::integer,
    (x.item ->> 'id_producto')::bigint, x.item ->> 'sku', x.item ->> 'nombre',
    x.item ->> 'imagen', (x.item ->> 'cantidad')::numeric,
    (x.item ->> 'precio_unitario')::numeric, (x.item ->> 'subtotal_linea')::numeric
  FROM jsonb_array_elements(v_resumen) AS x(item);

  IF p_user_id IS NULL THEN
    v_token := gen_random_uuid();
    INSERT INTO public.accesos_pedido_web (id_pedido, token_acceso)
    VALUES (v_id_pedido, v_token);
  END IF;

  RETURN jsonb_build_object(
    'id_pedido', v_id_pedido,
    'numero_orden', v_numero_orden,
    'estado', 'PENDIENTE',
    'estado_pago', v_estado_pago,
    'total', v_total
  ) || CASE WHEN p_user_id IS NULL
    THEN jsonb_build_object('token_acceso', v_token)
    ELSE '{}'::jsonb
  END;
END;
$$;

CREATE OR REPLACE FUNCTION public.actualizar_carrito_web(p_items jsonb)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_carrito bigint;
BEGIN
  IF v_usuario IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.perfiles p
    WHERE p.id = v_usuario AND p.activo AND p.rol = 'cliente'
  ) THEN
    RAISE EXCEPTION 'Inicia sesión con una cuenta de cliente para guardar el carrito.';
  END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) > 100 THEN
    RAISE EXCEPTION 'El carrito debe ser una lista de hasta 100 productos.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    WHERE x.id_producto IS NULL OR x.cantidad IS NULL OR x.cantidad <= 0
  ) OR EXISTS (
    SELECT x.id_producto
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    GROUP BY x.id_producto
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'El carrito contiene productos o cantidades inválidas o duplicadas.';
  END IF;
  SELECT e.id_empresa INTO STRICT v_empresa
  FROM public.empresa e
  WHERE e.activa
  ORDER BY e.id_empresa
  LIMIT 1;
  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric)
    LEFT JOIN public.productos p
      ON p.id_empresa = v_empresa AND p.id_producto = x.id_producto AND p.activo
    WHERE p.id_producto IS NULL
  ) THEN
    RAISE EXCEPTION 'El carrito incluye un producto inactivo o inexistente.';
  END IF;

  INSERT INTO public.carritos_web (id_empresa, user_id)
  VALUES (v_empresa, v_usuario)
  ON CONFLICT (id_empresa, user_id)
  DO UPDATE SET actualizado_en = clock_timestamp()
  RETURNING id_carrito INTO v_carrito;

  DELETE FROM public.detalles_carrito_web d
  WHERE d.id_empresa = v_empresa AND d.id_carrito = v_carrito;
  INSERT INTO public.detalles_carrito_web (id_empresa, id_carrito, id_producto, cantidad)
  SELECT v_empresa, v_carrito, x.id_producto, x.cantidad
  FROM jsonb_to_recordset(p_items) AS x(id_producto bigint, cantidad numeric);
  RETURN v_carrito;
END;
$$;

CREATE OR REPLACE FUNCTION public.checkout_carrito_web(
  p_datos jsonb,
  p_clave_idempotencia text,
  p_pago_simulado boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_items jsonb;
  v_carrito bigint;
  v_resultado jsonb;
BEGIN
  IF v_usuario IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.perfiles p
    WHERE p.id = v_usuario AND p.activo AND p.rol = 'cliente'
  ) THEN
    RAISE EXCEPTION 'Inicia sesión con una cuenta de cliente para finalizar el pedido.';
  END IF;
  SELECT e.id_empresa INTO STRICT v_empresa
  FROM public.empresa e
  WHERE e.activa
  ORDER BY e.id_empresa
  LIMIT 1;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(v_empresa::text || ':' || trim(COALESCE(p_clave_idempotencia, '')), 0)
  );
  IF EXISTS (
    SELECT 1 FROM public.pedidos_web p
    WHERE p.id_empresa = v_empresa AND p.user_id = v_usuario
      AND p.clave_idempotencia = trim(COALESCE(p_clave_idempotencia, ''))
  ) THEN
    RETURN (
      SELECT jsonb_build_object(
        'id_pedido', p.id_pedido, 'numero_orden', p.numero_orden,
        'estado', p.estado, 'estado_pago', p.estado_pago, 'total', p.total
      )
      FROM public.pedidos_web p
      WHERE p.id_empresa = v_empresa AND p.user_id = v_usuario
        AND p.clave_idempotencia = trim(p_clave_idempotencia)
    );
  END IF;

  SELECT c.id_carrito INTO v_carrito
  FROM public.carritos_web c
  WHERE c.id_empresa = v_empresa AND c.user_id = v_usuario
  FOR UPDATE;

  SELECT COALESCE(jsonb_agg(
    jsonb_build_object('id_producto', d.id_producto, 'cantidad', d.cantidad)
    ORDER BY d.id_producto
  ), '[]'::jsonb)
  INTO v_items
  FROM public.carritos_web c
  JOIN public.detalles_carrito_web d
    ON d.id_empresa = c.id_empresa AND d.id_carrito = c.id_carrito
  WHERE c.id_empresa = v_empresa AND c.user_id = v_usuario;

  v_resultado := public._registrar_pedido_web(
    v_empresa, v_usuario, p_datos, v_items, p_clave_idempotencia, p_pago_simulado
  );
  DELETE FROM public.detalles_carrito_web d
  WHERE d.id_empresa = v_empresa AND d.id_carrito = v_carrito;
  UPDATE public.carritos_web
  SET actualizado_en = clock_timestamp()
  WHERE id_empresa = v_empresa AND id_carrito = v_carrito;
  RETURN v_resultado;
END;
$$;

