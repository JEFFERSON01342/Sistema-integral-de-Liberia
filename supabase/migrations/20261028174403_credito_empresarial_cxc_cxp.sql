  ADD COLUMN plazo_credito_dias integer NOT NULL DEFAULT 0
    CHECK (plazo_credito_dias BETWEEN 0 AND 365);

ALTER TABLE public.ventas
  ALTER COLUMN id_caja DROP NOT NULL,
  ALTER COLUMN id_sesion DROP NOT NULL,
  DROP CONSTRAINT ventas_metodo_pago_check,
  DROP CONSTRAINT ventas_pago_check,
  ADD CONSTRAINT ventas_metodo_pago_check
    CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'MIXTO', 'CREDITO')),
  ADD CONSTRAINT ventas_pago_check CHECK (
    (
      metodo_pago = 'EFECTIVO'
      AND efectivo_recibido >= total
      AND cambio = efectivo_recibido - total
    )
    OR (
      metodo_pago IN ('TARJETA', 'TRANSFERENCIA')
      AND efectivo_recibido IS NULL
      AND cambio IS NULL
    )
    OR (
      metodo_pago = 'MIXTO'
      AND (
        (efectivo_recibido IS NULL AND cambio IS NULL)
        OR (
          efectivo_recibido IS NOT NULL
          AND efectivo_recibido >= 0
          AND cambio IS NOT NULL
          AND cambio >= 0
          AND cambio <= efectivo_recibido
        )
      )
    )
    OR (
      metodo_pago = 'CREDITO'
      AND efectivo_recibido IS NULL
      AND cambio IS NULL
    )
  ),
  ADD CONSTRAINT ventas_caja_credito_check CHECK (
    (
      metodo_pago = 'CREDITO'
      AND id_caja IS NULL
      AND id_sesion IS NULL
      AND id_cliente IS NOT NULL
    )
    OR (
      metodo_pago <> 'CREDITO'
      AND id_caja IS NOT NULL
      AND id_sesion IS NOT NULL
    )
  );

