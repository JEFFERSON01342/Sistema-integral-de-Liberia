BEGIN;

ALTER TABLE public.clientes
  ADD COLUMN tipo_cliente text NOT NULL DEFAULT 'PERSONA'
    CHECK (tipo_cliente IN ('PERSONA', 'EMPRESA')),
  ADD COLUMN limite_credito numeric(14,2) NOT NULL DEFAULT 0
    CHECK (limite_credito >= 0),
  ADD COLUMN plazo_credito_dias integer NOT NULL DEFAULT 0
    CHECK (plazo_credito_dias BETWEEN 0 AND 365);

