CREATE VIEW public.saldos_cuentas_por_cobrar
WITH (security_invoker = true)
AS
SELECT f.id_empresa, f.id_factura, f.numero, f.id_venta, f.id_cliente,
       f.fecha_emision, f.fecha_vencimiento, f.total,
       COALESCE(sum(a.monto), 0)::numeric(14,2) AS monto_cobrado,
       (f.total - COALESCE(sum(a.monto), 0))::numeric(14,2) AS saldo_pendiente,
       GREATEST(((clock_timestamp() AT TIME ZONE e.zona_horaria)::date
         - f.fecha_vencimiento), 0) AS dias_vencidos,
       CASE
         WHEN f.total = COALESCE(sum(a.monto), 0) THEN 'PAGADA'
         WHEN f.fecha_vencimiento < (clock_timestamp() AT TIME ZONE e.zona_horaria)::date THEN 'VENCIDA'
         ELSE 'PENDIENTE'
       END AS estado
FROM public.facturas_credito_empresa f
JOIN public.empresa e ON e.id_empresa = f.id_empresa
LEFT JOIN public.aplicaciones_cobro_factura_empresa a
  ON a.id_empresa = f.id_empresa AND a.id_factura = f.id_factura
GROUP BY f.id_empresa, f.id_factura, e.zona_horaria;

CREATE VIEW public.saldos_cuentas_por_pagar
WITH (security_invoker = true)
AS
SELECT c.id_empresa, c.id_cuenta_por_pagar, c.id_proveedor,
       c.id_recepcion, c.id_sucursal, c.fecha_emision, c.fecha_vencimiento,
       c.total, COALESCE(sum(a.monto), 0)::numeric(14,2) AS monto_pagado,
       (c.total - COALESCE(sum(a.monto), 0))::numeric(14,2) AS saldo_pendiente,
       GREATEST(((clock_timestamp() AT TIME ZONE e.zona_horaria)::date
         - c.fecha_vencimiento), 0) AS dias_vencidos,
       CASE
         WHEN c.total = COALESCE(sum(a.monto), 0) THEN 'PAGADA'
         WHEN c.fecha_vencimiento < (clock_timestamp() AT TIME ZONE e.zona_horaria)::date THEN 'VENCIDA'
         ELSE 'PENDIENTE'
       END AS estado
FROM public.cuentas_por_pagar c
JOIN public.empresa e ON e.id_empresa = c.id_empresa
LEFT JOIN public.aplicaciones_pago_proveedor a
  ON a.id_empresa = c.id_empresa
 AND a.id_cuenta_por_pagar = c.id_cuenta_por_pagar
GROUP BY c.id_empresa, c.id_cuenta_por_pagar, e.zona_horaria;

CREATE OR REPLACE FUNCTION public.crear_factura_credito_empresa(
  p_id_sucursal integer,
  p_id_cliente bigint,
  p_id_ubicacion bigint,
  p_items jsonb,
  p_clave_idempotencia text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_zona text;
  v_fecha date;
  v_ahora timestamptz := clock_timestamp();
  v_plazo integer;
  v_limite numeric(14,2);
  v_credito_usado numeric(14,2);
  v_id_bodega bigint;
  v_id_periodo bigint;
  v_id_venta bigint;
  v_id_factura bigint;
  v_id_comprobante bigint;
  v_id_cuenta_cxc bigint;
  v_id_cuenta_ingreso bigint;
  v_id_cuenta_costo bigint;
  v_id_cuenta_inventario bigint;
  v_items jsonb;
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
  v_huella text;
  v_huella_existente text;
  v_existente bigint;
  v_linea record;
  v_capa record;
  v_id_detalle bigint;
  v_numero integer := 0;
  v_pendiente numeric(14,3);
  v_consumo numeric(14,3);
  v_costo_unitario numeric(14,4);
  v_costo_linea numeric(14,2);
  v_costo_total numeric(14,2) := 0;
  v_subtotal numeric(14,2) := 0;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para emitir una factura empresarial.';
  END IF;
  IF char_length(v_clave) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'La clave de idempotencia debe tener entre 1 y 128 caracteres.';
  END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 50 THEN
    RAISE EXCEPTION 'La factura debe incluir entre 1 y 50 productos.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(p_items) e(value)
    WHERE jsonb_typeof(e.value) <> 'object'
       OR jsonb_typeof(e.value -> 'id_producto') <> 'number'
       OR jsonb_typeof(e.value -> 'cantidad') <> 'number'
  ) OR EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_items) x(id_producto bigint, cantidad numeric)
    WHERE x.id_producto IS NULL OR x.cantidad IS NULL
       OR x.cantidad <= 0 OR x.cantidad <> round(x.cantidad, 3)
  ) THEN
    RAISE EXCEPTION 'Cada línea requiere un producto y una cantidad positiva de hasta tres decimales.';
  END IF;
  IF EXISTS (
    SELECT id_producto FROM jsonb_to_recordset(p_items)
      x(id_producto bigint, cantidad numeric)
    GROUP BY id_producto HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'No repitas productos en la factura.';
  END IF;

  SELECT s.id_empresa, e.zona_horaria
  INTO v_empresa, v_zona
  FROM public.sucursales s
  JOIN public.empresa e ON e.id_empresa = s.id_empresa AND e.activa
  WHERE s.id_sucursal = p_id_sucursal AND s.activa;
  IF v_empresa IS NULL
     OR NOT (SELECT public.puede_administrar_empresa(v_empresa)) THEN
    RAISE EXCEPTION 'Solo un administrador puede emitir facturas de crédito empresarial.';
  END IF;

  SELECT jsonb_agg(jsonb_build_object(
    'id_producto', x.id_producto, 'cantidad', x.cantidad
  ) ORDER BY x.id_producto)
  INTO v_items
  FROM jsonb_to_recordset(p_items) x(id_producto bigint, cantidad numeric);
  v_huella := md5(v_empresa::text || '|' || p_id_sucursal::text || '|'
    || p_id_cliente::text || '|' || p_id_ubicacion::text || '|' || v_items::text);

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('FCE:' || v_empresa::text || ':' || v_clave, 0)
  );
  SELECT f.id_factura, f.huella_solicitud
  INTO v_existente, v_huella_existente
  FROM public.facturas_credito_empresa f
  WHERE f.id_empresa = v_empresa AND f.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_huella_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó con datos distintos.';
    END IF;
    RETURN v_existente;
  END IF;

  SELECT c.limite_credito, c.plazo_credito_dias
  INTO v_limite, v_plazo
  FROM public.clientes c
  WHERE c.id_empresa = v_empresa
    AND c.id_cliente = p_id_cliente
    AND c.activo
    AND c.tipo_cliente = 'EMPRESA'
  FOR UPDATE;
  IF NOT FOUND OR v_limite <= 0 OR v_plazo <= 0 THEN
    RAISE EXCEPTION 'El cliente debe ser una empresa activa con cupo y plazo de crédito autorizados.';
  END IF;

  SELECT u.id_bodega INTO v_id_bodega
  FROM public.ubicaciones_bodega u
  WHERE u.id_empresa = v_empresa AND u.id_sucursal = p_id_sucursal
    AND u.id_ubicacion = p_id_ubicacion AND u.activa;
  IF v_id_bodega IS NULL THEN
    RAISE EXCEPTION 'La ubicación de salida no existe o está inactiva.';
  END IF;

  v_fecha := (v_ahora AT TIME ZONE v_zona)::date;
  SELECT pc.id_periodo INTO v_id_periodo
  FROM public.periodos_contables pc
  WHERE pc.id_empresa = v_empresa AND pc.estado = 'ABIERTO'
    AND v_fecha BETWEEN pc.fecha_inicio AND pc.fecha_fin
  FOR SHARE;
  IF v_id_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha de emisión.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(v_items) x(id_producto bigint, cantidad numeric)
    LEFT JOIN public.productos p
      ON p.id_empresa = v_empresa AND p.id_producto = x.id_producto
    WHERE p.id_producto IS NULL OR NOT p.activo
  ) THEN
    RAISE EXCEPTION 'Uno o más productos no existen, están inactivos o pertenecen a otra empresa.';
  END IF;
  PERFORM p.id_producto
  FROM public.productos p
  JOIN jsonb_to_recordset(v_items) x(id_producto bigint, cantidad numeric)
    ON x.id_producto = p.id_producto
  WHERE p.id_empresa = v_empresa
  ORDER BY p.id_producto
  FOR UPDATE OF p;

  FOR v_linea IN
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta, x.cantidad
    FROM jsonb_to_recordset(v_items) x(id_producto bigint, cantidad numeric)
    JOIN public.productos p
      ON p.id_empresa = v_empresa AND p.id_producto = x.id_producto
    ORDER BY p.id_producto
  LOOP
    SELECT COALESCE(sum(f.cantidad_disponible), 0)
    INTO v_pendiente
    FROM public.capas_inventario_fifo f
    WHERE f.id_empresa = v_empresa AND f.id_sucursal = p_id_sucursal
      AND f.id_ubicacion = p_id_ubicacion AND f.id_producto = v_linea.id_producto;
    IF v_pendiente < v_linea.cantidad THEN
      RAISE EXCEPTION 'Existencias insuficientes para % (disponible %, solicitado %).',
        v_linea.sku, v_pendiente, v_linea.cantidad;
    END IF;
    v_subtotal := v_subtotal + round(v_linea.cantidad * v_linea.precio_venta, 2);
  END LOOP;

  SELECT COALESCE(sum(s.saldo_pendiente), 0)::numeric(14,2)
  INTO v_credito_usado
  FROM public.saldos_cuentas_por_cobrar s
  WHERE s.id_empresa = v_empresa AND s.id_cliente = p_id_cliente;
  IF v_credito_usado + v_subtotal > v_limite THEN
    RAISE EXCEPTION 'La factura excede el cupo disponible. Cupo %, utilizado %, factura %.',
      v_limite, v_credito_usado, v_subtotal;
  END IF;

  SELECT c.id_cuenta INTO v_id_cuenta_cxc
  FROM public.cuentas_contables c
  WHERE c.id_empresa = v_empresa AND c.codigo = '1.1.05'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
  SELECT c.id_cuenta INTO v_id_cuenta_ingreso
  FROM public.cuentas_contables c
  WHERE c.id_empresa = v_empresa AND c.codigo = '4.1.01'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
  SELECT c.id_cuenta INTO v_id_cuenta_costo
  FROM public.cuentas_contables c
  WHERE c.id_empresa = v_empresa AND c.codigo = '5.1.01'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
  SELECT c.id_cuenta INTO v_id_cuenta_inventario
  FROM public.cuentas_contables c
  WHERE c.id_empresa = v_empresa AND c.codigo = '1.1.06'
    AND c.activa AND NOT c.es_grupo AND c.permite_movimientos;
  IF v_id_cuenta_cxc IS NULL OR v_id_cuenta_ingreso IS NULL
     OR v_id_cuenta_costo IS NULL OR v_id_cuenta_inventario IS NULL THEN
    RAISE EXCEPTION 'Falta configurar cuentas contables para crédito, ingresos, costo o inventario.';
  END IF;

  INSERT INTO public.ventas (
    id_empresa, id_sucursal, id_caja, id_sesion, id_cliente,
    fecha_operativa, registrada_en, metodo_pago, subtotal, impuesto, total,
    efectivo_recibido, cambio, costo_total_fifo, idempotencia_key,
    huella_solicitud, registrada_por
  )
  VALUES (
    v_empresa, p_id_sucursal, NULL, NULL, p_id_cliente,
    v_fecha, v_ahora, 'CREDITO', v_subtotal, 0, v_subtotal,
    NULL, NULL, 0, 'FCE-' || md5(v_clave), v_huella, v_usuario
  )
  RETURNING id_venta INTO v_id_venta;

  v_subtotal := 0;
  FOR v_linea IN
    SELECT p.id_producto, p.sku, p.nombre, p.precio_venta, x.cantidad
    FROM jsonb_to_recordset(v_items) x(id_producto bigint, cantidad numeric)
    JOIN public.productos p
      ON p.id_empresa = v_empresa AND p.id_producto = x.id_producto
    ORDER BY p.id_producto
  LOOP
    v_numero := v_numero + 1;
    v_id_detalle := NULL;
    v_costo_linea := 0;
    INSERT INTO public.detalle_ventas (
      id_empresa, id_venta, id_producto, numero_linea, sku_snapshot,
      nombre_snapshot, cantidad, precio_unitario, subtotal_linea, costo_fifo
    )
    VALUES (
      v_empresa, v_id_venta, v_linea.id_producto, v_numero,
      v_linea.sku, v_linea.nombre, v_linea.cantidad, v_linea.precio_venta,
      round(v_linea.cantidad * v_linea.precio_venta, 2), 0
    )
    RETURNING id_detalle INTO v_id_detalle;

    v_pendiente := v_linea.cantidad;
    FOR v_capa IN
      SELECT f.id_capa, f.cantidad_disponible, f.costo_unitario
      FROM public.capas_inventario_fifo f
      WHERE f.id_empresa = v_empresa AND f.id_sucursal = p_id_sucursal
        AND f.id_ubicacion = p_id_ubicacion
        AND f.id_producto = v_linea.id_producto AND f.cantidad_disponible > 0
      ORDER BY f.recibido_en, f.id_capa
      FOR UPDATE OF f
    LOOP
      EXIT WHEN v_pendiente = 0;
      v_consumo := LEAST(v_pendiente, v_capa.cantidad_disponible);
      v_costo_unitario := v_capa.costo_unitario;
      v_costo_linea := v_costo_linea + round(v_consumo * v_costo_unitario, 2);
      v_pendiente := v_pendiente - v_consumo;

      UPDATE public.capas_inventario_fifo
      SET cantidad_disponible = cantidad_disponible - v_consumo
      WHERE id_capa = v_capa.id_capa;
      INSERT INTO public.consumos_fifo_venta (
        id_empresa, id_venta, id_detalle, id_capa, cantidad,
        costo_unitario, costo_total
      )
      VALUES (
        v_empresa, v_id_venta, v_id_detalle, v_capa.id_capa, v_consumo,
        v_costo_unitario, round(v_consumo * v_costo_unitario, 2)
      );
    END LOOP;
    IF v_pendiente <> 0 OR v_costo_linea <= 0 THEN
      RAISE EXCEPTION 'No fue posible asignar un costo FIFO positivo completo para %.',
        v_linea.sku;
    END IF;

    v_costo_linea := round(v_costo_linea, 2);
    UPDATE public.detalle_ventas
    SET costo_fifo = v_costo_linea
    WHERE id_empresa = v_empresa AND id_venta = v_id_venta
      AND id_detalle = v_id_detalle;
    INSERT INTO public.movimientos_inventario (
      id_empresa, id_sucursal, id_bodega, id_ubicacion, id_producto,
      tipo, cantidad_delta, costo_total, descripcion, fecha_operativa,
      registrado_en, registrado_por, origen_tipo, origen_id
    )
    VALUES (
      v_empresa, p_id_sucursal, v_id_bodega, p_id_ubicacion,
      v_linea.id_producto, 'VENTA', -v_linea.cantidad, v_costo_linea,
      'Salida por factura empresarial', v_fecha, v_ahora, v_usuario,
      'FACTURA_CREDITO_EMPRESA', v_id_venta::text
    );
    v_subtotal := v_subtotal
      + round(v_linea.cantidad * v_linea.precio_venta, 2);
    v_costo_total := v_costo_total + v_costo_linea;
  END LOOP;

  v_id_comprobante := public._registrar_asiento_operativo(
    v_empresa, p_id_sucursal, v_fecha, 'VENTA',
    'Factura empresarial de crédito V-' || v_id_venta::text,
    'FACTURA_CREDITO_EMPRESA', v_id_venta::text,
    jsonb_build_array(
      jsonb_build_object('id_cuenta', v_id_cuenta_cxc, 'debe', v_subtotal, 'haber', 0,
        'descripcion', 'Cuenta por cobrar a cliente empresarial'),
      jsonb_build_object('id_cuenta', v_id_cuenta_ingreso, 'debe', 0, 'haber', v_subtotal,
        'descripcion', 'Ingreso por venta empresarial'),
      jsonb_build_object('id_cuenta', v_id_cuenta_costo, 'debe', v_costo_total, 'haber', 0,
        'descripcion', 'Costo FIFO de venta empresarial'),
      jsonb_build_object('id_cuenta', v_id_cuenta_inventario, 'debe', 0, 'haber', v_costo_total,
        'descripcion', 'Salida de inventario empresarial')
    )
  );

  INSERT INTO public.facturas_credito_empresa (
    id_empresa, id_venta, id_cliente, fecha_emision, fecha_vencimiento,
    total, clave_idempotencia, huella_solicitud, id_comprobante, creada_por
  )
  VALUES (
    v_empresa, v_id_venta, p_id_cliente, v_fecha,
    v_fecha + v_plazo, v_subtotal, v_clave, v_huella,
    v_id_comprobante, v_usuario
  )
  RETURNING id_factura INTO v_id_factura;

  UPDATE public.ventas
  SET id_comprobante = v_id_comprobante,
      costo_total_fifo = v_costo_total
  WHERE id_empresa = v_empresa AND id_venta = v_id_venta;

  RETURN v_id_factura;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_cobro_factura_empresa(
  p_metodo_pago text,
  p_asignaciones jsonb,
  p_clave_idempotencia text,
  p_id_sesion bigint DEFAULT NULL,
  p_referencia text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_zona text;
  v_fecha date;
  v_ahora timestamptz := clock_timestamp();
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
  v_asignaciones jsonb;
  v_huella text;
  v_existente bigint;
  v_huella_existente text;
  v_id_cobro bigint;
  v_id_comprobante bigint;
  v_id_periodo bigint;
  v_id_cuenta_cxc bigint;
  v_id_cuenta_pago bigint;
  v_total numeric(14,2) := 0;
  v_linea integer := 0;
  v_item record;
  v_sesion record;
BEGIN
  IF v_usuario IS NULL THEN RAISE EXCEPTION 'Debes iniciar sesión.'; END IF;
  IF p_metodo_pago IS NULL OR p_metodo_pago NOT IN ('EFECTIVO', 'TRANSFERENCIA') THEN
    RAISE EXCEPTION 'El método de cobro no es válido.';
  END IF;
  IF char_length(v_clave) NOT BETWEEN 1 AND 128
     OR char_length(COALESCE(trim(p_referencia), '')) > 120 THEN
    RAISE EXCEPTION 'La clave de idempotencia o referencia no es válida.';
  END IF;
  IF jsonb_typeof(p_asignaciones) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_asignaciones) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'El cobro debe aplicarse a entre 1 y 100 facturas.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_asignaciones)
      x(id_factura bigint, monto numeric)
    WHERE x.id_factura IS NULL OR x.monto IS NULL OR x.monto <= 0
       OR x.monto <> round(x.monto, 2)
  ) OR EXISTS (
    SELECT id_factura FROM jsonb_to_recordset(p_asignaciones)
      x(id_factura bigint, monto numeric)
    GROUP BY id_factura HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Cada factura debe tener un monto positivo y no repetirse.';
  END IF;
  SELECT jsonb_agg(jsonb_build_object(
    'id_factura', x.id_factura, 'monto', x.monto
  ) ORDER BY x.id_factura), COALESCE(sum(x.monto), 0)::numeric(14,2)
  INTO v_asignaciones, v_total
  FROM jsonb_to_recordset(p_asignaciones) x(id_factura bigint, monto numeric);
  v_huella := md5(p_metodo_pago || '|' || v_asignaciones::text || '|'
    || COALESCE(p_id_sesion::text, '') || '|' || COALESCE(trim(p_referencia), ''));

  SELECT c.id_empresa, c.id_sucursal, e.zona_horaria
  INTO v_empresa, v_sucursal, v_zona
  FROM public.facturas_credito_empresa f
  JOIN public.ventas v ON v.id_empresa = f.id_empresa AND v.id_venta = f.id_venta
  JOIN public.empresa e ON e.id_empresa = f.id_empresa AND e.activa
  JOIN jsonb_to_recordset(v_asignaciones) x(id_factura bigint, monto numeric)
    ON x.id_factura = f.id_factura
  ORDER BY f.id_factura LIMIT 1;
  IF v_empresa IS NULL THEN RAISE EXCEPTION 'No se encontró una factura válida.'; END IF;
  IF NOT (SELECT public.puede_administrar_empresa(v_empresa)) THEN
    RAISE EXCEPTION 'Solo un administrador puede registrar cobros empresariales.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.facturas_credito_empresa f
    JOIN public.ventas v ON v.id_empresa = f.id_empresa AND v.id_venta = f.id_venta
    JOIN jsonb_to_recordset(v_asignaciones) x(id_factura bigint, monto numeric)
      ON x.id_factura = f.id_factura
    WHERE f.id_empresa <> v_empresa OR v.id_sucursal <> v_sucursal
  ) THEN
    RAISE EXCEPTION 'Un cobro solo puede aplicar facturas de la misma empresa y sucursal.';
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('CFE:' || v_empresa::text || ':' || v_clave, 0)
  );
  SELECT c.id_cobro, c.huella_solicitud INTO v_existente, v_huella_existente
  FROM public.cobros_factura_empresa c
  WHERE c.id_empresa = v_empresa AND c.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_huella_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó con datos distintos.';
    END IF;
    RETURN v_existente;
  END IF;

  PERFORM f.id_factura
  FROM public.facturas_credito_empresa f
  JOIN jsonb_to_recordset(v_asignaciones) x(id_factura bigint, monto numeric)
    ON x.id_factura = f.id_factura
  WHERE f.id_empresa = v_empresa
  ORDER BY f.id_factura
  FOR UPDATE OF f;

  FOR v_item IN
    SELECT f.id_factura, f.total, v.id_cliente,
           COALESCE(sum(a.monto), 0)::numeric(14,2) AS cobrado,
           x.monto AS aplicar
    FROM jsonb_to_recordset(v_asignaciones) x(id_factura bigint, monto numeric)
    JOIN public.facturas_credito_empresa f
      ON f.id_empresa = v_empresa AND f.id_factura = x.id_factura
    JOIN public.ventas v ON v.id_empresa = f.id_empresa AND v.id_venta = f.id_venta
    LEFT JOIN public.aplicaciones_cobro_factura_empresa a
      ON a.id_empresa = f.id_empresa AND a.id_factura = f.id_factura
    GROUP BY f.id_factura, f.total, v.id_cliente, x.monto
    ORDER BY f.id_factura
  LOOP
    IF v_item.cobrado + v_item.aplicar > v_item.total THEN
      RAISE EXCEPTION 'El cobro excede el saldo pendiente de la factura %.',
        v_item.id_factura;
    END IF;
  END LOOP;
  IF (SELECT count(*) FROM jsonb_to_recordset(v_asignaciones)
        x(id_factura bigint, monto numeric))
     <> (SELECT count(*) FROM public.facturas_credito_empresa f
        JOIN jsonb_to_recordset(v_asignaciones) x(id_factura bigint, monto numeric)
          ON x.id_factura = f.id_factura
        WHERE f.id_empresa = v_empresa) THEN
    RAISE EXCEPTION 'Una o más facturas no pertenecen a la empresa.';
  END IF;

  v_fecha := (v_ahora AT TIME ZONE v_zona)::date;
  SELECT pc.id_periodo INTO v_id_periodo
  FROM public.periodos_contables pc
  WHERE pc.id_empresa = v_empresa AND pc.estado = 'ABIERTO'
    AND v_fecha BETWEEN pc.fecha_inicio AND pc.fecha_fin
  FOR SHARE;
  IF v_id_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha del cobro.';
  END IF;
  IF p_metodo_pago = 'EFECTIVO' THEN
    SELECT sc.id_empresa, sc.id_sucursal, sc.id_caja, sc.estado, sc.zona_horaria
    INTO v_sesion
    FROM public.sesiones_caja sc
    WHERE sc.id_sesion = p_id_sesion
    FOR UPDATE;
    IF v_sesion.id_empresa IS DISTINCT FROM v_empresa
       OR v_sesion.id_sucursal IS DISTINCT FROM v_sucursal
       OR v_sesion.estado IS DISTINCT FROM 'ABIERTA'
       OR NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, false)) THEN
      RAISE EXCEPTION 'El cobro en efectivo requiere una sesión abierta autorizada de la sucursal.';
    END IF;
  ELSIF p_id_sesion IS NOT NULL THEN
    RAISE EXCEPTION 'No se debe asociar una sesión de caja a un cobro por transferencia.';
  END IF;

  SELECT id_cuenta INTO v_id_cuenta_cxc
  FROM public.cuentas_contables
  WHERE id_empresa = v_empresa AND codigo = '1.1.05'
    AND activa AND NOT es_grupo AND permite_movimientos;
  SELECT id_cuenta INTO v_id_cuenta_pago
  FROM public.cuentas_contables
  WHERE id_empresa = v_empresa
    AND codigo = CASE p_metodo_pago WHEN 'EFECTIVO' THEN '1.1.02' ELSE '1.1.04' END
    AND activa AND NOT es_grupo AND permite_movimientos;
  IF v_id_cuenta_cxc IS NULL OR v_id_cuenta_pago IS NULL THEN
    RAISE EXCEPTION 'Falta configurar la cuenta de cuentas por cobrar o del medio de cobro.';
  END IF;

  v_id_cobro := nextval(
    pg_get_serial_sequence('public.cobros_factura_empresa', 'id_cobro')::regclass
  );
  v_id_comprobante := public._registrar_asiento_operativo(
    v_empresa, v_sucursal, v_fecha, 'PAGO',
    'Cobro empresarial CE-' || v_id_cobro::text,
    'COBRO_FACTURA_EMPRESA', v_clave,
    jsonb_build_array(
      jsonb_build_object('id_cuenta', v_id_cuenta_pago, 'debe', v_total, 'haber', 0,
        'descripcion', 'Cobro empresarial por ' || p_metodo_pago),
      jsonb_build_object('id_cuenta', v_id_cuenta_cxc, 'debe', 0, 'haber', v_total,
        'descripcion', 'Aplicación a cuentas por cobrar')
    )
  );
  INSERT INTO public.cobros_factura_empresa (
    id_cobro, id_empresa, id_sucursal, id_caja, id_sesion, metodo_pago, referencia,
    fecha_operativa, monto, clave_idempotencia, huella_solicitud,
    id_comprobante, registrado_por
  )
  VALUES (
    v_id_cobro, v_empresa, v_sucursal,
    CASE WHEN p_metodo_pago = 'EFECTIVO' THEN v_sesion.id_caja END,
    p_id_sesion, p_metodo_pago,
    NULLIF(trim(p_referencia), ''), v_fecha, v_total, v_clave, v_huella,
    v_id_comprobante, v_usuario
  );

  INSERT INTO public.aplicaciones_cobro_factura_empresa (
    id_empresa, id_cobro, id_factura, monto
  )
  SELECT v_empresa, v_id_cobro, x.id_factura, x.monto
  FROM jsonb_to_recordset(v_asignaciones) x(id_factura bigint, monto numeric);

  IF p_metodo_pago = 'EFECTIVO' THEN
    INSERT INTO public.movimientos_caja (
      id_empresa, id_sucursal, id_caja, id_sesion, tipo, monto,
      descripcion, fecha_operativa, registrado_en, registrado_por,
      origen_tipo, origen_id, idempotencia_key
    )
    VALUES (
      v_empresa, v_sucursal, v_sesion.id_caja, p_id_sesion, 'INGRESO',
      v_total, 'Cobro factura empresarial CE-' || v_id_cobro,
      v_fecha, v_ahora, v_usuario, 'COBRO_FACTURA_EMPRESA',
      v_id_cobro::text, 'COBRO_EMPRESA:' || v_id_cobro::text
    );
  END IF;
  RETURN v_id_cobro;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_pago_proveedor(
  p_metodo_pago text,
  p_asignaciones jsonb,
  p_clave_idempotencia text,
  p_id_sesion bigint DEFAULT NULL,
  p_referencia text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_zona text;
  v_fecha date;
  v_ahora timestamptz := clock_timestamp();
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
  v_asignaciones jsonb;
  v_huella text;
  v_existente bigint;
  v_huella_existente text;
  v_id_pago bigint;
  v_id_comprobante bigint;
  v_id_periodo bigint;
  v_id_cuenta_ap bigint;
  v_id_cuenta_pago bigint;
  v_total numeric(14,2) := 0;
  v_item record;
  v_sesion record;
BEGIN
  IF v_usuario IS NULL THEN RAISE EXCEPTION 'Debes iniciar sesión.'; END IF;
  IF p_metodo_pago IS NULL OR p_metodo_pago NOT IN ('EFECTIVO', 'TRANSFERENCIA') THEN
    RAISE EXCEPTION 'El método de pago no es válido.';
  END IF;
  IF char_length(v_clave) NOT BETWEEN 1 AND 128
     OR char_length(COALESCE(trim(p_referencia), '')) > 120 THEN
    RAISE EXCEPTION 'La clave de idempotencia o referencia no es válida.';
  END IF;
  IF jsonb_typeof(p_asignaciones) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_asignaciones) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'El pago debe aplicarse a entre 1 y 100 cuentas por pagar.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(p_asignaciones)
      x(id_cuenta_por_pagar bigint, monto numeric)
    WHERE x.id_cuenta_por_pagar IS NULL OR x.monto IS NULL
       OR x.monto <= 0 OR x.monto <> round(x.monto, 2)
  ) OR EXISTS (
    SELECT id_cuenta_por_pagar
    FROM jsonb_to_recordset(p_asignaciones)
      x(id_cuenta_por_pagar bigint, monto numeric)
    GROUP BY id_cuenta_por_pagar HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Cada cuenta por pagar debe tener un monto positivo y no repetirse.';
  END IF;
  SELECT jsonb_agg(jsonb_build_object(
    'id_cuenta_por_pagar', x.id_cuenta_por_pagar, 'monto', x.monto
  ) ORDER BY x.id_cuenta_por_pagar), COALESCE(sum(x.monto), 0)::numeric(14,2)
  INTO v_asignaciones, v_total
  FROM jsonb_to_recordset(p_asignaciones)
    x(id_cuenta_por_pagar bigint, monto numeric);
  v_huella := md5(p_metodo_pago || '|' || v_asignaciones::text || '|'
    || COALESCE(p_id_sesion::text, '') || '|' || COALESCE(trim(p_referencia), ''));

  SELECT c.id_empresa, c.id_sucursal, e.zona_horaria
  INTO v_empresa, v_sucursal, v_zona
  FROM public.cuentas_por_pagar c
  JOIN public.empresa e ON e.id_empresa = c.id_empresa AND e.activa
  JOIN jsonb_to_recordset(v_asignaciones)
    x(id_cuenta_por_pagar bigint, monto numeric)
    ON x.id_cuenta_por_pagar = c.id_cuenta_por_pagar
  ORDER BY c.id_cuenta_por_pagar LIMIT 1;
  IF v_empresa IS NULL THEN RAISE EXCEPTION 'No se encontró una cuenta por pagar válida.'; END IF;
  IF NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, true)) THEN
    RAISE EXCEPTION 'Solo un administrador puede registrar pagos a proveedores.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.cuentas_por_pagar c
    JOIN jsonb_to_recordset(v_asignaciones)
      x(id_cuenta_por_pagar bigint, monto numeric)
      ON x.id_cuenta_por_pagar = c.id_cuenta_por_pagar
    WHERE c.id_empresa <> v_empresa OR c.id_sucursal <> v_sucursal
  ) THEN
    RAISE EXCEPTION 'Un pago solo puede aplicar cuentas por pagar de la misma sucursal.';
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('PPR:' || v_empresa::text || ':' || v_clave, 0)
  );
  SELECT p.id_pago_proveedor, p.huella_solicitud
  INTO v_existente, v_huella_existente
  FROM public.pagos_proveedor p
  WHERE p.id_empresa = v_empresa AND p.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_huella_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó con datos distintos.';
    END IF;
    RETURN v_existente;
  END IF;

  PERFORM c.id_cuenta_por_pagar
  FROM public.cuentas_por_pagar c
  JOIN jsonb_to_recordset(v_asignaciones)
    x(id_cuenta_por_pagar bigint, monto numeric)
    ON x.id_cuenta_por_pagar = c.id_cuenta_por_pagar
  WHERE c.id_empresa = v_empresa
  ORDER BY c.id_cuenta_por_pagar
  FOR UPDATE OF c;

  FOR v_item IN
    SELECT c.id_cuenta_por_pagar, c.total,
           COALESCE(sum(a.monto), 0)::numeric(14,2) AS pagado,
           x.monto AS aplicar
    FROM jsonb_to_recordset(v_asignaciones)
      x(id_cuenta_por_pagar bigint, monto numeric)
    JOIN public.cuentas_por_pagar c
      ON c.id_empresa = v_empresa
     AND c.id_cuenta_por_pagar = x.id_cuenta_por_pagar
    LEFT JOIN public.aplicaciones_pago_proveedor a
      ON a.id_empresa = c.id_empresa
     AND a.id_cuenta_por_pagar = c.id_cuenta_por_pagar
    GROUP BY c.id_cuenta_por_pagar, c.total, x.monto
    ORDER BY c.id_cuenta_por_pagar
  LOOP
    IF v_item.pagado + v_item.aplicar > v_item.total THEN
      RAISE EXCEPTION 'El pago excede el saldo pendiente de la cuenta %.',
        v_item.id_cuenta_por_pagar;
    END IF;
  END LOOP;
  IF (SELECT count(*) FROM jsonb_to_recordset(v_asignaciones)
        x(id_cuenta_por_pagar bigint, monto numeric))
     <> (SELECT count(*) FROM public.cuentas_por_pagar c
        JOIN jsonb_to_recordset(v_asignaciones)
          x(id_cuenta_por_pagar bigint, monto numeric)
          ON x.id_cuenta_por_pagar = c.id_cuenta_por_pagar
        WHERE c.id_empresa = v_empresa) THEN
    RAISE EXCEPTION 'Una o más cuentas por pagar no pertenecen a la empresa.';
  END IF;

  v_fecha := (v_ahora AT TIME ZONE v_zona)::date;
  SELECT pc.id_periodo INTO v_id_periodo
  FROM public.periodos_contables pc
  WHERE pc.id_empresa = v_empresa AND pc.estado = 'ABIERTO'
    AND v_fecha BETWEEN pc.fecha_inicio AND pc.fecha_fin
  FOR SHARE;
  IF v_id_periodo IS NULL THEN
    RAISE EXCEPTION 'No hay un período contable abierto para la fecha del pago.';
  END IF;
  IF p_metodo_pago = 'EFECTIVO' THEN
    SELECT sc.id_empresa, sc.id_sucursal, sc.id_caja, sc.estado, sc.zona_horaria
    INTO v_sesion
    FROM public.sesiones_caja sc
    WHERE sc.id_sesion = p_id_sesion
    FOR UPDATE;
    IF v_sesion.id_empresa IS DISTINCT FROM v_empresa
       OR v_sesion.id_sucursal IS DISTINCT FROM v_sucursal
       OR v_sesion.estado IS DISTINCT FROM 'ABIERTA'
       OR NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, true)) THEN
      RAISE EXCEPTION 'El pago en efectivo requiere una sesión abierta autorizada de la sucursal.';
    END IF;
  ELSIF p_id_sesion IS NOT NULL THEN
    RAISE EXCEPTION 'No se debe asociar una sesión de caja a un pago por transferencia.';
  END IF;

  SELECT id_cuenta INTO v_id_cuenta_ap
  FROM public.cuentas_contables
  WHERE id_empresa = v_empresa AND codigo = '2.1.01'
    AND activa AND NOT es_grupo AND permite_movimientos;
  SELECT id_cuenta INTO v_id_cuenta_pago
  FROM public.cuentas_contables
  WHERE id_empresa = v_empresa
    AND codigo = CASE p_metodo_pago WHEN 'EFECTIVO' THEN '1.1.02' ELSE '1.1.04' END
    AND activa AND NOT es_grupo AND permite_movimientos;
  IF v_id_cuenta_ap IS NULL OR v_id_cuenta_pago IS NULL THEN
    RAISE EXCEPTION 'Falta configurar la cuenta de proveedores por pagar o del medio de pago.';
  END IF;

  v_id_pago := nextval(
    pg_get_serial_sequence('public.pagos_proveedor', 'id_pago_proveedor')::regclass
  );
  v_id_comprobante := public._registrar_asiento_operativo(
    v_empresa, v_sucursal, v_fecha, 'PAGO',
    'Pago a proveedor PP-' || v_id_pago::text,
    'PAGO_PROVEEDOR', v_clave,
    jsonb_build_array(
      jsonb_build_object('id_cuenta', v_id_cuenta_ap, 'debe', v_total, 'haber', 0,
        'descripcion', 'Abono a proveedores por pagar'),
      jsonb_build_object('id_cuenta', v_id_cuenta_pago, 'debe', 0, 'haber', v_total,
        'descripcion', 'Pago a proveedor por ' || p_metodo_pago)
    )
  );
  INSERT INTO public.pagos_proveedor (
    id_pago_proveedor, id_empresa, id_sucursal, id_caja, id_sesion, metodo_pago,
    referencia, fecha_operativa, monto, clave_idempotencia, huella_solicitud,
    id_comprobante, registrado_por
  )
  VALUES (
    v_id_pago, v_empresa, v_sucursal,
    CASE WHEN p_metodo_pago = 'EFECTIVO' THEN v_sesion.id_caja END,
    p_id_sesion, p_metodo_pago,
    NULLIF(trim(p_referencia), ''), v_fecha, v_total, v_clave, v_huella,
    v_id_comprobante, v_usuario
  );

  INSERT INTO public.aplicaciones_pago_proveedor (
    id_empresa, id_pago_proveedor, id_cuenta_por_pagar, monto
  )
  SELECT v_empresa, v_id_pago, x.id_cuenta_por_pagar, x.monto
  FROM jsonb_to_recordset(v_asignaciones)
    x(id_cuenta_por_pagar bigint, monto numeric);

  IF p_metodo_pago = 'EFECTIVO' THEN
    INSERT INTO public.movimientos_caja (
      id_empresa, id_sucursal, id_caja, id_sesion, tipo, monto,
      descripcion, fecha_operativa, registrado_en, registrado_por,
      origen_tipo, origen_id, idempotencia_key
    )
    VALUES (
      v_empresa, v_sucursal, v_sesion.id_caja, p_id_sesion, 'RETIRO',
      v_total, 'Pago a proveedor PP-' || v_id_pago,
      v_fecha, v_ahora, v_usuario, 'PAGO_PROVEEDOR',
      v_id_pago::text, 'PAGO_PROVEEDOR:' || v_id_pago::text
    );
  END IF;
  RETURN v_id_pago;
END;
$$;

CREATE OR REPLACE FUNCTION public.crear_cxp_desde_recepcion()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_proveedor bigint;
  v_dias integer;
BEGIN
  SELECT o.id_proveedor, p.plazo_credito_dias
  INTO v_proveedor, v_dias
  FROM public.ordenes_compra o
  JOIN public.proveedores p
    ON p.id_empresa = o.id_empresa AND p.id_proveedor = o.id_proveedor
  WHERE o.id_empresa = NEW.id_empresa
    AND o.id_orden_compra = NEW.id_orden_compra;
  IF v_proveedor IS NULL THEN
    RAISE EXCEPTION 'No se pudo identificar al proveedor de la recepción.';
  END IF;
  INSERT INTO public.cuentas_por_pagar (
    id_empresa, id_proveedor, id_recepcion, id_sucursal,
    documento_referencia,
    fecha_emision, fecha_vencimiento, total, id_comprobante
  )
  VALUES (
    NEW.id_empresa, v_proveedor, NEW.id_recepcion, NEW.id_sucursal,
    NEW.documento_proveedor,
    NEW.fecha_operativa, NEW.fecha_operativa + v_dias,
    NEW.subtotal, NEW.id_comprobante
  );
  RETURN NEW;
END;
$$;

