CREATE OR REPLACE FUNCTION public.marcar_linea_conciliada(
  p_id_linea bigint,
  p_conciliado boolean,
  p_fecha_conciliacion date DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_fecha_linea date;
  v_estado text;
  v_es_banco boolean;
BEGIN
  IF v_usuario IS NULL OR p_conciliado IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión y seleccionar el estado de conciliación.';
  END IF;

  SELECT l.id_empresa, c.id_sucursal, c.fecha, c.estado, cc.es_banco
  INTO v_empresa, v_sucursal, v_fecha_linea, v_estado, v_es_banco
  FROM public.lineas_comprobante_contable AS l
  JOIN public.comprobantes_contables AS c
    ON c.id_empresa = l.id_empresa
   AND c.id_comprobante = l.id_comprobante
  JOIN public.cuentas_contables AS cc
    ON cc.id_empresa = l.id_empresa
   AND cc.id_cuenta = l.id_cuenta
  WHERE l.id_linea = p_id_linea
  FOR UPDATE OF l;

  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'La línea contable no existe.';
  END IF;
  IF NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, true)) THEN
    RAISE EXCEPTION 'No tienes permiso para conciliar movimientos de esta sucursal.';
  END IF;
  IF v_estado <> 'CONTABILIZADO' OR NOT v_es_banco THEN
    RAISE EXCEPTION 'Solo se pueden conciliar líneas contabilizadas de cuentas bancarias.';
  END IF;
  IF p_conciliado AND p_fecha_conciliacion IS NULL THEN
    RAISE EXCEPTION 'Indica la fecha de conciliación.';
  END IF;
  IF p_conciliado AND p_fecha_conciliacion < v_fecha_linea THEN
    RAISE EXCEPTION 'La fecha de conciliación no puede preceder la fecha del movimiento.';
  END IF;

  UPDATE public.lineas_comprobante_contable
  SET conciliado = p_conciliado,
      fecha_conciliacion = CASE WHEN p_conciliado THEN p_fecha_conciliacion END,
      conciliado_por = CASE WHEN p_conciliado THEN v_usuario END
  WHERE id_empresa = v_empresa
    AND id_linea = p_id_linea;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_prestamo(
  p_id_empresa integer,
  p_id_sucursal integer,
  p_descripcion text,
  p_monto_principal numeric,
  p_tasa_interes_anual numeric,
  p_plazo_meses integer,
  p_fecha_desembolso date,
  p_id_cuenta_banco bigint,
  p_id_cuenta_pasivo bigint,
  p_id_cuenta_gasto bigint,
  p_clave_idempotencia text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
  v_huella text;
  v_existente bigint;
  v_huella_existente text;
  v_tasa_mensual numeric;
  v_cuota numeric(14,2);
  v_id_prestamo bigint;
  v_id_comprobante bigint;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión.';
  END IF;
  IF char_length(v_clave) NOT BETWEEN 1 AND 128
     OR char_length(COALESCE(trim(p_descripcion), '')) = 0
     OR p_monto_principal IS NULL OR p_monto_principal <= 0
     OR p_monto_principal <> round(p_monto_principal, 2)
     OR p_tasa_interes_anual IS NULL OR p_tasa_interes_anual NOT BETWEEN 0 AND 100
     OR p_tasa_interes_anual <> round(p_tasa_interes_anual, 4)
     OR p_plazo_meses IS NULL OR p_plazo_meses NOT BETWEEN 1 AND 600
     OR p_fecha_desembolso IS NULL THEN
    RAISE EXCEPTION 'Los datos del préstamo no son válidos.';
  END IF;
  IF NOT (SELECT public.puede_operar_caja(p_id_empresa, p_id_sucursal, true)) THEN
    RAISE EXCEPTION 'No tienes permiso para registrar préstamos en esta sucursal.';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.sucursales AS s
    WHERE s.id_empresa = p_id_empresa
      AND s.id_sucursal = p_id_sucursal
      AND s.activa
  ) THEN
    RAISE EXCEPTION 'La sucursal no existe, está inactiva o no pertenece a la empresa.';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('PR:' || p_id_empresa::text || ':' || v_clave, 0)
  );
  v_huella := md5(
    p_id_empresa::text || '|' || p_id_sucursal::text || '|' ||
    trim(p_descripcion) || '|' || p_monto_principal::text || '|' ||
    p_tasa_interes_anual::text || '|' || p_plazo_meses::text || '|' ||
    p_fecha_desembolso::text || '|' || p_id_cuenta_banco::text || '|' ||
    p_id_cuenta_pasivo::text || '|' || p_id_cuenta_gasto::text
  );
  SELECT p.id_prestamo, p.huella_solicitud
  INTO v_existente, v_huella_existente
  FROM public.prestamos AS p
  WHERE p.id_empresa = p_id_empresa
    AND p.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_huella_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó para otro préstamo.';
    END IF;
    RETURN v_existente;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.cuentas_contables AS c
    WHERE c.id_empresa = p_id_empresa
      AND c.id_cuenta IN (p_id_cuenta_banco, p_id_cuenta_pasivo, p_id_cuenta_gasto)
      AND (NOT c.activa OR c.es_grupo OR NOT c.permite_movimientos)
  ) OR (
    SELECT count(*)
    FROM public.cuentas_contables AS c
    WHERE c.id_empresa = p_id_empresa
      AND c.id_cuenta IN (p_id_cuenta_banco, p_id_cuenta_pasivo, p_id_cuenta_gasto)
      AND c.activa AND NOT c.es_grupo AND c.permite_movimientos
  ) <> 3 THEN
    RAISE EXCEPTION 'Selecciona tres cuentas activas de detalle de esta empresa.';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.cuentas_contables AS c
    WHERE c.id_empresa = p_id_empresa AND c.id_cuenta = p_id_cuenta_banco
      AND c.es_banco AND c.naturaleza = 'ACTIVO'
  ) OR NOT EXISTS (
    SELECT 1 FROM public.cuentas_contables AS c
    WHERE c.id_empresa = p_id_empresa AND c.id_cuenta = p_id_cuenta_pasivo
      AND c.naturaleza = 'PASIVO'
  ) OR NOT EXISTS (
    SELECT 1 FROM public.cuentas_contables AS c
    WHERE c.id_empresa = p_id_empresa AND c.id_cuenta = p_id_cuenta_gasto
      AND c.naturaleza = 'GASTO'
  ) THEN
    RAISE EXCEPTION 'Asigna una cuenta bancaria, una cuenta de pasivo y una cuenta de gasto válidas.';
  END IF;

  v_tasa_mensual := round(p_tasa_interes_anual, 4) / 1200;
  v_cuota := CASE
    WHEN v_tasa_mensual = 0
      THEN round(p_monto_principal / p_plazo_meses, 2)
    ELSE round(
      p_monto_principal * v_tasa_mensual
      / (1 - pg_catalog.power(1 + v_tasa_mensual, -p_plazo_meses)),
      2
    )
  END;
  IF v_cuota <= round(round(p_monto_principal, 2) * v_tasa_mensual, 2) THEN
    RAISE EXCEPTION 'El monto, la tasa y el plazo generan una cuota que no amortiza el préstamo.';
  END IF;

  INSERT INTO public.prestamos (
    id_empresa, id_sucursal, descripcion, monto_principal, saldo_actual,
    tasa_interes_anual, plazo_meses, monto_cuota_mensual, fecha_desembolso,
    id_cuenta_banco, id_cuenta_pasivo, id_cuenta_gasto, clave_idempotencia,
    huella_solicitud, creado_por
  )
  VALUES (
    p_id_empresa, p_id_sucursal, trim(p_descripcion),
    round(p_monto_principal, 2), round(p_monto_principal, 2),
    p_tasa_interes_anual, p_plazo_meses, v_cuota, p_fecha_desembolso,
    p_id_cuenta_banco, p_id_cuenta_pasivo, p_id_cuenta_gasto,
    v_clave, v_huella, v_usuario
  )
  RETURNING id_prestamo INTO v_id_prestamo;

  v_id_comprobante := public._registrar_asiento_operativo(
    p_id_empresa,
    p_id_sucursal,
    p_fecha_desembolso,
    'MANUAL',
    'Desembolso de préstamo: ' || trim(p_descripcion),
    'PRESTAMO',
    v_id_prestamo::text,
    jsonb_build_array(
      jsonb_build_object('id_cuenta', p_id_cuenta_banco, 'debe', round(p_monto_principal, 2), 'haber', 0),
      jsonb_build_object('id_cuenta', p_id_cuenta_pasivo, 'debe', 0, 'haber', round(p_monto_principal, 2))
    )
  );

  UPDATE public.prestamos
  SET id_comprobante = v_id_comprobante
  WHERE id_empresa = p_id_empresa
    AND id_prestamo = v_id_prestamo;

  RETURN v_id_prestamo;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_pago_prestamo(
  p_id_prestamo bigint,
  p_fecha_pago date,
  p_clave_idempotencia text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario uuid := (SELECT auth.uid());
  v_empresa integer;
  v_sucursal integer;
  v_descripcion text;
  v_saldo numeric(14,2);
  v_tasa_anual numeric(7,4);
  v_plazo integer;
  v_cuota numeric(14,2);
  v_cuenta_banco bigint;
  v_cuenta_pasivo bigint;
  v_cuenta_gasto bigint;
  v_estado text;
  v_numero_cuota integer;
  v_interes numeric(14,2);
  v_principal numeric(14,2);
  v_total numeric(14,2);
  v_nuevo_saldo numeric(14,2);
  v_clave text := trim(COALESCE(p_clave_idempotencia, ''));
  v_huella text;
  v_existente bigint;
  v_huella_existente text;
  v_saldo_existente numeric(14,2);
  v_total_existente numeric(14,2);
  v_principal_existente numeric(14,2);
  v_interes_existente numeric(14,2);
  v_numero_cuota_existente integer;
  v_id_comprobante bigint;
BEGIN
  IF v_usuario IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión.';
  END IF;
  IF p_fecha_pago IS NULL OR char_length(v_clave) NOT BETWEEN 1 AND 128 THEN
    RAISE EXCEPTION 'La fecha y clave de idempotencia son obligatorias.';
  END IF;
  SELECT p.id_empresa, p.id_sucursal, p.descripcion, p.saldo_actual,
         p.tasa_interes_anual, p.plazo_meses, p.monto_cuota_mensual,
         p.id_cuenta_banco, p.id_cuenta_pasivo, p.id_cuenta_gasto, p.estado
  INTO v_empresa, v_sucursal, v_descripcion, v_saldo, v_tasa_anual, v_plazo,
       v_cuota, v_cuenta_banco, v_cuenta_pasivo, v_cuenta_gasto, v_estado
  FROM public.prestamos AS p
  WHERE p.id_prestamo = p_id_prestamo
  FOR UPDATE;
  IF v_empresa IS NULL THEN
    RAISE EXCEPTION 'El préstamo no existe.';
  END IF;
  IF NOT (SELECT public.puede_operar_caja(v_empresa, v_sucursal, true)) THEN
    RAISE EXCEPTION 'No tienes permiso para registrar pagos de este préstamo.';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('PP:' || v_empresa::text || ':' || v_clave, 0)
  );
  v_huella := md5(p_id_prestamo::text || '|' || p_fecha_pago::text);
  SELECT pago.id_pago_prestamo, pago.huella_solicitud, pago.saldo_resultante,
         pago.total, pago.principal, pago.interes, pago.numero_cuota
  INTO v_existente, v_huella_existente, v_saldo_existente, v_total_existente,
       v_principal_existente, v_interes_existente, v_numero_cuota_existente
  FROM public.pagos_prestamo AS pago
  WHERE pago.id_empresa = v_empresa
    AND pago.clave_idempotencia = v_clave;
  IF v_existente IS NOT NULL THEN
    IF v_huella_existente IS DISTINCT FROM v_huella THEN
      RAISE EXCEPTION 'La clave de idempotencia ya se usó para otro pago.';
    END IF;
    RETURN jsonb_build_object(
      'cuota', v_numero_cuota_existente,
      'principal', v_principal_existente,
      'interes', v_interes_existente,
      'total', v_total_existente,
      'saldo', v_saldo_existente
    );
  END IF;
  IF v_estado <> 'ACTIVO' OR v_saldo <= 0 THEN
    RAISE EXCEPTION 'El préstamo ya está pagado.';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.cuentas_contables AS c
    WHERE c.id_empresa = v_empresa
      AND c.id_cuenta = v_cuenta_banco
      AND c.activa
      AND c.es_banco
  ) THEN
    RAISE EXCEPTION 'La cuenta bancaria asociada al préstamo está inactiva o ya no está marcada como banco.';
  END IF;

  SELECT count(*) + 1
  INTO v_numero_cuota
  FROM public.pagos_prestamo AS pago
  WHERE pago.id_empresa = v_empresa
    AND pago.id_prestamo = p_id_prestamo;
  IF v_numero_cuota > v_plazo THEN
    RAISE EXCEPTION 'El préstamo ya alcanzó el número total de cuotas.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.pagos_prestamo AS pago
    WHERE pago.id_empresa = v_empresa
      AND pago.id_prestamo = p_id_prestamo
      AND pago.periodo_pago = date_trunc('month', p_fecha_pago::timestamp)::date
  ) THEN
    RAISE EXCEPTION 'Ya se registró una cuota del préstamo durante ese mes.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM public.pagos_prestamo AS pago
    WHERE pago.id_empresa = v_empresa
      AND pago.id_prestamo = p_id_prestamo
      AND pago.fecha_pago > p_fecha_pago
  ) THEN
    RAISE EXCEPTION 'La fecha del pago no puede preceder un pago ya registrado.';
  END IF;

  v_interes := round(v_saldo * v_tasa_anual / 1200, 2);
  v_principal := CASE
    WHEN v_numero_cuota = v_plazo THEN v_saldo
    ELSE LEAST(v_saldo, round(v_cuota - v_interes, 2))
  END;
  IF v_principal <= 0 THEN
    RAISE EXCEPTION 'La cuota calculada no amortiza el saldo del préstamo.';
  END IF;
  v_total := round(v_principal + v_interes, 2);
  v_nuevo_saldo := round(v_saldo - v_principal, 2);

  v_id_comprobante := public._registrar_asiento_operativo(
    v_empresa,
    v_sucursal,
    p_fecha_pago,
    'MANUAL',
    'Pago de cuota ' || v_numero_cuota || ' del préstamo: ' || v_descripcion,
    'PAGO_PRESTAMO',
    p_id_prestamo::text || ':' || v_numero_cuota::text,
    jsonb_build_array(
      jsonb_build_object('id_cuenta', v_cuenta_pasivo, 'debe', v_principal, 'haber', 0),
      jsonb_build_object('id_cuenta', v_cuenta_gasto, 'debe', v_interes, 'haber', 0),
      jsonb_build_object('id_cuenta', v_cuenta_banco, 'debe', 0, 'haber', v_total)
    )
  );

  INSERT INTO public.pagos_prestamo (
    id_empresa, id_prestamo, numero_cuota, fecha_pago, principal,
    interes, total, saldo_resultante, id_comprobante, clave_idempotencia,
    huella_solicitud, registrado_por
  )
  VALUES (
    v_empresa, p_id_prestamo, v_numero_cuota, p_fecha_pago, v_principal,
    v_interes, v_total, v_nuevo_saldo, v_id_comprobante, v_clave,
    v_huella, v_usuario
  );

  UPDATE public.prestamos
  SET saldo_actual = v_nuevo_saldo,
      estado = CASE WHEN v_nuevo_saldo = 0 THEN 'PAGADO' ELSE 'ACTIVO' END
  WHERE id_empresa = v_empresa
    AND id_prestamo = p_id_prestamo;

  RETURN jsonb_build_object(
    'cuota', v_numero_cuota,
    'principal', v_principal,
    'interes', v_interes,
    'total', v_total,
    'saldo', v_nuevo_saldo
  );
END;
